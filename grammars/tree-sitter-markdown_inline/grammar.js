/**
 * @file Tree-sitter grammar for Markdown's inline content.
 *
 * mep's own grammar, written against CommonMark 0.31 (spec.commonmark.org,
 * §6 Inlines) and GFM 0.29's strikethrough, plus `$` LaTeX spans. Its node
 * names, fields and tree shapes are the ones
 * tree-sitter-grammars/tree-sitter-markdown 0.5's inline grammar
 * established, which mep vendored before (third_party/grammars/
 * markdown_inline), so queries written for it keep working; see README.md.
 *
 * mep parses this grammar over each `inline` node the block grammar
 * (../tree-sitter-markdown) leaves, one range at a time.
 *
 * Emphasis is the hard part (§6.2's delimiter runs): whether a `*` or `_`
 * opens or closes depends on what is before and after it. The grammar tells
 * the scanner about the token before, by making `_last_token_whitespace`
 * and `_last_token_punctuation` (never produced) valid right after
 * whitespace and punctuation; the scanner looks at the character after.
 * Contexts that may not hold a delimiter of one kind (an emphasis's own
 * content, link text, ...) are separate rule families, generated by
 * addInlineRules below.
 *
 * Rules are declared in the old grammar's order, which is load-bearing.
 */

const common = require('../tree-sitter-markdown/common.js');

const PRECEDENCE_LEVEL_EMPHASIS = 1;
const PRECEDENCE_LEVEL_LINK = common.PRECEDENCE_LEVEL_LINK;
const PRECEDENCE_LEVEL_HTML = 100;

const PUNCTUATION_CHARACTERS_REGEX = common.PUNCTUATION_CHARACTERS_REGEX;

module.exports = grammar(addInlineRules({
  name: 'markdown_inline',

  externals: $ => [
    // Never produced on its own: ends a parse branch.
    $._error,
    // Valid where a branch must end: the scanner answers with `_error`.
    $._trigger_error,
    $._code_span_start,
    $._code_span_close,
    $._emphasis_open_star,
    $._emphasis_open_underscore,
    $._emphasis_close_star,
    $._emphasis_close_underscore,
    // Never produced: valid right after whitespace or punctuation, which is
    // how the scanner learns what came before a delimiter run.
    $._last_token_whitespace,
    $._last_token_punctuation,
    $._strikethrough_open,
    $._strikethrough_close,
    $._latex_span_start,
    $._latex_span_close,
    // A run of backticks (or `$`) no run of the same length closes: text.
    $._unclosed_span,
  ],

  precedences: $ => [
    [$._strong_emphasis_star_no_link, $._inline_element_no_star_no_link],
    [$._strong_emphasis_underscore_no_link, $._inline_element_no_underscore_no_link],
    [$.hard_line_break, $._whitespace],
    [$.hard_line_break, $._text_base],
  ],

  // More are added by addInlineRules.
  conflicts: $ => [
    [$._closing_tag, $._text_base],
    [$._open_tag, $._text_base],
    [$._html_comment, $._text_base],
    [$._processing_instruction, $._text_base],
    [$._declaration, $._text_base],
    [$._cdata_section, $._text_base],

    [$._link_text_non_empty, $._inline_element],
    [$._link_text_non_empty, $._inline_element_no_star],
    [$._link_text_non_empty, $._inline_element_no_underscore],
    [$._link_text_non_empty, $._inline_element_no_tilde],
    [$._link_text, $._inline_element],
    [$._link_text, $._inline_element_no_star],
    [$._link_text, $._inline_element_no_underscore],
    [$._link_text, $._inline_element_no_tilde],

    [$._image_description, $._image_description_non_empty, $._text_base],

    [$._image_shortcut_link, $._image_description],
    [$.shortcut_link, $._link_text],
    [$.link_destination, $.link_title],
    [$._link_destination_parenthesis, $.link_title],
  ],

  extras: _ => [],

  rules: {
    inline: $ => seq(optional($._last_token_whitespace), $._inline),

    ...common.rules,

    // §6.1: a run of backticks to the next run of the same length.
    code_span: $ => seq(
      alias($._code_span_start, $.code_span_delimiter),
      repeat(choice($._text_base, '[', ']', $._soft_line_break, $._html_tag)),
      alias($._code_span_close, $.code_span_delimiter),
    ),

    // `$...$`, `$$...$$`: delimited like a code span.
    latex_block: $ => seq(
      alias($._latex_span_start, $.latex_span_delimiter),
      repeat(choice($._text_base, '[', ']', $._soft_line_break, $._html_tag)),
      alias($._latex_span_close, $.latex_span_delimiter),
    ),

    // §6.3: inline, full, collapsed and shortcut links. Dynamic precedence
    // is spread as finely as possible, to let the parser rank the readings
    // as it goes.
    _link_text: $ => prec.dynamic(PRECEDENCE_LEVEL_LINK, choice($._link_text_non_empty, seq('[', ']'))),
    _link_text_non_empty: $ => seq('[', alias($._inline_no_link, $.link_text), ']'),
    shortcut_link: $ => prec.dynamic(PRECEDENCE_LEVEL_LINK, $._link_text_non_empty),
    full_reference_link: $ => prec.dynamic(2 * PRECEDENCE_LEVEL_LINK, seq($._link_text, $.link_label)),
    collapsed_reference_link: $ => prec.dynamic(PRECEDENCE_LEVEL_LINK, seq($._link_text, '[', ']')),
    inline_link: $ => prec.dynamic(PRECEDENCE_LEVEL_LINK, seq(
      $._link_text,
      '(',
      repeat(choice($._whitespace, $._soft_line_break)),
      optional(seq(
        choice(
          seq(
            $.link_destination,
            optional(seq(repeat1(choice($._whitespace, $._soft_line_break)), $.link_title)),
          ),
          $.link_title,
        ),
        repeat(choice($._whitespace, $._soft_line_break)),
      )),
      ')',
    )),

    // §6.4: a link with `!` in front.
    image: $ => choice(
      $._image_inline_link,
      $._image_shortcut_link,
      $._image_full_reference_link,
      $._image_collapsed_reference_link,
    ),
    _image_inline_link: $ => prec.dynamic(PRECEDENCE_LEVEL_LINK, seq(
      $._image_description,
      '(',
      repeat(choice($._whitespace, $._soft_line_break)),
      optional(seq(
        choice(
          seq(
            $.link_destination,
            optional(seq(repeat1(choice($._whitespace, $._soft_line_break)), $.link_title)),
          ),
          $.link_title,
        ),
        repeat(choice($._whitespace, $._soft_line_break)),
      )),
      ')',
    )),
    _image_shortcut_link: $ => prec.dynamic(3 * PRECEDENCE_LEVEL_LINK, $._image_description_non_empty),
    _image_full_reference_link: $ => prec.dynamic(PRECEDENCE_LEVEL_LINK, seq($._image_description, $.link_label)),
    _image_collapsed_reference_link: $ => prec.dynamic(PRECEDENCE_LEVEL_LINK, seq($._image_description, '[', ']')),
    _image_description: $ => prec.dynamic(3 * PRECEDENCE_LEVEL_LINK, choice(
      $._image_description_non_empty,
      seq('!', '[', prec(1, ']')),
    )),
    _image_description_non_empty: $ => seq('!', '[', alias($._inline, $.image_description), prec(1, ']')),

    // §6.5: `<scheme:...>` and `<user@host>`. A scheme of any length (the
    // spec says 2 to 32 characters; a bounded repeat makes the lexer huge).
    uri_autolink: _ => /<[a-zA-Z][a-zA-Z0-9+\.\-][a-zA-Z0-9+\.\-]*:[^ \t\r\n<>]*>/,
    email_autolink: _ =>
      /<[a-zA-Z0-9.!#$%&'*+/=?^_`{|}~-]+@[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(?:\.[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)*>/,

    // §6.6: raw HTML, one node (a proper HTML grammar reads its insides).
    _html_tag: $ => choice($._open_tag, $._closing_tag, $._html_comment, $._processing_instruction, $._declaration, $._cdata_section),
    _open_tag: $ => prec.dynamic(PRECEDENCE_LEVEL_HTML, seq(
      '<',
      $._tag_name,
      repeat($._attribute),
      repeat(choice($._whitespace, $._soft_line_break)),
      optional('/'),
      '>',
    )),
    _closing_tag: $ => prec.dynamic(PRECEDENCE_LEVEL_HTML, seq(
      '<',
      '/',
      $._tag_name,
      repeat(choice($._whitespace, $._soft_line_break)),
      '>',
    )),
    _tag_name: $ => seq($._word_no_digit, repeat(choice($._word_no_digit, $._digits, '-'))),
    _attribute: $ => seq(
      repeat1(choice($._whitespace, $._soft_line_break)),
      $._attribute_name,
      repeat(choice($._whitespace, $._soft_line_break)),
      '=',
      repeat(choice($._whitespace, $._soft_line_break)),
      $._attribute_value,
    ),
    _attribute_name: _ => /[a-zA-Z_:][a-zA-Z0-9_\.:\-]*/,
    _attribute_value: $ => choice(
      /[^ \t\r\n"'=<>`]+/,
      seq('\'', repeat(choice($._word, $._whitespace, $._soft_line_break, common.punctuationWithout($, ['\'']))), '\''),
      seq('"', repeat(choice($._word, $._whitespace, $._soft_line_break, common.punctuationWithout($, ['"']))), '"'),
    ),
    _html_comment: $ => prec.dynamic(PRECEDENCE_LEVEL_HTML, seq(
      '<!--',
      optional(seq(
        choice(
          $._word,
          $._whitespace,
          $._soft_line_break,
          common.punctuationWithout($, ['-', '>']),
          seq('-', common.punctuationWithout($, ['>'])),
        ),
        repeat(prec.right(choice(
          $._word,
          $._whitespace,
          $._soft_line_break,
          common.punctuationWithout($, ['-']),
          seq('-', choice($._word, $._whitespace, $._soft_line_break, common.punctuationWithout($, ['-']))),
        ))),
      )),
      '-->',
    )),
    _processing_instruction: $ => prec.dynamic(PRECEDENCE_LEVEL_HTML, seq(
      '<?',
      repeat(prec.right(choice($._word, $._whitespace, $._soft_line_break, common.punctuationWithout($, [])))),
      '?>',
    )),
    _declaration: $ => prec.dynamic(PRECEDENCE_LEVEL_HTML, seq(
      /<![a-zA-Z]/,
      repeat(choice($._word, $._whitespace, $._soft_line_break, common.punctuationWithout($, ['>']))),
      '>',
    )),
    _cdata_section: $ => prec.dynamic(PRECEDENCE_LEVEL_HTML, seq(
      '<![CDATA[',
      repeat(prec.right(choice($._word, $._whitespace, $._soft_line_break, common.punctuationWithout($, [])))),
      ']]>',
    )),

    // §6.7: a backslash, or two or more spaces, before a line ending.
    hard_line_break: $ => seq(choice('\\', $._whitespace_ge_2), $._soft_line_break),

    // One space or more: hard line breaks need to tell them apart.
    _whitespace_ge_2: _ => /\t| [ \t]+/,
    _whitespace: $ => seq(choice($._whitespace_ge_2, / /), optional($._last_token_whitespace)),

    // Text is runs of digits, punctuation (one token each) and runs of
    // anything else, so the lexer has few states to keep apart.
    _word: $ => choice($._word_no_digit, $._digits),
    _word_no_digit: _ => new RegExp('[^' + PUNCTUATION_CHARACTERS_REGEX + ' \\t\\n\\r0-9]+(_+[^' + PUNCTUATION_CHARACTERS_REGEX + ' \\t\\n\\r]+)*'),
    _digits: _ => /[0-9][0-9_]*/,
    _soft_line_break: $ => seq($._newline_token, optional($._last_token_whitespace)),
    _newline_token: _ => /\n|\r\n?/,

    _inline_base: $ => prec.right(repeat1(choice(
      $.image,
      $._soft_line_break,
      $.backslash_escape,
      $.hard_line_break,
      $.uri_autolink,
      $.email_autolink,
      $.entity_reference,
      $.numeric_character_reference,
      $.latex_block,
      $.code_span,
      alias($._html_tag, $.html_tag),
      $._text_base,
      $._unclosed_span,
    ))),

    _text_base: $ => choice(
      $._word,
      common.punctuationWithout($, ['[', ']']),
      $._whitespace,
      '<!--',
      /<![a-zA-Z]/,
      '<?',
      '<![CDATA[',
    ),

    _text_inline_no_link: $ => choice(
      $._text_base,
      $._emphasis_open_star,
      $._emphasis_open_underscore,
      $._unclosed_span,
    ),
  },
}));

/**
 * The inline-content rule families: `_inline_element` and `_inline` with or
 * without links (link text may not hold a link), and without a delimiter
 * kind (an emphasis's content may not hold its own unmatched opener), and
 * the emphasis, strong emphasis and strikethrough rules of each, with the
 * conflicts between them.
 */
function addInlineRules(grammar) {
  const conflicts = [];
  for (const link of [true, false]) {
    const suffixLink = link ? '' : '_no_link';
    for (const delimiter of [false, 'star', 'underscore', 'tilde']) {
      const suffixDelimiter = delimiter ? '_no_' + delimiter : '';
      const suffix = suffixDelimiter + suffixLink;
      grammar.rules['_inline_element' + suffix] = $ => {
        let elements = [
          $._inline_base,
          alias($['_emphasis_star' + suffixLink], $.emphasis),
          alias($['_strong_emphasis_star' + suffixLink], $.strong_emphasis),
          alias($['_emphasis_underscore' + suffixLink], $.emphasis),
          alias($['_strong_emphasis_underscore' + suffixLink], $.strong_emphasis),
          alias($['_strikethrough' + suffixLink], $.strikethrough),
        ];
        if (delimiter !== 'star') elements.push($._emphasis_open_star);
        if (delimiter !== 'underscore') elements.push($._emphasis_open_underscore);
        if (delimiter !== 'tilde') elements.push($._strikethrough_open);
        if (link) {
          elements = elements.concat([
            $.shortcut_link,
            $.full_reference_link,
            $.collapsed_reference_link,
            $.inline_link,
            seq(choice('[', ']'), optional($._last_token_punctuation)),
          ]);
        }
        return choice(...elements);
      };
      grammar.rules['_inline' + suffix] = $ => repeat1($['_inline_element' + suffix]);
      if (delimiter !== 'star') {
        conflicts.push(['_emphasis_star' + suffixLink, '_inline_element' + suffix]);
        conflicts.push(['_emphasis_star' + suffixLink, '_strong_emphasis_star' + suffixLink, '_inline_element' + suffix]);
      }
      if (link && (delimiter === 'star' || delimiter === 'underscore')) {
        conflicts.push(['_strong_emphasis_' + delimiter, '_inline_element_no_' + delimiter]);
      }
      if (delimiter !== 'underscore') {
        conflicts.push(['_emphasis_underscore' + suffixLink, '_inline_element' + suffix]);
        conflicts.push(['_emphasis_underscore' + suffixLink, '_strong_emphasis_underscore' + suffixLink, '_inline_element' + suffix]);
      }
      if (delimiter !== 'tilde') {
        conflicts.push(['_strikethrough' + suffixLink, '_inline_element' + suffix]);
      }
    }

    grammar.rules['_strikethrough' + suffixLink] = $ => prec.dynamic(PRECEDENCE_LEVEL_EMPHASIS, seq(
      alias($._strikethrough_open, $.emphasis_delimiter),
      optional($._last_token_punctuation),
      $['_inline_no_tilde' + suffixLink],
      alias($._strikethrough_close, $.emphasis_delimiter),
    ));
    grammar.rules['_emphasis_star' + suffixLink] = $ => prec.dynamic(PRECEDENCE_LEVEL_EMPHASIS, seq(
      alias($._emphasis_open_star, $.emphasis_delimiter),
      optional($._last_token_punctuation),
      $['_inline_no_star' + suffixLink],
      alias($._emphasis_close_star, $.emphasis_delimiter),
    ));
    grammar.rules['_strong_emphasis_star' + suffixLink] = $ => prec.dynamic(2 * PRECEDENCE_LEVEL_EMPHASIS, seq(
      alias($._emphasis_open_star, $.emphasis_delimiter),
      $['_emphasis_star' + suffixLink],
      alias($._emphasis_close_star, $.emphasis_delimiter),
    ));
    grammar.rules['_emphasis_underscore' + suffixLink] = $ => prec.dynamic(PRECEDENCE_LEVEL_EMPHASIS, seq(
      alias($._emphasis_open_underscore, $.emphasis_delimiter),
      optional($._last_token_punctuation),
      $['_inline_no_underscore' + suffixLink],
      alias($._emphasis_close_underscore, $.emphasis_delimiter),
    ));
    grammar.rules['_strong_emphasis_underscore' + suffixLink] = $ => prec.dynamic(2 * PRECEDENCE_LEVEL_EMPHASIS, seq(
      alias($._emphasis_open_underscore, $.emphasis_delimiter),
      $['_emphasis_underscore' + suffixLink],
      alias($._emphasis_close_underscore, $.emphasis_delimiter),
    ));
  }

  const declared = grammar.conflicts;
  grammar.conflicts = ($, previous) => declared($, previous).concat(conflicts.map(c => c.map(name => $[name])));
  return grammar;
}
