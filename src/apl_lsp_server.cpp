// `mep-apl-lsp`: the wire half of mep's own APL language server, and a
// command-line linter. Speaks LSP over stdio; every answer comes from
// apl_lsp.h's pure analysis functions.
//
//   mep-apl-lsp                       the language server on stdio
//   mep-apl-lsp --lint FILE...        diagnostics as path:line:col: severity: message [code];
//                                        exit 1 on any error or warning ('-' reads stdin)
//   mep-apl-lsp --doc [--root DIR] NAME [FILE...]
//                                     Markdown documentation of a glyph (⍴ or rho), a ⎕name,
//                                        a :Keyword, a )command or a user function -- looked
//                                        up in FILE..., the current directory's APL files and
//                                        MEP_APL_PATH (the language UI's Help tab)
//   mep-apl-lsp --hover FILE LINE COL the hover at a 1-based line and column
//   mep-apl-lsp --outline FILE        the definitions, tab-separated (the UI's Functions panel)
//   mep-apl-lsp --glyphs              the glyph vocabulary, tab-separated (the UI's language bar)
//
// Other files' definitions come from apl_lsp_index.h: the workspace's APL
// files and MEP_APL_PATH, cached by modification time.
//
// Single-threaded and synchronous; Content-Length framing via
// rpc_framing.h, full text sync, `positionEncoding: "utf-8"`.
// Generated by tools/new_language.py from nix_lsp_server.cpp.
