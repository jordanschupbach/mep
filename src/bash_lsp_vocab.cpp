const BashLspVocabEntry *BashLspFind(const std::vector<BashLspVocabEntry> &vocab, const std::string &name) {
    for (const BashLspVocabEntry &e : vocab) {
        if (name == e.name) return &e;
    }
    return nullptr;
}
