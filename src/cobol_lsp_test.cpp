void TestCompletion(const Fixture &f) {
    // Inside the CALL literal: the programs the copybooks document.
    auto doc = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           CALL \"dm_km"), f.program);
    auto items = CobolLspCompletions(*doc, 2, 22);
    CHECK(items.size() == 2 && items[0].label == "dm_kmeans_fit" && items[1].label == "dm_kmeans_new");
    CHECK(items[0].replace_start == 17 && items[0].replace_end == 22 && items[0].insert_text == "dm_kmeans_fit");
    CHECK(items[0].detail == "USING DM-KMEANS-FIT DM-STATUS" && Contains(items[0].documentation, "Fits k-means"));
    // After CALL, before the quote: quoted names.
    doc = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           CALL "), f.program);
    items = CobolLspCompletions(*doc, 2, 16);
    CHECK(items.size() == 9 && items[0].insert_text == "\"dm_close\"" && items[3].insert_text == "\"dm_kmeans_fit\"");
    // Every CALL line of a record is offered, each with its own USING.
    doc = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           CALL \"dm_square_side_"), f.program);
    items = CobolLspCompletions(*doc, 2, 32);
    CHECK(items.size() == 2 && items[0].label == "dm_square_side_get" && items[1].label == "dm_square_side_set" &&
          items[1].detail == "USING DM-SQUARE-SIDE DM-STATUS");

    // Record and field names, case-insensitive, then keywords.
    doc = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           MOVE 1 TO dm-kmeans-fit-"), f.program);
    items = CobolLspCompletions(*doc, 2, 35);
    bool k = false;
    for (const auto &it : items) {
        k = k || (it.label == "DM-KMEANS-FIT-K" && it.kind == CobolLspKind::Field && it.replace_start == 21 &&
                  Contains(it.detail, "datamunge.cpy") && Contains(it.documentation, "Number of clusters"));
    }
    CHECK(items.size() == 4 && k);
    doc = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           MOVE 1 TO DM-KM"), f.program);
    items = CobolLspCompletions(*doc, 2, 26);
    CHECK(!items.empty() && items[0].label == "DM-KMEANS-FIT" && items[0].kind == CobolLspKind::Struct);
    doc = CobolLspAnalyze(L("       PROCEDURE DIVISION.\n           PERF"), f.program);
    items = CobolLspCompletions(*doc, 1, 15);
    CHECK(items.size() == 1 && items[0].label == "PERFORM" && items[0].kind == CobolLspKind::Keyword);
    // COPY offers the .cpy files on the search path.
    doc = CobolLspAnalyze(L("       WORKING-STORAGE SECTION.\n       COPY data"), f.program);
    items = CobolLspCompletions(*doc, 1, 16);
    CHECK(items.size() == 2 && items[0].label == "datamunge" && items[1].label == "datamunge-callbacks");
}

