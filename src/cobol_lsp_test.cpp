void TestLineStructure() {
    // Fixed format: column 7 indicator, sequence area, floating comment.
    CobolLineInfo i = CobolClassifyLine("000100*comment", CobolFormat::Fixed);
    CHECK(i.comment_line && i.comment_start == 6);
    i = CobolClassifyLine("       01 X PIC X. *> note", CobolFormat::Fixed);
    CHECK(!i.comment_line && i.code_start == 7 && i.comment_start == 19 && i.code_end == 19);
    i = CobolClassifyLine("       DISPLAY \"a *> b\"", CobolFormat::Fixed);
    CHECK(i.comment_start == -1);  // `*>` inside a literal is not a comment
    i = CobolClassifyLine("      *>> doc", CobolFormat::Fixed);
    CHECK(i.comment_line);
    i = CobolClassifyLine("  *> free comment", CobolFormat::Free);
    CHECK(i.comment_line && i.comment_start == 2);
    i = CobolClassifyLine("       >>SOURCE FORMAT IS FREE", CobolFormat::Fixed);
    CHECK(i.directive);

    // Format detection: default fixed, free when code sits in the sequence area, directives switch.
    auto f = CobolLineFormats(L("       IDENTIFICATION DIVISION.\n000200 PROGRAM-ID. X."));
    CHECK(f[0] == CobolFormat::Fixed && f[1] == CobolFormat::Fixed);
    f = CobolLineFormats(L("IDENTIFICATION DIVISION.\nPROGRAM-ID. X."));
    CHECK(f[0] == CobolFormat::Free);
    f = CobolLineFormats(L("       >>SOURCE FORMAT FREE\nIDENTIFICATION DIVISION.\n>>SOURCE FIXED\n       X."));
    CHECK(f[0] == CobolFormat::Fixed && f[1] == CobolFormat::Free && f[3] == CobolFormat::Fixed);

    // Doc comments: fixed, free, behind a sequence number; `*>` alone is not one.
    std::string t;
    CHECK(CobolDocCommentText("      *>> KMeans handle.", &t) && t == "KMeans handle.");
    CHECK(CobolDocCommentText("*>> free", &t) && t == "free");
    CHECK(CobolDocCommentText("    *>>   indented body", &t) && t == "  indented body");
    CHECK(CobolDocCommentText("000600*>> numbered", &t) && t == "numbered");
    CHECK(CobolDocCommentText("      *>>", &t) && t.empty());
    CHECK(!CobolDocCommentText("      *> plain comment", &t));
    CHECK(!CobolDocCommentText("       01 X.", &t));
}

void TestDocBlocks() {
    const CobolLspDocBlock d = CobolLspSplitDoc({"datamunge::f(int k) -> void", "CALL \"dm_f\" USING DM-F DM-STATUS", "",
                                                 "Does f.", "", "More."});
    CHECK(d.signature.size() == 1 && d.signature[0] == "datamunge::f(int k) -> void");
    CHECK(d.call_name == "dm_f" && d.call_line == "CALL \"dm_f\" USING DM-F DM-STATUS");
    CHECK(d.body.size() == 3 && d.body[0] == "Does f." && d.body[2] == "More.");
    const CobolLspDocBlock plain = CobolLspSplitDoc({"k (int, default 3): Number of clusters."});
    CHECK(plain.call_name.empty() && plain.signature.empty() && plain.body.size() == 1);

    // Attachment, both formats, in one unit.
    const auto fixed = CobolLspAnalyze(L(kDatamunge));
    bool fit = false, k = false, ok88 = false, less = false;
    for (const CobolLspItemInfo &it : CobolLspItems(*fixed)) {
        if (it.name == "DM-KMEANS-FIT") {
            fit = it.level == 1 && it.call_name == "dm_kmeans_fit" && it.doc.size() == 6 && it.line == 19;
        }
        if (it.name == "DM-KMEANS-FIT-K") {
            k = it.level == 5 && it.parent == "DM-KMEANS-FIT" && it.doc.size() == 1 &&
                it.doc[0] == "k (int, default 3): Number of clusters.";
        }
        if (it.name == "DM-STATUS-OK") ok88 = it.level == 88 && it.parent == "DM-STATUS-CODE" && it.doc.empty();
        if (it.name == "DM-ALTERNATIVE-LESS") less = it.level == 78 && it.doc.size() == 1;
    }
    CHECK(fit && k && ok88 && less);
    const auto free = CobolLspAnalyze(L(kCallbacks));
    bool arg = false, status = false;
    for (const CobolLspItemInfo &it : CobolLspItems(*free)) {
        if (it.name == "DM-FN-DOUBLE-OF-DOUBLE-ARG-1") arg = it.doc.size() == 1 && it.doc[0] == "The argument.";
        if (it.name == "DM-CALLBACK-STATUS") status = it.doc.size() == 1 && it.parent.empty();
    }
    CHECK(arg && status);
    // An ordinary comment between a doc block and its entry does not break it; code does.
    const auto mixed = CobolLspAnalyze(L("      *>> Doc for A.\n      *> not doc\n       01 A PIC X.\n       01 B PIC X."));
    const auto items = CobolLspItems(*mixed);
    CHECK(items.size() == 2 && items[0].doc.size() == 1 && items[1].doc.empty());
}

void TestCopyResolution(const Fixture &f) {
    namespace fs = std::filesystem;
    unsetenv("COBCPY");
    unsetenv("COB_COPY_DIR");
    auto doc = CobolLspAnalyze(L(kProgram), f.program);
    auto diags = CobolLspDiagnostics(*doc);
    CHECK(diags.size() == 1 && diags[0].code == "copy-not-found" && diags[0].range.line == 4);
    CHECK(!CobolLspHover(*doc, 11, 20).found);

    // $COBCPY (':'-separated, a missing directory first).
    const std::string cobcpy = (f.root / "nowhere").string() + ":" + f.copydir.string();
    setenv("COBCPY", cobcpy.c_str(), 1);
    const auto dirs = CobolLspCopybookDirs(f.program, {});
    CHECK(dirs.size() == 3 && dirs[0] == (f.root / "src").string() && dirs[2] == f.copydir.string());
    // The order: the file's directory, $COBCPY, then includeDirs (the Run Setup's -I), relative to the file.
    const auto ordered = CobolLspCopybookDirs(f.program, {"/opt/inc", "../lib"});
    CHECK(ordered.size() == 5 && ordered[1] == (f.root / "nowhere").string() && ordered[2] == f.copydir.string() &&
          ordered[3] == "/opt/inc" && ordered[4] == (f.root / "lib").string());
    CHECK(CobolLspResolveCopy("datamunge", dirs) == fs::weakly_canonical(f.copydir / "datamunge.cpy").string());
    CHECK(CobolLspResolveCopy("DATAMUNGE", dirs) == fs::weakly_canonical(f.copydir / "datamunge.cpy").string());
    CHECK(CobolLspResolveCopy("datamunge-callbacks.cpy", dirs) != "");
    CHECK(CobolLspResolveCopy("nope", dirs).empty());
    doc = CobolLspAnalyze(L(kProgram), f.program);
    CHECK(CobolLspDiagnostics(*doc).empty());
    int nested = 0;
    for (const CobolLspItemInfo &it : CobolLspItems(*doc)) nested += it.name == "DM-FN-DOUBLE-OF-DOUBLE";
    CHECK(nested == 1);  // datamunge.cpy's own COPY of the callbacks copybook was followed

    // includeDirs (cobc -I), relative to the document's directory, without $COBCPY.
    unsetenv("COBCPY");
    doc = CobolLspAnalyze(L(kProgram), f.program, {"../build/cobol/copybooks"});
    CHECK(CobolLspDiagnostics(*doc).empty());
    // The document's own directory.
    WriteFile(f.root / "src/local.cpy", "       01 LOCAL-REC PIC X.\n");
    doc = CobolLspAnalyze(L("       WORKING-STORAGE SECTION.\n       COPY local.\n"), f.program);
    CHECK(CobolLspDiagnostics(*doc).empty() && CobolLspHover(*doc, 1, 13).found);
    setenv("COBCPY", f.copydir.string().c_str(), 1);
}

void TestHover(const Fixture &f) {
    const auto doc = CobolLspAnalyze(L(kProgram), f.program);

    // The CALL literal: the record's doc block, its declaration and fields.
    auto h = CobolLspHover(*doc, 11, 20);
    std::printf("--- hover CALL \"dm_kmeans_fit\" ---\n%s\n", h.text.c_str());
    CHECK(h.found && h.range.line == 11 && h.range.col == 16);
    CHECK(Contains(h.text, "```cpp\ndatamunge::cluster::KMeans::fit(const std::vector<double> &X, int k = 3) -> void\n```"));
    CHECK(Contains(h.text, "CALL \"dm_kmeans_fit\" USING DM-KMEANS-FIT DM-STATUS\n01 DM-KMEANS-FIT.\n```"));
    CHECK(Contains(h.text, "Fits k-means to the data.\n\nLloyd's algorithm"));
    CHECK(Contains(h.text, "- `DM-KMEANS-FIT-K` `USAGE BINARY-LONG SIGNED`: k (int, default 3): Number of clusters."));
    CHECK(Contains(h.text, "- `DM-KMEANS-FIT-GIVEN` `USAGE BINARY-LONG SIGNED VALUE 1`"));
    CHECK(Contains(h.text, "*datamunge.cpy:20*"));

    // The record name: the same hover.
    const auto h2 = CobolLspHover(*doc, 11, 45);
    CHECK(h2.found && h2.text == h.text);

    // A field.
    h = CobolLspHover(*doc, 10, 25);
    std::printf("--- hover DM-KMEANS-FIT-K ---\n%s\n", h.text.c_str());
    CHECK(h.found && Contains(h.text, "```cobol\n05 DM-KMEANS-FIT-K USAGE BINARY-LONG SIGNED.\n```"));
    CHECK(Contains(h.text, "k (int, default 3): Number of clusters."));
    CHECK(Contains(h.text, "In `DM-KMEANS-FIT` (`CALL \"dm_kmeans_fit\"`)"));

    // An 88 condition and the field that carries 88s.
    h = CobolLspHover(*doc, 12, 20);
    CHECK(h.found && Contains(h.text, "88 DM-STATUS-OK VALUE 0.") && Contains(h.text, "Condition on `DM-STATUS-CODE`, in `DM-STATUS`"));
    const auto status = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           MOVE 0 TO DM-STATUS-CODE."), f.program);
    h = CobolLspHover(*status, 2, 30);
    CHECK(h.found && Contains(h.text, "**Values**") && Contains(h.text, "- `DM-STATUS-OK` VALUE 0"));
    // A 78 constant.
    const auto cst = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           MOVE DM-ALTERNATIVE-LESS TO X."), f.program);
    h = CobolLspHover(*cst, 2, 20);
    CHECK(h.found && Contains(h.text, "78 DM-ALTERNATIVE-LESS VALUE 0.") && Contains(h.text, "datamunge::Alternative::Less"));

    // The program's own items: a 77 with its doc, and paragraphs.
    h = CobolLspHover(*doc, 10, 17);
    CHECK(h.found && Contains(h.text, "77 WS-K PIC 9(4) VALUE 3.") && Contains(h.text, "How many clusters") &&
          Contains(h.text, "*line 7*"));
    h = CobolLspHover(*doc, 15, 22);
    CHECK(h.found && Contains(h.text, "CLEANUP.") && Contains(h.text, "Paragraph"));
    h = CobolLspHover(*doc, 9, 9);
    CHECK(h.found && Contains(h.text, "Entry point."));

    // COPY: the copybook and its records.
    h = CobolLspHover(*doc, 4, 18);
    CHECK(h.found && Contains(h.text, "datamunge.cpy") && Contains(h.text, "`DM-KMEANS-FIT` `CALL \"dm_kmeans_fit\"`: Fits k-means"));

    // A CALL literal no doc block names still finds the record rosetta names after it.
    const auto byname =
        CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           CALL \"dm_status\" USING X."), f.program);
    CHECK(CobolLspHover(*byname, 2, 20).found);
    // A literal elsewhere, a keyword, unknown names: nothing.
    CHECK(!CobolLspHover(*doc, 18, 22).found);
    CHECK(!CobolLspHover(*doc, 10, 12).found);
    CHECK(!CobolLspHover(*doc, 18, 40).found);  // in the trailing comment
}

