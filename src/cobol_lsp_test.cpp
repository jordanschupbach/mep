void TestLineFormats() {
    // Code in the sequence area makes a file free format; a sequence number, or a word filling the
    // area with an indicator after it, does not.
    auto formats = CobolLineFormats(L("000100 IDENTIFICATION DIVISION.\nrogerw     DISPLAY \"x\".\n000300     STOP RUN."));
    CHECK(formats[0] == CobolFormat::Fixed && formats[2] == CobolFormat::Fixed);
    formats = CobolLineFormats(L("*> free\nIDENTIFICATION DIVISION.\n    STOP RUN."));
    CHECK(formats[0] == CobolFormat::Free && formats[2] == CobolFormat::Free);
    formats = CobolLineFormats(L("       IDENTIFICATION DIVISION.\n      >>SOURCE FORMAT FREE\nMOVE 1 TO X."));
    CHECK(formats[0] == CobolFormat::Fixed && formats[1] == CobolFormat::Fixed && formats[2] == CobolFormat::Free);
}

void TestFormatting() {
    // One edit per changed line, the whole line replaced.
    const std::vector<std::string> lines = L("       PROCEDURE DIVISION.\n       IF X\n       DISPLAY X\n       END-IF.");
    std::string error;
    std::vector<CobolLspTextEdit> edits = CobolLspFormat(lines, 0, -1, &error);
    CHECK(error.empty());
    CHECK(edits.size() == 3);
    CHECK(edits[0].range.line == 1 && edits[0].range.col == 0 && edits[0].range.end_col == 11);
    CHECK(edits[0].new_text == "           IF X");
    CHECK(edits[1].new_text == "               DISPLAY X");
    CHECK(edits[2].range.line == 3 && edits[2].new_text == "           END-IF.");
    // A range: only its lines (formatted in the whole document's context).
    edits = CobolLspFormat(lines, 2, 2, &error);
    CHECK(error.empty() && edits.size() == 1 && edits[0].range.line == 2);
    // Formatted text: no edits.
    std::vector<std::string> done = lines;
    for (const CobolLspTextEdit &e : CobolLspFormat(lines, 0, -1, &error)) done[static_cast<size_t>(e.range.line)] = e.new_text;
    CHECK(CobolLspFormat(done, 0, -1, &error).empty() && error.empty());
    // A refusal: no edits, the reason.
    edits = CobolLspFormat(L("000100 PROCEDURE DIVISION.\nDISPLAY-IT. DISPLAY 1."), 0, -1, &error);
    CHECK(edits.empty() && !error.empty());
}

void TestRobustness(const Fixture &f) {
    // Every query on every prefix of a file must not crash.
    const std::string src = std::string(kProgram) + kDatamunge + kCallbacks + "      \"unterminated\n   01 .\n  88\n";
    for (size_t n = 0; n <= src.size(); n += 3) {
        const auto lines = L(src.substr(0, n));
        const auto doc = CobolLspAnalyze(lines, f.program);
        const int last = static_cast<int>(lines.size()) - 1;
        const int col = static_cast<int>(lines.back().size());
        CobolLspDiagnostics(*doc);
        CobolLspCompletions(*doc, last, col);
        CobolLspHover(*doc, last, col);
        CobolLspHover(*doc, last, col > 0 ? col - 1 : 0);
        CobolLspDefinition(*doc, last, col);
        CobolLspSignatureAt(*doc, last, col);
        CobolLspSymbols(*doc);
        CobolLspFolds(*doc);
    }
}


void TestUnwrap() {
    // Rosetta's continuation lines (two extra spaces) join the line they continue; not inside a fence,
    // not a nested list item, not across a blank line.
    const std::vector<std::string> doc = {"Solve it for", "  real.", "", "- MFEM: weak forms.", "  P1 intervals.",
                                          "  - nested", "```cpp", "auto x = f(1,", "  2);", "```", "Done."};
    const auto u = CobolLspUnwrapDoc(doc);
    CHECK(u.size() == 9 && u[0] == "Solve it for real." && u[2] == "- MFEM: weak forms. P1 intervals." && u[3] == "  - nested" &&
          u[5] == "auto x = f(1," && u[6] == "  2);" && u[8] == "Done.");

    // Several CALL lines, wrapped; a summary head (not C++); body after the blank line.
    CobolLspDocBlock d = CobolLspSplitDoc({"Any handle.", "CALL \"x_close\" USING X-HANDLE X-STATUS (destroys its",
                                           "  object)", "CALL \"x_handle_type\" USING X-HANDLE X-STATUS", "", "Body."});
    CHECK(d.signature.size() == 1 && d.signature[0] == "Any handle." && d.calls.size() == 2);
    CHECK(d.calls[0].name == "x_close" && d.calls[0].line == "CALL \"x_close\" USING X-HANDLE X-STATUS (destroys its object)");
    CHECK(d.calls[1].name == "x_handle_type" && d.call_name == "x_close" && d.body.size() == 1 && d.body[0] == "Body.");
    // A CALL whose USING wraps onto the next line.
    d = CobolLspSplitDoc({"Copies.", "CALL \"x_from_table\" USING", "  X-TABLE X-STATUS (sets -SELF)"});
    CHECK(d.calls.size() == 1 && d.calls[0].line == "CALL \"x_from_table\" USING X-TABLE X-STATUS (sets -SELF)");
    // The callbacks copybook: PROCEDURE DIVISION USING instead of CALL.
    d = CobolLspSplitDoc({"ns::Shape::area() const -> double", "PROCEDURE DIVISION USING X-ARGS X-CALLBACK-STATUS", "",
                          "The record."});
    CHECK(d.calls.empty() && d.using_line == "PROCEDURE DIVISION USING X-ARGS X-CALLBACK-STATUS" &&
          d.signature.size() == 1 && d.body.size() == 1);
    // A CALL mentioned in the body is not a CALL line; a block with no head is all body.
    d = CobolLspSplitDoc({"C++ class ns::Shape. Close the handle with CALL", "  \"x_close\"."});
    CHECK(d.calls.empty() && d.signature.empty() && d.body.size() == 1);
}

void TestMultipleCalls(const Fixture &f) {
    const auto doc = CobolLspAnalyze(L(kFullProgram), (f.root / "src/full.cob").string());
    CHECK(CobolLspDiagnostics(*doc).empty());
    bool handle = false, side = false, table = false;
    for (const CobolLspItemInfo &it : CobolLspItems(*doc)) {
        if (it.name == "DM-HANDLE") {
            handle = it.calls == std::vector<std::string>{"dm_close", "dm_handle_type", "dm_handle_open"};
        }
        if (it.name == "DM-SQUARE-SIDE") side = it.calls == std::vector<std::string>{"dm_square_side_get", "dm_square_side_set"};
        if (it.name == "DM-VECTOR-DOUBLE-TABLE") {
            table = it.calls == std::vector<std::string>{"dm_vector_double_from_table", "dm_vector_double_to_table"};
        }
    }
    CHECK(handle && side && table);

    // Each CALL literal finds its record: _set, a wrapped table call, the handle's third call.
    auto h = CobolLspHover(*doc, 9, 15);
    std::printf("--- hover CALL \"dm_square_side_set\" ---\n%s\n", h.text.c_str());
    CHECK(h.found && Contains(h.text, "```cpp\ndatamunge::Square::side\n```") &&
          Contains(h.text, "CALL \"dm_square_side_get\" USING DM-SQUARE-SIDE DM-STATUS\nCALL \"dm_square_side_set\" USING "
                           "DM-SQUARE-SIDE DM-STATUS\n01 DM-SQUARE-SIDE.") &&
          Contains(h.text, "- `DM-SQUARE-SIDE-VALUE` `USAGE COMP-2`: side (double): the value get reads and set writes."));
    h = CobolLspHover(*doc, 14, 15);
    CHECK(h.found && Contains(h.text, "Copies VECTOR-DOUBLE elements to or from a COBOL table of up to 1000 entries.\n\n```cobol") &&
          Contains(h.text, "CALL \"dm_vector_double_from_table\" USING DM-VECTOR-DOUBLE-TABLE DM-STATUS (sets -SELF to a new "
                           "one holding the -COUNT items)") &&
          Contains(h.text, "  - `DM-VECTOR-DOUBLE-TABLE-ITEM` `USAGE COMP-2`: An element: double."));
    h = CobolLspHover(*doc, 16, 15);
    CHECK(h.found && Contains(h.text, "01 DM-HANDLE.") && Contains(h.text, "(destroys its object; closing twice is harmless)"));
    auto locs = CobolLspDefinition(*doc, 16, 15);
    CHECK(locs.size() == 1 && locs[0].range.line == 43);
    const auto sig = CobolLspSignatureAt(*doc, 16, 45);
    CHECK(sig.found && sig.label == "CALL \"dm_handle_open\" USING DM-HANDLE DM-STATUS" && sig.params.size() == 2);

    // Names in MOVE / IF / COMPUTE, with subscripts and reference modification.
    h = CobolLspHover(*doc, 10, 12);  // 78 sharing its enum's block
    CHECK(h.found && Contains(h.text, "78 DM-KIND-SQUARE VALUE 1.") && Contains(h.text, "**Value:** `1`") &&
          Contains(h.text, "C++ enum datamunge::Kind (KIND fields).\n\nShape kinds."));
    h = CobolLspHover(*doc, 11, 10);  // DM-STATUS-MESSAGE(1:...)
    CHECK(h.found && Contains(h.text, "05 DM-STATUS-MESSAGE PIC X(256).") && Contains(h.text, "In `DM-STATUS`"));
    h = CobolLspHover(*doc, 11, 32);  // DM-STATUS-LENGTH inside the parentheses
    CHECK(h.found && Contains(h.text, "DM-STATUS-LENGTH"));
    h = CobolLspHover(*doc, 15, 25);  // DM-VECTOR-DOUBLE-TABLE-ITEM(3)
    CHECK(h.found && Contains(h.text, "10 DM-VECTOR-DOUBLE-TABLE-ITEM USAGE COMP-2.") && Contains(h.text, "An element: double.") &&
          Contains(h.text, "In `DM-VECTOR-DOUBLE-TABLE` (`CALL \"dm_vector_double_from_table\"`)"));
    h = CobolLspHover(*doc, 8, 20);  // a field of a _get/_set record
    CHECK(h.found && Contains(h.text, "In `DM-SQUARE-SIDE` (`CALL \"dm_square_side_get\"`)"));
    // A multi-line entry reads as one declaration.
    const auto count = CobolLspHover(*CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n"
                                                          "           MOVE 0 TO DM-VECTOR-DOUBLE-TABLE-COUNT."), f.program),
                                     2, 30);
    CHECK(count.found && Contains(count.text, "05 DM-VECTOR-DOUBLE-TABLE-COUNT USAGE BINARY-LONG SIGNED VALUE 0."));

    // The second program: COPY in LINKAGE, the record named in PROCEDURE DIVISION USING.
    h = CobolLspHover(*doc, 26, 30);
    std::printf("--- hover DM-SHAPE-AREA-ARGS ---\n%s\n", h.text.c_str());
    CHECK(h.found && Contains(h.text, "```cpp\ndatamunge::Shape::area() const -> double\n```") &&
          Contains(h.text, "PROCEDURE DIVISION USING DM-SHAPE-AREA-ARGS DM-CALLBACK-STATUS\n01 DM-SHAPE-AREA-ARGS.") &&
          Contains(h.text, "(the COBOL override of datamunge::Shape::area)"));
    h = CobolLspHover(*doc, 27, 20);
    CHECK(h.found && Contains(h.text, "Result (double): double.") && Contains(h.text, "In `DM-SHAPE-AREA-ARGS`"));
    // COPY: on the name and on the keyword.
    h = CobolLspHover(*doc, 5, 10);
    CHECK(h.found && Contains(h.text, "Copybook `") && Contains(h.text, "datamunge.cpy`"));
    CHECK(CobolLspHover(*doc, 5, 1).found && CobolLspHover(*doc, 25, 10).found);
    CHECK(Contains(CobolLspHover(*doc, 25, 10).text, "datamunge-callbacks.cpy`"));
    // Paragraph detection is not fooled by the second program's header lines.
    for (const CobolLspSymbol &sym : CobolLspSymbols(*doc)) CHECK(sym.name != "GOBACK" && sym.name != "MY-AREA");
}

// Optional: rosetta's real generated copybooks and test programs, when MEP_COBOL_ROSETTA names a
// rosetta checkout with build/cobol-tests built (and MEP_COBOL_DATAMUNGE the directory holding
// datamunge.cpy). Every CALL literal anywhere in a copybook's doc comments must find a record whose
// doc block has that CALL line (or mentions it), every PROCEDURE DIVISION USING record must show it,
// and the sample programs must resolve all their COPYs.
std::vector<std::string> ReadAll(const std::string &path) {
    std::ifstream in(path, std::ios::binary);
    std::vector<std::string> out;
    std::string line;
    while (std::getline(in, line)) out.push_back(line);
    return out;
}

void CheckEveryCall(const std::string &copydir, const std::string &book) {
    const std::vector<std::string> lines = ReadAll(copydir + "/" + book);
    CHECK(!lines.empty());
    std::vector<std::string> calls, usings;
    for (const std::string &l : lines) {
        std::string text;
        if (!CobolDocCommentText(l, &text)) continue;
        for (size_t at = text.find("CALL \""); at != std::string::npos; at = text.find("CALL \"", at + 1)) {
            const size_t end = text.find('"', at + 6);
            if (end != std::string::npos) calls.push_back(text.substr(at + 6, end - at - 6));
        }
        if (text.compare(0, 25, "PROCEDURE DIVISION USING ") == 0) usings.push_back(text.substr(25, text.find(' ', 25) - 25));
    }
    std::string program = "       COPY \"" + book + "\".\n       PROCEDURE DIVISION.\n";
    for (const std::string &c : calls) program += "           CALL \"" + c + "\" USING X\n";
    for (const std::string &u : usings) program += "           MOVE " + u + " TO X\n";
    const auto doc = CobolLspAnalyze(L(program), copydir + "/probe.cob");
    CHECK(CobolLspDiagnostics(*doc).empty());
    int row = 2;
    for (const std::string &c : calls) {
        const auto h = CobolLspHover(*doc, row++, 18);
        if (!h.found || !Contains(h.text, "\"" + c + "\"")) std::fprintf(stderr, "unmapped CALL \"%s\" in %s\n", c.c_str(), book.c_str());
        CHECK(h.found && Contains(h.text, "\"" + c + "\""));
    }
    for (const std::string &u : usings) {
        const auto h = CobolLspHover(*doc, row++, 17);
        CHECK(h.found && Contains(h.text, "PROCEDURE DIVISION USING " + u));
    }
    std::printf("%s: %zu CALL literals and %zu callback records map to their records\n", book.c_str(), calls.size(), usings.size());
}

void TestRosettaSamples() {
    const char *root = std::getenv("MEP_COBOL_ROSETTA");
    if (root && *root) {
        const std::string copydir = std::string(root) + "/build/cobol-tests/cobol";
        CheckEveryCall(copydir, "features.cpy");
        CheckEveryCall(copydir, "features-callbacks.cpy");
        setenv("COBCPY", copydir.c_str(), 1);
        // Free format, five programs, COPY in WORKING-STORAGE and LINKAGE.
        const std::string full = std::string(root) + "/tests/test_cobol_full.cob";
        const auto lines = ReadAll(full);
        const auto doc = CobolLspAnalyze(lines, full);
        CHECK(CobolLspDiagnostics(*doc).empty());
        int calls = 0;
        for (size_t row = 0; row < lines.size(); row++) {
            const size_t at = lines[row].find("CALL \"");
            if (at == std::string::npos) continue;
            const auto h = CobolLspHover(*doc, static_cast<int>(row), static_cast<int>(at) + 7);
            if (!h.found) std::fprintf(stderr, "no hover: %s\n", lines[row].c_str());
            CHECK(h.found && Contains(h.text, "```cobol\n"));
            calls++;
        }
        CHECK(calls > 30);
        // Fixed format program over fixed format copybooks.
        const std::string fixed = std::string(root) + "/tests/test_cobol_fixed.cob";
        const auto fdoc = CobolLspAnalyze(ReadAll(fixed), fixed);
        CHECK(CobolLspDiagnostics(*fdoc).empty());
        // CALL "cobol_demo_add": these copybooks carry plain `*>` comments only, so the record is found by
        // name (cobol_demo_add -> COBOL-DEMO-ADD).
        const auto h = CobolLspHover(*fdoc, 11, 20);
        CHECK(h.found && Contains(h.text, "01 COBOL-DEMO-ADD.") && Contains(h.text, "`COBOL-DEMO-ADD-RESULT`"));
        CHECK(CobolLspHover(*fdoc, 9, 25).found);  // MOVE 20 TO COBOL-DEMO-ADD-A
        std::printf("rosetta samples: %d CALL hovers in test_cobol_full.cob\n", calls);
    } else {
        std::printf("(MEP_COBOL_ROSETTA unset: skipping rosetta's generated copybooks)\n");
    }
    const char *dm = std::getenv("MEP_COBOL_DATAMUNGE");
    if (dm && *dm) {
        const auto t0 = std::chrono::steady_clock::now();
        const auto doc = CobolLspAnalyze(L("       COPY datamunge.\n"), std::string(dm) + "/probe.cob");
        const auto t1 = std::chrono::steady_clock::now();
        const auto again = CobolLspAnalyze(L("       COPY datamunge.\n"), std::string(dm) + "/probe.cob");
        const auto t2 = std::chrono::steady_clock::now();
        const auto ms = [](auto a, auto b) { return std::chrono::duration<double, std::milli>(b - a).count(); };
        std::printf("datamunge.cpy: first analysis %.1f ms, cached %.2f ms\n", ms(t0, t1), ms(t1, t2));
        CHECK(CobolLspDiagnostics(*doc).empty() && ms(t1, t2) < 50);
        // Completion over ~2800 records stays interactive: a bare CALL literal, and a name prefix.
        const auto probe = CobolLspAnalyze(L("       COPY datamunge.\n       PROCEDURE DIVISION.\n           CALL \"\n"
                                             "           MOVE 1 TO DM-"),
                                           std::string(dm) + "/probe.cob");
        const auto t3 = std::chrono::steady_clock::now();
        const auto calls = CobolLspCompletions(*probe, 2, 17);
        const auto t4 = std::chrono::steady_clock::now();
        const auto names = CobolLspCompletions(*probe, 3, 24);
        const auto t5 = std::chrono::steady_clock::now();
        std::printf("datamunge.cpy: CALL \" completion %zu items in %.1f ms, DM- %zu items in %.1f ms\n", calls.size(),
                    ms(t3, t4), names.size(), ms(t4, t5));
        CHECK(calls.size() >= 2000 && names.size() >= 2000 && ms(t3, t4) < 500 && ms(t4, t5) < 500);
        CheckEveryCall(dm, "datamunge.cpy");
        CheckEveryCall(dm, "datamunge-callbacks.cpy");
    }
}

