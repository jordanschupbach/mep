// Coverage for crystal_format.h: mep's own Crystal formatter, a port of the
// Crystal compiler's formatter. Every expected layout below is
// `crystal tool format`'s own (Crystal 1.19): most are cases of the
// compiler's spec/compiler/formatter/formatter_spec.cr. Each result is fed
// back through Format() to prove it is a fixed point.
//
// `mep-crystal-format-test --format FILE...` prints each file formatted
// instead (the reason a file was left alone on stderr), which is how the
// formatter is compared with `crystal tool format` on a corpus.

