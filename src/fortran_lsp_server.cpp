int main(int argc, char **argv) {
#if defined(_WIN32)
    _setmode(_fileno(stdout), _O_BINARY);
    _setmode(_fileno(stdin), _O_BINARY);
#endif
    if (argc > 1) {
        const std::string first = argv[1];
        std::vector<std::string> rest;
        for (int i = 2; i < argc; i++) rest.emplace_back(argv[i]);
        if (first == "--lint") {
            if (rest.empty()) rest.emplace_back("-");
            return Lint(rest);
        }
        if (first == "--gfortran-check") {
            // The reader's first syntax error as `LINE: message`, or "ok"; one line per file.
            for (const std::string &path : rest) {
                bool ok = false;
                const std::string text = ReadFile(path, &ok);
                const std::string msg = ok ? FortranLspGfortranCheck(text, path) : "unreadable";
                std::printf("%s\n", msg.empty() ? "ok" : msg.c_str());
            }
            return 0;
        }
        if (first == "--intrinsic") {
            if (rest.size() != 1) {
                std::fprintf(stderr, "usage: mep-fortran-lsp --intrinsic NAME\n");
                return 2;
            }
            return DescribeIntrinsic(rest[0]);
        }
        if (first == "--help" || first == "-h") {
            std::printf("usage: mep-fortran-lsp                        run the language server on stdio\n"
                        "       mep-fortran-lsp --lint FILE...         print diagnostics (FILE '-' reads stdin)\n"
                        "       mep-fortran-lsp --gfortran-check FILE...  the reader's first syntax error, or ok\n"
                        "       mep-fortran-lsp --intrinsic NAME       documentation of an intrinsic or keyword\n");
            return 0;
        }
        if (first != "--stdio") {
            std::fprintf(stderr, "mep-fortran-lsp: unknown argument %s (try --help)\n", first.c_str());
            return 2;
        }
    }
    FortranLanguageServer server;
    std::string buffer;
    char chunk[4096];
    while (server.running()) {
#if defined(_WIN32)
        const int got = _read(_fileno(stdin), chunk, static_cast<unsigned int>(sizeof(chunk)));
#else
        const ssize_t got = read(STDIN_FILENO, chunk, sizeof(chunk));
        if (got < 0 && errno == EINTR) continue;
#endif
        if (got <= 0) break;
        buffer.append(chunk, static_cast<size_t>(got));
        if (!PumpRpcFrames(buffer, [&server](const std::string &body) { server.HandleMessage(body); })) break;
    }
    return server.exit_code();
}
