std::vector<std::string> SplitLines(const std::string &text) {
    std::vector<std::string> lines;
    std::string cur;
    for (char c : text) {
        if (c == '\n') {
            if (!cur.empty() && cur.back() == '\r') cur.pop_back();
            lines.push_back(cur);
            cur.clear();
        } else {
            cur += c;
        }
    }
    if (!cur.empty() && cur.back() == '\r') cur.pop_back();
    lines.push_back(cur);
    return lines;
}

std::string ReadFile(const std::string &path, bool *ok) {
    std::ifstream in(path, std::ios::binary);
    *ok = static_cast<bool>(in);
    if (!in) return std::string();
    std::ostringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

Json Position(int line, int character) {
    Json p = Json::Object();
    p["line"] = line;
    p["character"] = character;
    return p;
}

Json RangeOf(const FortranLspRange &range) {
    Json r = Json::Object();
    r["start"] = Position(range.line, range.col);
    r["end"] = Position(range.end_line, range.end_col);
    return r;
}

Json EditsJson(const std::vector<FortranLspTextEdit> &edits) {
    Json arr = Json::Array();
    for (const FortranLspTextEdit &e : edits) {
        Json j = Json::Object();
        j["range"] = RangeOf(e.range);
        j["newText"] = e.new_text;
        arr.push_back(j);
    }
    return arr;
}

class FortranLanguageServer {
public:
    void HandleMessage(const std::string &body) {
        Json msg;
        if (!Json::Parse(body, &msg)) return;
        const std::string method = msg.get("method").as_string();
        const Json &params = msg.get("params");
        const bool is_request = msg.contains("id");

        if (method == "initialize") {
            Reply(msg.get("id"), Capabilities());
            std::string root = params.get("rootUri").as_string();
            if (root.empty()) root = params.get("rootPath").as_string();
            if (!root.empty()) index_.SetRoot(PathOfUri(root));
            return;
        }
        if (method == "shutdown") {
            shutting_down_ = true;
            Reply(msg.get("id"), Json());
            return;
        }
        if (method == "exit") {
            exit_code_ = shutting_down_ ? 0 : 1;
            running_ = false;
            return;
        }
        if (method == "initialized" || method == "workspace/didChangeConfiguration" || method == "$/setTrace") {
            return;
        }
        if (method == "textDocument/didSave") {
            index_.Refresh(PathOfUri(UriOf(params)));
            return;
        }
        if (method == "textDocument/didOpen") {
            const std::string uri = UriOf(params);
            Set(uri, params.get("textDocument").get("text").as_string());
            Publish(uri);
            return;
        }
        if (method == "textDocument/didChange") {
            const std::string uri = UriOf(params);
            const Json &changes = params.get("contentChanges");
            if (changes.is_array() && changes.size() > 0) Set(uri, changes.items().back().get("text").as_string());
            Publish(uri);
            return;
        }
        if (method == "textDocument/didClose") {
            const std::string uri = UriOf(params);
            docs_.erase(uri);
            index_.Close(PathOfUri(uri));
            Json note = Json::Object();
            note["uri"] = uri;
            note["diagnostics"] = Json::Array();
            Notify("textDocument/publishDiagnostics", note);
            return;
        }
        if (!is_request) return;

        if (method == "textDocument/completion") {
            Reply(msg.get("id"), Completion(params));
        } else if (method == "textDocument/hover") {
            Reply(msg.get("id"), HoverAt(params));
        } else if (method == "textDocument/documentSymbol") {
            Reply(msg.get("id"), Symbols(params));
        } else if (method == "textDocument/foldingRange") {
            Reply(msg.get("id"), Folds(params));
        } else if (method == "textDocument/definition") {
            Reply(msg.get("id"), Definition(params));
        } else if (method == "textDocument/references") {
            Reply(msg.get("id"), References(params));
        } else if (method == "textDocument/documentHighlight") {
            Reply(msg.get("id"), Highlights(params));
        } else if (method == "textDocument/signatureHelp") {
            Reply(msg.get("id"), SignatureHelp(params));
        } else if (method == "textDocument/prepareRename") {
            Reply(msg.get("id"), PrepareRename(params));
        } else if (method == "textDocument/rename") {
            std::string error;
            Json result = Rename(params, &error);
            if (!error.empty()) {
                ReplyError(msg.get("id"), -32803, error);
            } else {
                Reply(msg.get("id"), result);
            }
        } else if (method == "textDocument/formatting" || method == "textDocument/rangeFormatting") {
            std::string error;
            const std::vector<FortranLspTextEdit> edits = FortranLspFormat(Doc(UriOf(params)).lines, PathOfUri(UriOf(params)), &error);
            if (!error.empty()) {
                ReplyError(msg.get("id"), -32803, error);
            } else {
                Reply(msg.get("id"), EditsJson(edits));
            }
        } else if (method == "completionItem/resolve") {
            Reply(msg.get("id"), params);
        } else {
            ReplyError(msg.get("id"), -32601, "Unsupported method: " + method);
        }
    }

    bool running() const { return running_; }
    int exit_code() const { return exit_code_; }

private:
    struct OpenDoc {
        std::vector<std::string> lines;
        std::shared_ptr<const FortranLspDocument> analysis;
    };
    std::map<std::string, OpenDoc> docs_;
    FortranModuleIndex index_;
    bool running_ = true;
    bool shutting_down_ = false;
    int exit_code_ = 1;

    static void Send(const Json &msg) {
        const std::string framed = FrameRpcMessage(msg.dump());
        std::fwrite(framed.data(), 1, framed.size(), stdout);
        std::fflush(stdout);
    }

    static void Reply(const Json &id, Json result) {
        Json msg = Json::Object();
        msg["jsonrpc"] = "2.0";
        msg["id"] = id;
        msg["result"] = std::move(result);
        Send(msg);
    }

    static void ReplyError(const Json &id, int code, const std::string &message) {
        Json err = Json::Object();
        err["code"] = code;
        err["message"] = message;
        Json msg = Json::Object();
        msg["jsonrpc"] = "2.0";
        msg["id"] = id;
        msg["error"] = std::move(err);
        Send(msg);
    }

    static void Notify(const std::string &method, Json params) {
        Json msg = Json::Object();
        msg["jsonrpc"] = "2.0";
        msg["method"] = method;
        msg["params"] = std::move(params);
        Send(msg);
    }

    static Json Capabilities() {
        Json sync = Json::Object();
        sync["openClose"] = true;
        sync["change"] = 1;
        sync["save"] = false;

        Json completion = Json::Object();
        completion["resolveProvider"] = false;
        Json completion_triggers = Json::Array();
        completion_triggers.push_back(".");
        completion["triggerCharacters"] = completion_triggers;

        Json signature = Json::Object();
        Json signature_triggers = Json::Array();
        for (const char *t : {"(", ","}) signature_triggers.push_back(t);
        signature["triggerCharacters"] = signature_triggers;

        Json rename = Json::Object();
        rename["prepareProvider"] = true;

        Json caps = Json::Object();
        caps["positionEncoding"] = "utf-8";
        caps["textDocumentSync"] = sync;
        caps["completionProvider"] = completion;
        caps["signatureHelpProvider"] = signature;
        caps["hoverProvider"] = true;
        caps["documentSymbolProvider"] = true;
        caps["foldingRangeProvider"] = true;
        caps["definitionProvider"] = true;
        caps["referencesProvider"] = true;
        caps["documentHighlightProvider"] = true;
        caps["renameProvider"] = rename;
        caps["documentFormattingProvider"] = true;
        caps["documentRangeFormattingProvider"] = true;

        Json info = Json::Object();
        info["name"] = "mep-fortran-lsp";
        info["version"] = "1";

        Json result = Json::Object();
        result["capabilities"] = caps;
        result["serverInfo"] = info;
        return result;
    }

    void Set(const std::string &uri, const std::string &text) {
        OpenDoc &d = docs_[uri];
        d.lines = SplitLines(text);
        const std::string path = PathOfUri(uri);
        d.analysis = index_.Analyze(d.lines, path);
        index_.SetOpen(path, d.analysis);
    }

    const OpenDoc &Doc(const std::string &uri) {
        const auto it = docs_.find(uri);
        if (it != docs_.end()) return it->second;
        Set(uri, std::string());
        return docs_[uri];
    }
    // A query's analysis, made again first when a module it USEs from another file has changed.
    const FortranLspDocument &Analysis(const Json &params) {
        const std::string uri = UriOf(params);
        const OpenDoc &d = Doc(uri);
        if (index_.Stale(*d.analysis)) {
            OpenDoc &m = docs_[uri];
            m.analysis = index_.Analyze(m.lines, PathOfUri(uri));
            index_.SetOpen(PathOfUri(uri), m.analysis);
        }
        return *docs_[uri].analysis;
    }

    static std::string UriOf(const Json &params) { return params.get("textDocument").get("uri").as_string(); }
    // file:///a/b%20c.f -> /a/b c.f (the suffix picks the source form; the directory is
    // searched for modules)
    static std::string PathOfUri(const std::string &uri) {
        std::string p = uri.compare(0, 7, "file://") == 0 ? uri.substr(7) : uri;
        const size_t q = p.find_first_of("?#");
        if (q != std::string::npos) p = p.substr(0, q);
        std::string out;
        for (size_t i = 0; i < p.size(); i++) {
            if (p[i] == '%' && i + 2 < p.size() && std::isxdigit(static_cast<unsigned char>(p[i + 1])) &&
                std::isxdigit(static_cast<unsigned char>(p[i + 2]))) {
                out += static_cast<char>(std::stoi(p.substr(i + 1, 2), nullptr, 16));
                i += 2;
            } else {
                out += p[i];
            }
        }
        return out;
    }
    static std::string UriOfPath(const std::string &path) {
        static const char *const kHex = "0123456789ABCDEF";
        std::string out = "file://";
        for (char ch : path) {
            const unsigned char c = static_cast<unsigned char>(ch);
            if (std::isalnum(c) || c == '/' || c == '-' || c == '_' || c == '.' || c == '~') {
                out += ch;
            } else {
                out += '%';
                out += kHex[c >> 4];
                out += kHex[c & 15];
            }
        }
        return out;
    }
    static int LineOf(const Json &params) { return params.get("position").get("line").as_int(); }
    static int ColOf(const Json &params) { return params.get("position").get("character").as_int(); }

    void Publish(const std::string &uri) {
        Json arr = Json::Array();
        for (const FortranLspDiagnostic &d : FortranLspDiagnostics(*Doc(uri).analysis)) {
            Json j = Json::Object();
            j["range"] = RangeOf(d.range);
            j["severity"] = static_cast<int>(d.severity);
            j["code"] = d.code;
            j["source"] = "fortran";
            j["message"] = d.message;
            if (d.unnecessary || d.deprecated) {
                Json tags = Json::Array();
                if (d.unnecessary) tags.push_back(1);
                if (d.deprecated) tags.push_back(2);
                j["tags"] = tags;
            }
            arr.push_back(j);
        }
        Json note = Json::Object();
        note["uri"] = uri;
        note["diagnostics"] = arr;
        Notify("textDocument/publishDiagnostics", note);
    }

    Json Completion(const Json &params) {
        const int line = LineOf(params);
        const std::vector<FortranLspCompletionItem> items = FortranLspCompletions(Analysis(params), line, ColOf(params));
        Json arr = Json::Array();
        for (size_t i = 0; i < items.size(); i++) {
            const FortranLspCompletionItem &it = items[i];
            Json j = Json::Object();
            j["label"] = it.label;
            j["kind"] = static_cast<int>(it.kind);
            j["insertText"] = it.insert_text;
            j["insertTextFormat"] = 1;
            if (!it.detail.empty()) j["detail"] = it.detail;
            if (!it.documentation.empty()) {
                Json doc = Json::Object();
                doc["kind"] = "markdown";
                doc["value"] = it.documentation;
                j["documentation"] = doc;
            }
            std::string sort_text = std::to_string(i);
            if (sort_text.size() < 4) sort_text.insert(0, 4 - sort_text.size(), '0');
            j["sortText"] = sort_text;
            Json range = Json::Object();
            range["start"] = Position(line, it.replace_start);
            range["end"] = Position(line, it.replace_end);
            Json edit = Json::Object();
            edit["range"] = range;
            edit["newText"] = it.insert_text;
            j["textEdit"] = edit;
            arr.push_back(j);
        }
        Json list = Json::Object();
        list["isIncomplete"] = false;
        list["items"] = arr;
        return list;
    }

    Json HoverAt(const Json &params) {
        const FortranLspHoverInfo info = FortranLspHover(Analysis(params), LineOf(params), ColOf(params));
        if (!info.found) return Json();
        Json contents = Json::Object();
        contents["kind"] = "markdown";
        contents["value"] = info.text;
        Json out = Json::Object();
        out["contents"] = contents;
        out["range"] = RangeOf(info.range);
        return out;
    }

    Json Symbols(const Json &params) {
        const std::vector<FortranLspSymbol> syms = FortranLspSymbols(Analysis(params));
        std::vector<Json> nodes(syms.size());
        for (size_t i = syms.size(); i-- > 0;) {
            const FortranLspSymbol &s = syms[i];
            Json j = Json::Object();
            j["name"] = s.name;
            if (!s.detail.empty()) j["detail"] = s.detail;
            j["kind"] = static_cast<int>(s.kind);
            j["range"] = RangeOf(s.range);
            j["selectionRange"] = RangeOf(s.sel_range);
            if (!nodes[i].is_null()) j["children"] = nodes[i];
            if (s.parent >= 0 && static_cast<size_t>(s.parent) < nodes.size()) {
                nodes[static_cast<size_t>(s.parent)].push_back(j);
            } else {
                nodes[i] = j;
            }
        }
        Json arr = Json::Array();
        for (size_t i = 0; i < syms.size(); i++) {
            if (syms[i].parent < 0 && nodes[i].is_object()) arr.push_back(nodes[i]);
        }
        return arr;
    }

    Json Folds(const Json &params) {
        Json arr = Json::Array();
        for (const FortranLspFold &f : FortranLspFolds(Analysis(params))) {
            Json j = Json::Object();
            j["startLine"] = f.start_line;
            j["endLine"] = f.end_line;
            if (!f.kind.empty()) j["kind"] = f.kind;
            arr.push_back(j);
        }
        return arr;
    }

    Json Definition(const Json &params) {
        const std::string uri = UriOf(params);
        Json arr = Json::Array();
        for (const FortranLspLocation &loc : FortranLspDefinition(Analysis(params), LineOf(params), ColOf(params))) {
            Json j = Json::Object();
            j["uri"] = loc.path.empty() ? uri : UriOfPath(loc.path);
            j["range"] = RangeOf(loc.range);
            arr.push_back(j);
        }
        if (arr.size() == 0) return Json();
        return arr;
    }

    Json References(const Json &params) {
        const std::string uri = UriOf(params);
        const bool include_declaration =
            !params.contains("context") || params.get("context").get("includeDeclaration").as_bool();
        Json arr = Json::Array();
        for (const FortranLspReference &ref : FortranLspReferences(Analysis(params), LineOf(params), ColOf(params))) {
            if (ref.is_definition && !include_declaration) continue;
            Json j = Json::Object();
            j["uri"] = uri;
            j["range"] = RangeOf(ref.range);
            arr.push_back(j);
        }
        return arr;
    }

    Json Highlights(const Json &params) {
        Json arr = Json::Array();
        for (const FortranLspReference &ref : FortranLspReferences(Analysis(params), LineOf(params), ColOf(params))) {
            Json j = Json::Object();
            j["range"] = RangeOf(ref.range);
            j["kind"] = ref.is_definition ? 3 : 2;
            arr.push_back(j);
        }
        return arr;
    }

    Json PrepareRename(const Json &params) {
        const FortranLspRenameTarget t = FortranLspPrepareRename(Analysis(params), LineOf(params), ColOf(params));
        if (!t.found) return Json();
        Json out = Json::Object();
        out["range"] = RangeOf(t.range);
        out["placeholder"] = t.placeholder;
        return out;
    }

    Json Rename(const Json &params, std::string *error) {
        const std::string uri = UriOf(params);
        const std::vector<FortranLspTextEdit> edits =
            FortranLspRename(Analysis(params), LineOf(params), ColOf(params), params.get("newName").as_string(), error);
        if (!error->empty()) return Json();
        Json changes = Json::Object();
        changes[uri] = EditsJson(edits);
        Json out = Json::Object();
        out["changes"] = changes;
        return out;
    }

    Json SignatureHelp(const Json &params) {
        const FortranLspSignatureHelp sh = FortranLspSignatureAt(Analysis(params), LineOf(params), ColOf(params));
        if (!sh.found) return Json();
        auto markdown = [](const std::string &text) {
            Json doc = Json::Object();
            doc["kind"] = "markdown";
            doc["value"] = text;
            return doc;
        };
        Json signatures = Json::Array();
        for (const FortranLspSignature &sg : sh.signatures) {
            Json parameters = Json::Array();
            for (size_t i = 0; i < sg.params.size(); i++) {
                Json p = Json::Object();
                p["label"] = sg.params[i];
                if (i < sg.param_docs.size() && !sg.param_docs[i].empty()) p["documentation"] = markdown(sg.param_docs[i]);
                parameters.push_back(p);
            }
            Json signature = Json::Object();
            signature["label"] = sg.label;
            if (!sg.documentation.empty()) signature["documentation"] = markdown(sg.documentation);
            signature["parameters"] = parameters;
            signatures.push_back(signature);
        }
        Json out = Json::Object();
        out["signatures"] = signatures;
        out["activeSignature"] = sh.active_signature;
        out["activeParameter"] = sh.active_param;
        return out;
    }
};

int Lint(const std::vector<std::string> &paths) {
    bool failed = false;
    bool unreadable = false;
    for (const std::string &path : paths) {
        std::string text;
        if (path == "-") {
            text.assign(std::istreambuf_iterator<char>(std::cin), std::istreambuf_iterator<char>());
        } else {
            bool ok = false;
            text = ReadFile(path, &ok);
            if (!ok) {
                std::fprintf(stderr, "mep-fortran-lsp: cannot read %s\n", path.c_str());
                unreadable = true;
                continue;
            }
        }
        const auto doc = FortranLspAnalyze(SplitLines(fortran::DecodeSource(text)), path == "-" ? "stdin.f90" : path);
        for (const FortranLspDiagnostic &d : FortranLspDiagnostics(*doc)) {
            std::printf("%s\n", FortranLspFormatDiagnostic(path, d).c_str());
            if (FortranLspDiagnosticFails(d)) failed = true;
        }
    }
    if (unreadable) return 2;
    return failed ? 1 : 0;
}

// --intrinsic NAME: every vocabulary entry named NAME (an intrinsic and the keyword
// it shares a name with, or the same name in two intrinsic modules), blank-line separated.
int DescribeIntrinsic(const std::string &name) {
    std::string lower;
    for (char c : name) lower += static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    size_t count = 0;
    const FortranVocabEntry *all = FortranVocab(&count);
    const FortranVocabEntry *e = FortranVocabFind(lower.c_str(), lower.size());
    if (!e) return 1;
    static const char *const kKinds[] = {"function", "subroutine", "constant", "type", "module", "keyword"};
    for (bool first = true; e < all + count && lower == e->name; ++e, first = false) {
        if (!first) std::printf("\n");
        if (e->signature[0]) std::printf("%s\n\n", e->signature);
        else std::printf("%s\n\n", e->name);
        const std::string what = e->klass[0] ? e->klass : kKinds[static_cast<int>(e->kind)];
        std::printf("%s", what.c_str());
        if (e->module[0]) std::printf(" from module %s", e->module);
        if (e->standard[0]) std::printf(" (%s)", e->standard);
        if (e->generic[0]) std::printf(", a specific name of %s", e->generic);
        std::printf("\n%s\n", e->summary);
    }
    return 0;
}

