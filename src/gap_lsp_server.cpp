// `mep-gap-lsp`: the wire half of mep's own GAP language server, and a
// command-line linter. Speaks LSP over stdio; every answer comes from
// gap_lsp.h's pure analysis functions.
//
//   mep-gap-lsp                    the language server on stdio
//   mep-gap-lsp --lint FILE...     diagnostics as path:line:col: severity: message [code];
//                                     exit 1 on any error or warning ('-' reads stdin);
//                                     names the file's package binds elsewhere count as bound
//
// Single-threaded and synchronous; Content-Length framing via
// rpc_framing.h, full text sync, `positionEncoding: "utf-8"`.
// Generated by tools/new_language.py from nix_lsp_server.cpp.
