// `mep-go-lsp`: the wire half of mep's own Go language server, and a
// command-line linter. Speaks LSP over stdio; every answer comes from
// go_lsp.h's pure analysis functions.
//
//   mep-go-lsp                    the language server on stdio
//   mep-go-lsp --lint FILE...     diagnostics as path:line:col: severity: message [code];
//                                     exit 1 on any error or warning ('-' reads stdin)
//   mep-go-lsp --doc NAME [--dir DIR] [--file FILE]...
//                                 NAME's doc comment as Markdown, in go doc's forms (pkg,
//                                     pkg.Name, pkg.Type.Method, Name, an import path), read
//                                     from the workspace, replace dirs, vendor/, the module
//                                     cache and GOROOT (go_lsp_pkgdoc.h); exit 1 when none
//   mep-go-lsp --exports [PKG] [--dir DIR] [--all]
//                                 the package's exported names (--all: every top-level
//                                     name): kind TAB name TAB signature TAB file:line
//                                     (PKG: a directory or import path)
//
// Hover on `pkg.Name` that the one-file analysis cannot answer (a
// workspace or dependency package) reads that package's doc comments.
//
// Single-threaded and synchronous; Content-Length framing via
// rpc_framing.h, full text sync, `positionEncoding: "utf-8"`.
// Generated by tools/new_language.py from nix_lsp_server.cpp.
