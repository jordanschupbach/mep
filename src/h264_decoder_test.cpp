// FNV-1a 64 of the 8 decoded frames (I420, output order) as AVFoundation decodes them.
constexpr uint64_t kTinyBaselineHash = 0x853cb4c07c27eda7ull;
constexpr uint64_t kTinyHighHash = 0xeaa49f78bfcb688eull;

uint64_t Fnv(uint64_t h, const std::vector<uint8_t> &bytes) {
    for (uint8_t b : bytes) h = (h ^ b) * 0x100000001b3ull;
    return h;
}

// Splits an Annex B stream into access units (a new one at an AUD, SPS,
// PPS or SEI after a slice, or at a slice starting the picture).
std::vector<std::vector<uint8_t>> AccessUnits(const uint8_t *s, size_t n) {
    std::vector<std::pair<size_t, size_t>> nals;
    size_t start = SIZE_MAX;
    for (size_t i = 0; i + 3 <= n;) {
        if (s[i] == 0 && s[i + 1] == 0 && s[i + 2] == 1) {
            if (start != SIZE_MAX) {
                size_t e = i;
                while (e > start && s[e - 1] == 0) --e;
                nals.push_back({start, e});
            }
            start = i + 3;
            i += 3;
        } else {
            ++i;
        }
    }
    if (start != SIZE_MAX) nals.push_back({start, n});
    std::vector<std::vector<uint8_t>> aus(1);
    bool has_slice = false;
    for (auto [b, e] : nals) {
        if (e <= b) continue;
        const int type = s[b] & 31;
        const bool slice = type >= 1 && type <= 5;
        // first_mb_in_slice == 0 shows as a 1 in the bit after the header byte.
        const bool first = slice && e - b > 1 && (s[b + 1] & 0x80);
        if (has_slice && ((slice && first) || (type >= 6 && type <= 9))) {
            aus.emplace_back();
            has_slice = false;
        }
        static const uint8_t kStart[3] = {0, 0, 1};
        aus.back().insert(aus.back().end(), kStart, kStart + 3);
        aus.back().insert(aus.back().end(), s + b, s + e);
        has_slice |= slice;
    }
    return aus;
}

// Decodes an Annex B stream; returns the frames' hash and count.
uint64_t DecodeStream(const uint8_t *s, size_t n, int *frames, int *errors, std::vector<std::vector<uint8_t>> *out = nullptr) {
    h264::Decoder dec;
    uint64_t h = 0xcbf29ce484222325ull;
    *frames = *errors = 0;
    auto drain = [&] {
        h264::Picture p;
        while (dec.GetPicture(&p)) {
            h = Fnv(Fnv(Fnv(h, p.y), p.u), p.v);
            if (out) {
                std::vector<uint8_t> f = p.y;
                f.insert(f.end(), p.u.begin(), p.u.end());
                f.insert(f.end(), p.v.begin(), p.v.end());
                out->push_back(std::move(f));
            }
            ++*frames;
        }
    };
    for (const std::vector<uint8_t> &au : AccessUnits(s, n)) {
        std::string err;
        if (!dec.DecodeAnnexB(au.data(), au.size(), *frames, &err)) ++*errors;
        drain();
    }
    dec.Flush();
    drain();
    return h;
}

