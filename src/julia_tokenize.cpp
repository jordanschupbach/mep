template <class F> bool Lexer::accept_number(F f) {
    bool lexed_number = false;
    while (true) {
        JChar pc = peekchar(), ppc = dpeekchar2();
        if (pc == C('_') && !f(ppc)) {
            return lexed_number;
        } else if (f(pc) || pc == C('_')) {
            readchar();
        } else {
            return lexed_number;
        }
        lexed_number = true;
    }
}

RawToken Lexer::lex_digit(Kind kind) {
    auto isdig = [](JChar c) { return isdigit(c); };
    accept_number(isdig);
    JChar pc = peekchar(), ppc = dpeekchar2();
    auto is_exp_start = [](JChar p, JChar pp) {
        return (p == C('e') || p == C('E') || p == C('f')) &&
               (isdigit(pp) || pp == C('+') || pp == C('-') || pp == C(0x2212));
    };
    if (pc == C('.')) {
        if (ppc == C('.')) {
            return emit(kind);
        } else if (kind == K("Float")) {
            readchar();
            return emit(K("ErrorInvalidNumericConstant"));
        } else if (is_dottable_operator_start_char(ppc)) {
            readchar();
            return emit(K("ErrorAmbiguousNumericConstant"));  // `1.+`
        }
        readchar();

        kind = K("Float");
        if (accept(C('_'))) return emit(K("ErrorInvalidNumericConstant"));  // `1._`
        bool had_fraction_digs = accept_number(isdig);
        pc = peekchar();
        ppc = dpeekchar2();
        if (is_exp_start(pc, ppc)) {
            kind = pc == C('f') ? K("Float32") : K("Float");
            readchar();
            accept_str(U"+-−");
            if (accept_batch(isdig)) {
                pc = peekchar();
                ppc = dpeekchar2();
                if (pc == C('.') && !is_dottable_operator_start_char(ppc)) {
                    readchar();
                    return emit(K("ErrorInvalidNumericConstant"));  // `1.e1.`
                }
            } else {
                return emit(K("ErrorInvalidNumericConstant"));  // `1.e`
            }
        } else if (pc == C('.') && ppc != C('.') && !is_dottable_operator_start_char(ppc)) {
            readchar();
            return emit(K("ErrorInvalidNumericConstant"));  // `1.1.`
        } else if (!had_fraction_digs && (is_identifier_start_char(pc) || pc == C('(') || pc == C('[') ||
                                          pc == C('{') || pc == C('@') || pc == C('`') || pc == C('"'))) {
            return emit(K("ErrorAmbiguousNumericDotMultiply"));  // `1.(` `1.x`
        }
    } else if (is_exp_start(pc, ppc)) {
        kind = pc == C('f') ? K("Float32") : K("Float");
        readchar();
        accept_str(U"+-−");
        if (accept_batch(isdig)) {
            pc = peekchar();
            ppc = dpeekchar2();
            if (pc == C('.') && !is_dottable_operator_start_char(ppc)) {
                accept(C('.'));
                return emit(K("ErrorInvalidNumericConstant"));  // `1e1.`
            }
        } else {
            return emit(K("ErrorInvalidNumericConstant"));  // `1e+`
        }
    } else if (position() - startpos() == 1 && chars_[0] == C('0')) {
        bool is_bin_oct_hex_int = false;
        bool had_digits = false;
        if (pc == C('x')) {
            kind = K("HexInt");
            bool isfloat = false;
            readchar();
            had_digits = accept_number(ishex);
            pc = peekchar();
            ppc = dpeekchar2();
            if (pc == C('.') && ppc != C('.')) {
                readchar();
                had_digits = accept_number(ishex) || had_digits;
                isfloat = true;
            }
            if (accept_str(U"pP")) {
                kind = K("Float");
                accept_str(U"+-−");
                if (!accept_number(isdig) || !had_digits)
                    return emit(K("ErrorInvalidNumericConstant"));  // `0x1p` `0x.p0`
            } else if (isfloat) {
                return emit(K("ErrorHexFloatMustContainP"));  // `0x.` `0x1.0`
            }
            is_bin_oct_hex_int = !isfloat;
        } else if (pc == C('b')) {
            readchar();
            had_digits = accept_number(isbinary);
            kind = K("BinInt");
            is_bin_oct_hex_int = true;
        } else if (pc == C('o')) {
            readchar();
            had_digits = accept_number(isoctal);
            kind = K("OctInt");
            is_bin_oct_hex_int = true;
        }
        if (is_bin_oct_hex_int) {
            pc = peekchar();
            if (!had_digits || isdigit(pc) || is_identifier_start_char(pc)) {
                accept_batch([](JChar c) { return isdigit(c) || is_identifier_start_char(c); });
                return emit(K("ErrorInvalidNumericConstant"));
            }
        }
    }
    return emit(kind);
}

RawToken Lexer::lex_prime() {
    Kind lt = last_token_;
    if (lt == K("Identifier") || is_contextual_keyword(lt) || is_word_operator(lt) || lt == K(".") ||
        lt == K(")") || lt == K("]") || lt == K("}") || lt == K("'") || lt == K("end") || is_literal(lt)) {
        return emit(K("'"));
    } else {
        string_states_.push_back(StringState{false, true, C('\''), 0});
        return emit(K("'"), false);
    }
}

RawToken Lexer::lex_amper() {
    if (accept(C('&'))) return emit(K("&&"));
    if (accept(C('='))) return emit(K("&="));
    return emit(K("&"));
}

RawToken Lexer::lex_quote() {
    bool raw = last_token_ == K("Identifier") || is_contextual_keyword(last_token_) || is_word_operator(last_token_);
    JChar pc = peekchar(), dpc = dpeekchar2();
    bool triplestr = pc == C('"') && dpc == C('"');
    string_states_.push_back(StringState{triplestr, raw, C('"'), 0});
    if (triplestr) {
        readchar();
        readchar();
        return emit(K("\"\"\""));
    }
    return emit(K("\""));
}

bool Lexer::string_terminates(JChar delim, bool triplestr) const {
    if (triplestr) return chars_[1] == delim && chars_[2] == delim && chars_[3] == delim;
    return chars_[1] == delim;
}

RawToken Lexer::lex_forwardslash() {
    if (accept(C('/'))) {
        if (accept(C('='))) return emit(K("//="));
        return emit(K("//"));
    } else if (accept(C('='))) {
        return emit(K("/="));
    }
    return emit(K("/"));
}

RawToken Lexer::lex_backslash() {
    if (accept(C('='))) return emit(K("\\="));
    return emit(K("\\"));
}

RawToken Lexer::lex_dot() {
    if (accept(C('.'))) {
        if (accept(C('.'))) return emit(K("..."));
        if (is_dottable_operator_start_char(peekchar())) {
            readchar();
            return emit(K("ErrorInvalidOperator"));
        }
        return emit(K(".."));
    } else if (isdigit(peekchar())) {
        return lex_digit(K("Float"));
    } else {
        JChar pc = peekchar(), dpc = dpeekchar2();
        if (pc == C('+')) {
            dotop_ = true;
            readchar();
            return lex_plus();
        } else if (pc == C('-')) {
            dotop_ = true;
            readchar();
            return lex_minus();
        } else if (pc == C(0x2212)) {
            dotop_ = true;
            readchar();
            return emit(accept(C('=')) ? K("-=") : K("-"));
        } else if (pc == C('*')) {
            dotop_ = true;
            readchar();
            return lex_star();
        } else if (pc == C('/')) {
            dotop_ = true;
            readchar();
            return lex_forwardslash();
        } else if (pc == C('\\')) {
            dotop_ = true;
            readchar();
            return lex_backslash();
        } else if (pc == C('^')) {
            dotop_ = true;
            readchar();
            return lex_circumflex();
        } else if (pc == C('<')) {
            dotop_ = true;
            readchar();
            return lex_less();
        } else if (pc == C('>')) {
            dotop_ = true;
            readchar();
            return lex_greater();
        } else if (pc == C('&')) {
            dotop_ = true;
            readchar();
            if (accept(C('='))) return emit(K("&="));
            if (accept(C('&'))) return emit(K("&&"));
            return emit(K("&"));
        } else if (pc == C('%')) {
            dotop_ = true;
            readchar();
            return lex_percent();
        } else if (pc == C('=') && dpc != C('>')) {
            dotop_ = true;
            readchar();
            return lex_equal();
        } else if (pc == C('|')) {
            dotop_ = true;
            readchar();
            if (accept(C('|'))) return emit(K("||"));
            return lex_bar();
        } else if (pc == C('!') && dpc == C('=')) {
            dotop_ = true;
            readchar();
            return lex_exclaim();
        } else if (pc == C(0x22bb)) {
            dotop_ = true;
            readchar();
            return lex_xor();
        } else if (pc == C(0xf7)) {
            dotop_ = true;
            readchar();
            return lex_division();
        } else if (pc == C('=') && dpc == C('>')) {
            dotop_ = true;
            readchar();
            return lex_equal();
        } else if (is_dottable_operator_start_char(pc)) {
            dotop_ = true;
            return _next_token(readchar());
        }
        return emit(K("."));
    }
}

RawToken Lexer::lex_backtick() {
    JChar pc = peekchar(), dpc = dpeekchar2();
    bool triplestr = pc == C('`') && dpc == C('`');
    string_states_.push_back(StringState{triplestr, true, C('`'), 0});
    if (triplestr) {
        readchar();
        readchar();
        return emit(K("```"));
    }
    return emit(K("`"));
}

