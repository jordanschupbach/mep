template <size_t N> uint32_t RunLookup(const uint32_t (&runs)[N][2], uint32_t cp) {
    // last run whose start <= cp
    size_t lo = 0, hi = N;
    while (hi - lo > 1) {
        size_t mid = (lo + hi) / 2;
        if (runs[mid][0] <= cp)
            lo = mid;
        else
            hi = mid;
    }
    return runs[lo][1];
}

