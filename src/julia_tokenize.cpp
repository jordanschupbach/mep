bool isopsuffix(JChar c) {
    if (c == kEofChar) return false;
    if (!isvalid(c)) return false;
    uint32_t u = codepoint(c);
    if (u < 0xa1 || u > 0x10ffff) return false;
    int cat = category_code(c);
    if (cat == CAT_MN || cat == CAT_MC || cat == CAT_ME) return true;
    return kOpSuffixChars.find(static_cast<char32_t>(u)) != std::u32string_view::npos;
}

bool optakessuffix(Kind k) {
    return is_operator(k) &&
           !(k == K("...") || is_prec_assignment(k) || k == K("?") || k == K("<:") || k == K(">:") ||
             k == K("&&") || k == K("||") || k == K("in") || k == K("isa") || k == K("≔") || k == K("⩴") ||
             k == K(":") || k == K("..") || k == K("$") || k == K("::") || k == K("where") || k == K(".") ||
             k == K("!") || k == K(".'") || k == K("->") || KindIn(k, K("¬"), K("∜")));
}

static bool ishex(JChar c) {
    return isdigit(c) || (C('a') <= c && c <= C('f')) || (C('A') <= c && c <= C('F'));
}
static bool isbinary(JChar c) { return c == C('0') || c == C('1'); }
static bool isoctal(JChar c) { return C('0') <= c && c <= C('7'); }
static bool iswhitespace(JChar c) { return (isvalid(c) && isspace(c)) || c == C(0xfeff); }

