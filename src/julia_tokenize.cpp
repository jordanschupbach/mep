Lexer::Lexer(std::string_view text, size_t start) : text_(text), io_pos_(start) {
    JChar c1 = C(' ');
    int64_t p1 = static_cast<int64_t>(io_pos_);
    chars_[0] = c1;
    charspos_[0] = p1;
    for (int k = 1; k < 4; ++k) {
        chars_[k] = io_readchar();
        charspos_[k] = static_cast<int64_t>(io_pos_);
    }
    token_startpos_ = static_cast<int64_t>(io_pos_);
}

JChar Lexer::io_readchar() {
    if (io_pos_ >= text_.size()) return kEofChar;
    size_t len = 0;
    JChar c = ReadCharIO(text_, io_pos_, &len);
    io_pos_ += len;
    return c;
}

JChar Lexer::readchar() {
    JChar c = io_readchar();
    chars_[0] = chars_[1];
    chars_[1] = chars_[2];
    chars_[2] = chars_[3];
    chars_[3] = c;
    charspos_[0] = charspos_[1];
    charspos_[1] = charspos_[2];
    charspos_[2] = charspos_[3];
    charspos_[3] = static_cast<int64_t>(io_pos_);
    return chars_[0];
}

bool Lexer::accept(JChar f) {
    bool ok = peekchar() == f;
    if (ok) readchar();
    return ok;
}

bool Lexer::accept_str(std::u32string_view set) {
    JChar c = peekchar();
    bool ok = false;
    for (char32_t s : set)
        if (C(s) == c) ok = true;
    if (ok) readchar();
    return ok;
}

template <class F> bool Lexer::accept_f(F f) {
    bool ok = f(peekchar());
    if (ok) readchar();
    return ok;
}

template <class F> bool Lexer::accept_batch(F f) {
    bool ok = false;
    while (accept_f(f)) ok = true;
    return ok;
}

RawToken Lexer::emit(Kind kind, bool maybe_op) {
    bool suffix = false;
    if (optakessuffix(kind) && maybe_op) {
        while (isopsuffix(peekchar())) {
            readchar();
            suffix = true;
        }
    }
    RawToken tok{kind, startpos(), position() - 1, dotop_, suffix};
    dotop_ = false;
    last_token_ = kind;
    return tok;
}

RawToken Lexer::next_token(bool start) {
    if (start) start_token();
    if (!string_states_.empty()) return lex_string_chunk();
    return _next_token(readchar());
}

RawToken Lexer::_next_token(JChar c) {
    if (c == kEofChar) return emit(K("EndMarker"));
    if (iswhitespace(c)) return lex_whitespace(c);
    if (c == C('[')) return emit(K("["));
    if (c == C(']')) return emit(K("]"));
    if (c == C('{')) return emit(K("{"));
    if (c == C(';')) return emit(K(";"));
    if (c == C('}')) return emit(K("}"));
    if (c == C('(')) return emit(K("("));
    if (c == C(')')) return emit(K(")"));
    if (c == C(',')) return emit(K(","));
    if (c == C('*')) return lex_star();
    if (c == C('^')) return lex_circumflex();
    if (c == C('@')) return emit(K("@"));
    if (c == C('?')) return emit(K("?"));
    if (c == C('$')) return lex_dollar();
    if (c == C(0x22bb)) return lex_xor();  // ⊻
    if (c == C('~')) return emit(K("~"));
    if (c == C('#')) return lex_comment();
    if (c == C('=')) return lex_equal();
    if (c == C('!')) return lex_exclaim();
    if (c == C('>')) return lex_greater();
    if (c == C('<')) return lex_less();
    if (c == C(':')) return lex_colon();
    if (c == C('|')) return lex_bar();
    if (c == C('&')) return lex_amper();
    if (c == C('\'')) return lex_prime();
    if (c == C(0xf7)) return lex_division();  // ÷
    if (c == C('"')) return lex_quote();
    if (c == C('%')) return lex_percent();
    if (c == C('/')) return lex_forwardslash();
    if (c == C('\\')) return lex_backslash();
    if (c == C('.')) return lex_dot();
    if (c == C('+')) return lex_plus();
    if (c == C('-')) return lex_minus();
    if (c == C(0x2212)) return emit(accept(C('=')) ? K("-=") : K("-"));  // − \minus
    if (c == C('`')) return lex_backtick();
    if (is_identifier_start_char(c)) return lex_identifier(c);
    if (isdigit(c)) return lex_digit(K("Integer"));
    Kind k = UnicodeOp(c);
    if (k != K("error")) return emit(k);
    return emit(!isvalid(c)              ? K("ErrorInvalidUTF8")
                : is_invisible_char(c) ? K("ErrorInvisibleChar")
                                       : K("ErrorUnknownCharacter"));
}

namespace {
struct Bidi {
    int embedding = 0, isolate = 0;
    bool operator!=(const Bidi &o) const { return embedding != o.embedding || isolate != o.isolate; }
};
Bidi update_bidi_state(Bidi s, JChar c) {
    if (c == C('\n')) {
        s.embedding = 0;
        s.isolate = 0;
    } else if (c == C(0x202A) || c == C(0x202B) || c == C(0x202D) || c == C(0x202E)) {
        s.embedding += 1;
    } else if (c == C(0x202C)) {
        s.embedding -= 1;
    } else if (c == C(0x2066) || c == C(0x2067) || c == C(0x2068)) {
        s.isolate += 1;
    } else if (c == C(0x2069)) {
        s.isolate -= 1;
    }
    return s;
}
}  // namespace

RawToken Lexer::lex_string_chunk() {
    StringState state = string_states_.back();
    if (state.paren_depth > 0) {
        JChar c = readchar();
        if (c == C('(')) {
            string_states_.back().paren_depth = state.paren_depth + 1;
            return emit(K("("));
        } else if (c == C(')')) {
            string_states_.back().paren_depth = state.paren_depth - 1;
            return emit(K(")"));
        } else {
            return _next_token(c);
        }
    }
    JChar pc = peekchar();
    if (last_token_ == K("$")) {
        pc = peekchar();
        if (pc == C('(')) {
            readchar();
            string_states_.back().paren_depth = state.paren_depth + 1;
            return emit(K("("));
        } else if (is_identifier_start_char(pc)) {
            return lex_identifier(readchar());
        }
        // else: syntax error, fall through to reading string characters
    } else if (last_token_ == K("Identifier") &&
               !(pc == kEofChar || is_operator_start_char(pc) || is_never_id_char(pc))) {
        readchar();
        return emit(K("ErrorInvalidInterpolationTerminator"));
    }
    if (pc == kEofChar) {
        return emit(K("EndMarker"));
    } else if (!state.raw && pc == C('$')) {
        readchar();
        return emit(K("$"));
    } else if (!state.raw && pc == C('\\') && (dpeekchar2() == C('\r') || dpeekchar2() == C('\n'))) {
        JChar pc2 = dpeekchar2();
        readchar();
        readchar();
        if (pc2 == C('\r') && peekchar() == C('\n')) readchar();
        while (true) {
            pc = peekchar();
            if (!(pc == C(' ') || pc == C('\t'))) break;
            readchar();
        }
        return emit(K("Whitespace"));
    } else if (pc == state.delim && string_terminates(state.delim, state.triplestr)) {
        if (state.delim == C('\'') && last_token_ == K("'") && dpeekchar2() == C('\'')) {
            readchar();
            return emit(K("Char"));
        }
        string_states_.pop_back();
        readchar();
        if (state.triplestr) {
            readchar();
            readchar();
            return emit(state.delim == C('"') ? K("\"\"\"") : K("```"));
        } else {
            return emit(state.delim == C('"') ? K("\"") : state.delim == C('`') ? K("`") : K("'"), false);
        }
    }
    // Read a chunk of string characters
    const Bidi init_bidi_state{};
    Bidi bidi_state = init_bidi_state;
    bool valid = true;
    if (state.raw) {
        while (true) {
            pc = peekchar();
            if (string_terminates(state.delim, state.triplestr) || pc == kEofChar) {
                break;
            } else if (state.triplestr && (pc == C('\n') || pc == C('\r'))) {
                readchar();
                if (pc == C('\n')) {
                    bidi_state = init_bidi_state;
                } else if (pc == C('\r') && peekchar() == C('\n')) {
                    bidi_state = init_bidi_state;
                    readchar();
                }
                break;
            }
            JChar c = readchar();
            if (c == C('\\')) {
                int n = 1;
                while (peekchar() == C('\\')) {
                    readchar();
                    n += 1;
                }
                if (peekchar() == state.delim && (n % 2) != 0) readchar();
            }
            bidi_state = update_bidi_state(bidi_state, c);
            valid = valid && isvalid(c);
        }
    } else {
        while (true) {
            pc = peekchar();
            if (pc == C('$') || pc == kEofChar) {
                break;
            } else if (state.triplestr && (pc == C('\n') || pc == C('\r'))) {
                readchar();
                if (pc == C('\n')) {
                    bidi_state = init_bidi_state;
                } else if (pc == C('\r') && peekchar() == C('\n')) {
                    readchar();
                    bidi_state = init_bidi_state;
                }
                break;
            } else if (pc == state.delim && string_terminates(state.delim, state.triplestr)) {
                break;
            } else if (pc == C('\\')) {
                JChar pc2 = dpeekchar2(), pc3 = peekchar3();
                if (pc2 == C('\r') || pc2 == C('\n')) {
                    if (pc2 == C('\n') || pc3 == C('\n')) bidi_state = init_bidi_state;
                    break;
                }
            }
            JChar c = readchar();
            if (c == C('\\')) {
                c = readchar();
                if (c == kEofChar) break;
            }
            bidi_state = update_bidi_state(bidi_state, c);
            valid = valid && isvalid(c);
        }
    }
    Kind outk = !valid                         ? K("ErrorInvalidUTF8")
                : state.delim == C('\'')       ? K("Char")
                : bidi_state != init_bidi_state ? K("ErrorBidiFormatting")
                : state.delim == C('"')        ? K("String")
                : state.delim == C('`')        ? K("CmdString")
                                               : K("error");
    return emit(outk);
}

RawToken Lexer::lex_whitespace(JChar c) {
    Kind k = K("Whitespace");
    while (true) {
        if (c == C('\n')) k = K("NewlineWs");
        JChar pc = peekchar(), ppc = dpeekchar2();
        if (!iswhitespace(pc) || (k == K("NewlineWs") && (pc == C('\n') || (pc == C('\r') && ppc == C('\n')))))
            break;
        c = readchar();
    }
    return emit(k);
}

RawToken Lexer::lex_comment() {
    if (peekchar() != C('=')) {
        bool valid = true;
        while (true) {
            JChar pc = peekchar(), ppc = dpeekchar2();
            if (pc == C('\n') || (pc == C('\r') && ppc == C('\n')) || pc == kEofChar)
                return emit(valid ? K("Comment") : K("ErrorInvalidUTF8"));
            valid = valid && isvalid(pc);
            readchar();
        }
    } else {
        JChar c = readchar();  // consume the '='
        const Bidi init_bidi_state{};
        Bidi bidi_state = init_bidi_state;
        bool skip = true;
        int nesting = 1;
        bool valid = true;
        while (true) {
            if (c == kEofChar) return emit(K("ErrorEofMultiComment"));
            JChar nc = readchar();
            bidi_state = update_bidi_state(bidi_state, nc);
            valid = valid && isvalid(nc);
            if (skip) {
                skip = false;
            } else {
                if (c == C('#') && nc == C('=')) {
                    nesting += 1;
                    skip = true;
                } else if (c == C('=') && nc == C('#')) {
                    nesting -= 1;
                    skip = true;
                    if (nesting == 0) {
                        Kind outk = !valid                          ? K("ErrorInvalidUTF8")
                                    : bidi_state != init_bidi_state ? K("ErrorBidiFormatting")
                                                                    : K("Comment");
                        return emit(outk);
                    }
                }
            }
            c = nc;
        }
    }
}

RawToken Lexer::lex_greater() {
    if (accept(C('>'))) {
        if (accept(C('>'))) {
            if (accept(C('='))) return emit(K(">>>="));
            return emit(K(">>>"));
        } else if (accept(C('='))) {
            return emit(K(">>="));
        } else {
            return emit(K(">>"));
        }
    } else if (accept(C('='))) {
        return emit(K(">="));
    } else if (accept(C(':'))) {
        return emit(K(">:"));
    } else {
        return emit(K(">"));
    }
}

RawToken Lexer::lex_less() {
    if (accept(C('<'))) {
        if (accept(C('='))) return emit(K("<<="));
        return emit(K("<<"));
    } else if (accept(C('='))) {
        return emit(K("<="));
    } else if (accept(C(':'))) {
        return emit(K("<:"));
    } else if (accept(C('|'))) {
        return emit(K("<|"));
    } else if (peekchar() == C('-') && dpeekchar2() == C('-')) {
        readchar();
        readchar();
        if (accept(C('-'))) {
            return emit(K("ErrorInvalidOperator"));
        } else {
            if (accept(C('>'))) {
                return emit(K("<-->"));
            } else if (accept(C('-'))) {
                return emit(K("ErrorInvalidOperator"));
            } else {
                return emit(K("<--"));
            }
        }
    } else {
        return emit(K("<"));
    }
}

