// Characters (Julia's base/char.jl and strings/unicode.jl)

bool ismalformed(JChar u) {
    int l1 = leading_ones(u) << 3;
    int t0 = trailing_zeros(u) & 56;
    uint32_t tail = (u & 0x00c0c0c0u) ^ 0x00808080u;
    uint32_t shifted = t0 >= 32 ? 0 : (tail >> t0);
    return (l1 == 8) || (l1 + t0 > 32) || (shifted != 0);
}

static bool is_overlong_enc(uint32_t u) {
    return (u >> 24 == 0xc0) || (u >> 24 == 0xc1) || (u >> 21 == 0x0704) || (u >> 20 == 0x0f08);
}

bool isoverlong(JChar c) { return is_overlong_enc(c); }

bool isvalid(JChar c) {
    return !ismalformed(c) && !isoverlong(c) && ((c <= C(0xd7ff)) || ((C(0xe000) <= c) && (c <= C(0x10ffff))));
}

uint32_t codepoint(JChar c) {
    uint32_t u = c;
    if (u < 0x80000000u) return u >> 24;
    int l1 = leading_ones(u);
    int t0 = trailing_zeros(u) & 56;
    u &= l1 >= 32 ? 0u : (0xffffffffu >> l1);
    u = t0 >= 32 ? 0u : (u >> t0);
    return ((u & 0x0000007fu) >> 0) | ((u & 0x00007f00u) >> 2) | ((u & 0x007f0000u) >> 4) | ((u & 0x7f000000u) >> 6);
}

int ncodeunits(JChar c) {
    uint32_t u = c;
    // number of non-zero trailing bytes: Julia's ncodeunits(c::Char)
    int n = 4 - (trailing_zeros(u) >> 3);
    return n < 1 ? 1 : n;
}

int category_code(JChar c) {
    if (ismalformed(c)) return 31;
    if (isoverlong(c)) return 31;  // UInt32(c) would throw in Julia; never reached by callers
    uint32_t cp = codepoint(c);
    if (cp > 0x10ffff) return 30;
    return static_cast<int>(RunLookup(kCategoryRuns, cp));
}

bool isprint(JChar c) {
    int cat = category_code(c);
    return CAT_LU <= cat && cat <= CAT_ZS;
}

bool isspace(JChar c) {
    return c == C(' ') || (C('\t') <= c && c <= C('\r')) || c == C(0x85) ||
           (C(0xa0) <= c && category_code(c) == CAT_ZS);
}

JChar ReadCharIO(std::string_view s, size_t pos, size_t *len) {
    // read(io::IO, ::Type{Char})
    uint8_t b0 = static_cast<uint8_t>(s[pos]);
    int lo = std::countl_one(b0);
    uint8_t l = static_cast<uint8_t>(0x08 * static_cast<uint8_t>(0x04 - lo));
    uint32_t c = static_cast<uint32_t>(b0) << 24;
    size_t i = pos + 1;
    if (l <= 0x10) {
        int sh = 16;
        while (sh >= l && i < s.size()) {
            uint8_t b = static_cast<uint8_t>(s[i]);
            if ((b & 0xc0) != 0x80) break;
            c |= static_cast<uint32_t>(b) << sh;
            ++i;
            sh -= 8;
        }
    }
    *len = i - pos;
    return c;
}

JChar ReadCharStr(std::string_view s, size_t pos, size_t *len) {
    // iterate(::String, i) / iterate_continued
    size_t n = s.size();
    size_t i = pos;
    uint32_t u = static_cast<uint32_t>(static_cast<uint8_t>(s[i])) << 24;
    if (u < 0xc0000000u) {
        *len = 1;
        return u;
    }
    do {
        if (++i >= n) break;
        uint8_t b = static_cast<uint8_t>(s[i]);
        if ((b & 0xc0) != 0x80) break;
        u |= static_cast<uint32_t>(b) << 16;
        if (++i >= n || u < 0xe0000000u) break;
        b = static_cast<uint8_t>(s[i]);
        if ((b & 0xc0) != 0x80) break;
        u |= static_cast<uint32_t>(b) << 8;
        if (++i >= n || u < 0xf0000000u) break;
        b = static_cast<uint8_t>(s[i]);
        if ((b & 0xc0) != 0x80) break;
        u |= static_cast<uint32_t>(b);
        ++i;
    } while (false);
    *len = i - pos;
    return u;
}

bool BaseIsIdStartChar(JChar c) { return RunLookup(kIdStartRuns, codepoint(c)) != 0; }
bool BaseIsIdChar(JChar c) { return RunLookup(kIdCharRuns, codepoint(c)) != 0; }

static void PutUtf8(std::string &out, JChar c) {
    int n = ncodeunits(c);
    for (int k = 0; k < n; ++k) out.push_back(static_cast<char>((c >> (24 - 8 * k)) & 0xff));
}

static const char kHexChars[] = "0123456789abcdef";

static void PutHex(std::string &out, uint32_t v, int pad) {
    char buf[16];
    int n = 0;
    do {
        buf[n++] = kHexChars[v & 0xf];
        v >>= 4;
    } while (v != 0);
    for (int k = n; k < pad; ++k) out.push_back('0');
    while (n > 0) out.push_back(buf[--n]);
}

std::string ReprChar(JChar c) {
    std::string out;
    if (c <= C('\\')) {
        char b = c == C('\0') ? '0'
                 : c == C('\a') ? 'a'
                 : c == C('\b') ? 'b'
                 : c == C('\t') ? 't'
                 : c == C('\n') ? 'n'
                 : c == C('\v') ? 'v'
                 : c == C('\f') ? 'f'
                 : c == C('\r') ? 'r'
                 : c == C(0x1b) ? 'e'
                 : c == C('\'') ? '\''
                 : c == C('\\') ? '\\'
                                : '\xff';
        if (b != '\xff') {
            out = "'\\";
            out.push_back(b);
            out.push_back('\'');
            return out;
        }
    }
    if (isoverlong(c) || ismalformed(c)) {
        out.push_back('\'');
        uint32_t u = c;
        while (true) {
            out += "\\x";
            out.push_back(kHexChars[(u >> 28) & 0xf]);
            out.push_back(kHexChars[(u >> 24) & 0xf]);
            u <<= 8;
            if (u == 0) break;
        }
        out.push_back('\'');
    } else if (isprint(c)) {
        out.push_back('\'');
        PutUtf8(out, c);
        out.push_back('\'');
    } else {
        uint32_t u = codepoint(c);
        out.push_back('\'');
        out.push_back('\\');
        out.push_back(u <= 0x7f ? 'x' : u <= 0xffff ? 'u' : 'U');
        int d = std::max(2, 8 - (std::countl_zero(u) >> 2));
        while (0 < d) {
            d -= 1;
            out.push_back(kHexChars[(u >> (d << 2)) & 0xf]);
        }
        out.push_back('\'');
    }
    return out;
}

static bool isxdigit(JChar c) {
    return (C('0') <= c && c <= C('9')) || (C('a') <= c && c <= C('f')) || (C('A') <= c && c <= C('F'));
}

std::string ReprString(std::string_view s) {
    // print_quoted: escape_string(io, s, ('"', '$')) between quotes
    std::string out = "\"";
    size_t i = 0;
    while (i < s.size()) {
        size_t len = 0;
        JChar c = ReadCharStr(s, i, &len);
        i += len;
        bool has_next = i < s.size();
        JChar next = 0;
        if (has_next) {
            size_t l2 = 0;
            next = ReadCharStr(s, i, &l2);
        }
        if (c == C('"') || c == C('$')) {
            out.push_back('\\');
            PutUtf8(out, c);
        } else if (isascii(c)) {
            if (c == C('\0')) {
                out += (has_next && C('0') <= next && next <= C('7')) ? "\\x00" : "\\0";
            } else if (c == C(0x1b)) {
                out += "\\e";
            } else if (c == C('\\')) {
                out += "\\\\";
            } else if (C('\a') <= c && c <= C('\r')) {
                out.push_back('\\');
                out.push_back("abtnvfr"[codepoint(c) - 7]);
            } else if (isprint(c)) {
                PutUtf8(out, c);
            } else {
                out += "\\x";
                PutHex(out, codepoint(c), 2);
            }
        } else if (!isoverlong(c) && !ismalformed(c)) {
            bool full = has_next && isxdigit(next);
            if (isprint(c)) {
                PutUtf8(out, c);
            } else if (c <= C(0x7f)) {
                out += "\\x";
                PutHex(out, codepoint(c), 2);
            } else if (c <= C(0xffff)) {
                out += "\\u";
                PutHex(out, codepoint(c), full ? 4 : 2);
            } else {
                out += "\\U";
                PutHex(out, codepoint(c), full ? 8 : 4);
            }
        } else {
            uint32_t u = ((c & 0xFFu) << 24) | ((c & 0xFF00u) << 8) | ((c >> 8) & 0xFF00u) | (c >> 24);
            while (true) {
                out += "\\x";
                PutHex(out, u & 0xff, 2);
                u >>= 8;
                if (u == 0) break;
            }
        }
    }
    out.push_back('"');
    return out;
}

