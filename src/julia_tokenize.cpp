struct OpTables {
    std::vector<uint32_t> op_start;                     // sorted code points
    std::vector<std::pair<uint32_t, Kind>> unicode_ops;  // sorted by code point
};

bool IsNondotSymbolicOperatorKind(Kind k) {
    if (!is_operator(k)) return false;
    return !(k == K("ErrorInvalidOperator") || k == K("Error**") || k == K("...") || k == K(".") ||
             k == K("where") || k == K("isa") || k == K("in") || k == K(".'"));
}

const OpTables &GetOpTables() {
    static const OpTables tables = [] {
        OpTables t;
        std::vector<std::pair<uint32_t, Kind>> ops;
        for (uint16_t i = KindIndex(K("BEGIN_OPS")); i <= KindIndex(K("END_OPS")); ++i) {
            Kind k = static_cast<Kind>(i);
            if (!IsNondotSymbolicOperatorKind(k)) continue;
            std::string_view s = kKindNames[i];
            size_t len = 0;
            JChar c = ReadCharStr(s, 0, &len);
            t.op_start.push_back(codepoint(c));
            if (len == s.size() && !isascii(c)) {
                // Dict: later entries replace earlier ones
                auto it = std::find_if(ops.begin(), ops.end(), [&](auto &p) { return p.first == codepoint(c); });
                if (it != ops.end())
                    it->second = k;
                else
                    ops.emplace_back(codepoint(c), k);
            }
        }
        const std::pair<uint32_t, Kind> aliases[] = {
            {0x2212, K("-")}, {0x00b7, K("⋅")}, {0x0387, K("⋅")}};
        for (auto &a : aliases) {
            t.op_start.push_back(a.first);
            auto it = std::find_if(ops.begin(), ops.end(), [&](auto &p) { return p.first == a.first; });
            if (it != ops.end())
                it->second = a.second;
            else
                ops.push_back(a);
        }
        std::sort(t.op_start.begin(), t.op_start.end());
        t.op_start.erase(std::unique(t.op_start.begin(), t.op_start.end()), t.op_start.end());
        std::sort(ops.begin(), ops.end(), [](auto &a, auto &b) { return a.first < b.first; });
        t.unicode_ops = std::move(ops);
        return t;
    }();
    return tables;
}

Kind UnicodeOp(JChar c) {
    if (!isvalid(c)) return K("error");
    const auto &ops = GetOpTables().unicode_ops;
    uint32_t cp = codepoint(c);
    auto it = std::lower_bound(ops.begin(), ops.end(), cp, [](auto &p, uint32_t v) { return p.first < v; });
    if (it != ops.end() && it->first == cp) return it->second;
    return K("error");
}

