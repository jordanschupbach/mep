#ifndef MEP_NIX_LSP_H
#define MEP_NIX_LSP_H

// The analysis half of mep's own Nix language server (the wire half is
// nix_lsp_server.cpp, the `mep-nix-lsp` binary; kBuiltinLsp's `nix_ls` entry
// in main.cpp spawns it). It reads with nix_parse.h's parser, whose errors
// are `nix-instantiate --parse`'s (checked by tools/nix_parse_check.py), and
// resolves every variable the way Nix's bindVars does -- `let`, `rec`,
// function arguments, `with` (a name no static scope binds is looked up in
// the innermost enclosing `with` at run time), then the top-level builtins.
// So "undefined variable" is Nix's own error, reported before evaluation.
//
// Beyond Nix's errors it lints (help/nix-lsp.org has the table): unused `let`
// bindings and function arguments, a `with` nothing uses, `rec` nothing
// needs, the deprecated `let { }` form, unquoted URLs, Nix's "cursed or".
//
// Everything here is a pure function of the document text, so the whole
// server is testable without a client (nix_lsp_test.cpp). Positions are
// 0-based lines and 0-based byte columns (`positionEncoding: "utf-8"`).

#include <cstddef>
#include <map>
#include <memory>
#include <string>
#include <vector>

struct NixLspRange {
    int line = 0, col = 0, end_line = 0, end_col = 0;
};

struct NixLspOptions {
    std::string origin = "«string»";  // the file, as Nix names it in "already defined at FILE:L:C"
    bool pipe_operators = false;       // the `pipe-operators` experimental feature
};

// --- Builtins (nix_lsp_builtins.cpp is generated by tools/gen_nix_vocab.py) ---

struct NixLspBuiltin {
    const char *name;
    const char *args;          // space-separated argument names ("f list"), "" for values
    const char *kind;          // function, set, string, Boolean, ...
    bool bare;                 // in scope at the top level as `name`
    bool dunder;               // in scope at the top level as `__name`
    bool member;               // an attribute of `builtins`
    const char *experimental;  // the experimental feature it needs, "" for none
    bool impure;               // only in impure evaluation
};

const NixLspBuiltin *NixLspBuiltinTable(size_t *count);
/** @brief A builtin by its name in `builtins` (without `__`), or null. */
const NixLspBuiltin *NixLspFindBuiltin(const std::string &name);
/** @brief Builtin docs (name -> markdown), from `nix __dump-language`; empty until the server sets them. */
void NixLspSetBuiltinDocs(std::map<std::string, std::string> docs);
const std::string &NixLspBuiltinDoc(const std::string &name);

// --- The analysed document ----------------------------------------------------

class NixLspDocument;

/** @brief Parses and resolves a document; every query below runs on the result. */
std::shared_ptr<const NixLspDocument> NixLspAnalyze(const std::vector<std::string> &lines,
                                                    const NixLspOptions &opts = NixLspOptions());

// --- Diagnostics ----------------------------------------------------------------

enum class NixLspSeverity { Error = 1, Warning = 2, Information = 3, Hint = 4 };

struct NixLspDiagnostic {
    NixLspRange range;
    NixLspSeverity severity = NixLspSeverity::Error;
    std::string code;  // stable id: syntax-error, undefined-variable, unused-let, ...
    std::string message;
    bool unnecessary = false;  // LSP DiagnosticTag.Unnecessary (unused code)
    bool deprecated = false;   // LSP DiagnosticTag.Deprecated
};

std::vector<NixLspDiagnostic> NixLspDiagnostics(const NixLspDocument &doc);

/** @brief `path:line:col: severity: message [code]`, 1-based, as `mep-nix-lsp --lint` prints it. */
std::string NixLspFormatDiagnostic(const std::string &path, const NixLspDiagnostic &d);
/** @brief Whether a diagnostic makes `--lint` exit non-zero (an error or a warning). */
bool NixLspDiagnosticFails(const NixLspDiagnostic &d);

/**
 * @brief What `nix-instantiate --parse` would say, for tools/nix_parse_check.py: the first error Nix stops at
 *        while parsing (byte offset and message), or -- when parsing succeeds -- every undefined variable
 *        (Nix reports whichever it meets first, in an order that depends on its symbol table).
 */
struct NixLspCheck {
    bool parse_error = false;
    int offset = 0;
    std::string message;
    std::vector<std::pair<int, std::string>> undefined;  // (offset, name)
};
NixLspCheck NixLspNixCheck(const std::string &text, const NixLspOptions &opts = NixLspOptions());

// --- Completion -------------------------------------------------------------------

enum class NixLspKind {
    Text = 1, Method = 2, Function = 3, Field = 5, Variable = 6, Class = 7, Module = 9, Property = 10,
    Value = 12, Keyword = 14, Snippet = 15, Constant = 21, Struct = 22,
};

struct NixLspCompletionItem {
    std::string label;
    std::string insert_text;
    NixLspKind kind = NixLspKind::Text;
    std::string detail;
    std::string documentation;
    int replace_start = 0, replace_end = 0;  // byte columns on the request's line
};

/**
 * @brief Completions at a position: after `x.` the attributes `x` is known to have (`builtins.`, a `let`-bound
 *        or argument-default attribute set written in this file); otherwise every name in scope there, innermost
 *        first, then the top-level builtins and the keywords.
 */
std::vector<NixLspCompletionItem> NixLspCompletions(const NixLspDocument &doc, int line, int col);

// --- Hover / signature help ---------------------------------------------------------

struct NixLspHoverInfo {
    bool found = false;
    std::string text;  // markdown
    NixLspRange range;
};

/** @brief A builtin's signature and docs; where a variable is bound and to what; what a `with` brings in. */
NixLspHoverInfo NixLspHover(const NixLspDocument &doc, int line, int col);

struct NixLspSignatureHelp {
    bool found = false;
    std::string label;                // "builtins.map f list" / "f = { a, b ? 1 }:"
    std::vector<std::string> params;  // substrings of label
    std::string documentation;
    int active_param = 0;
};

/** @brief The function application the cursor is in: a builtin's or a function this file defines. */
NixLspSignatureHelp NixLspSignatureAt(const NixLspDocument &doc, int line, int col);

// --- Navigation ------------------------------------------------------------------------

struct NixLspLocation {
    NixLspRange range;
};

/** @brief Where the variable (or the attribute of a known set) under the cursor is bound. */
std::vector<NixLspLocation> NixLspDefinition(const NixLspDocument &doc, int line, int col);

struct NixLspReference {
    NixLspRange range;
    bool is_definition = false;
};

/** @brief Every occurrence of the binding under the cursor: where it is bound and every use. */
std::vector<NixLspReference> NixLspReferences(const NixLspDocument &doc, int line, int col);

struct NixLspTextEdit {
    NixLspRange range;
    std::string new_text;
};

struct NixLspRenameTarget {
    bool found = false;
    NixLspRange range;
    std::string placeholder;
};

/** @brief textDocument/prepareRename: `let` and `rec` bindings and function arguments this file declares. */
NixLspRenameTarget NixLspPrepareRename(const NixLspDocument &doc, int line, int col);

/** @brief The edits renaming the binding under the cursor; `error` says why not. */
std::vector<NixLspTextEdit> NixLspRename(const NixLspDocument &doc, int line, int col, const std::string &new_name,
                                         std::string *error);

// --- Outline / folding --------------------------------------------------------------------

enum class NixLspSymbolKind {
    File = 1, Module = 2, Namespace = 3, Class = 5, Method = 6, Property = 7, Field = 8, Function = 12,
    Variable = 13, Constant = 14, String = 15, Number = 16, Boolean = 17, Array = 18, Object = 19, Key = 20,
    Null = 21,
};

struct NixLspSymbol {
    std::string name;
    std::string detail;
    NixLspSymbolKind kind = NixLspSymbolKind::Variable;
    NixLspRange range;
    NixLspRange sel_range;
    int parent = -1;
};

/** @brief The outline: `let` bindings and attributes (nested sets under their attribute), function arguments. */
std::vector<NixLspSymbol> NixLspSymbols(const NixLspDocument &doc);

struct NixLspFold {
    int start_line = 0, end_line = 0;
    std::string kind;  // "" or "comment"
};

/** @brief Multi-line sets, lists, `let`s, argument sets, indented strings, comment runs. */
std::vector<NixLspFold> NixLspFolds(const NixLspDocument &doc);

// --- Formatting ------------------------------------------------------------------------------

/** @brief mep's nixfmt port (nix_format.h) as one edit over the changed lines; none when already formatted. */
std::vector<NixLspTextEdit> NixLspFormat(const std::vector<std::string> &lines, int width, std::string *error);

#endif  // MEP_NIX_LSP_H
