// PDFIUM_REMOVAL_PLAN.md Phase 10 coverage for pdf_encodings.h/.cpp.
// WinAnsiEncoding/MacRomanEncoding are cross-checked against Python's
// stdlib `codecs` module (cp1252 / mac_roman respectively) -- an
// independent oracle, generated once via a `python3` one-liner and
// pasted in as static data, same "external tool as ground truth"
// approach the image codecs used ImageMagick for. A few INTENTIONAL,
// documented deviations from raw Mac OS Roman / cp1252 are excluded
// from the diff (PDF's own spec explicitly defines them this way, or
// the deviation is inherent to a full-256-byte codec vs. a text-only
// encoding table): WinAnsiEncoding code 0xA0 is "space" (not nbsp),
// 0xAD is "hyphen" (not soft hyphen -- reuses ASCII 0x2D's own glyph
// name, an old Adobe-encoding convention that predates a distinct
// soft-hyphen glyph name existing at all), and 0x7F (DEL) is undefined;
// MacRomanEncoding code 0xCA is "space" (not nbsp), 0xF0 is undefined
// (not the Apple-logo private-use codepoint, which has no AGL name),
// and 0x7F is likewise undefined.
//
// StandardEncoding has no equivalent common-codec oracle, so it's
// spot-checked by hand for the well-known assignments, plus cross-
// checked against the CFF standard-strings table for the unambiguous
// plain-ASCII range (ASCII codes 32-126 map to CFF SIDs 1-95 in the
// same order in every reference) -- a real independent check for that
// range, though narrower than originally attempted: the stronger claim
// "ISOAdobe == all 228 of StandardEncoding's defined glyphs in code
// order" was tried first and did NOT hold up against this module's own
// StandardEncoding table (149 defined codes found, not 228), so rather
// than chase an unverifiable premise it was narrowed to what's actually
// checkable with confidence. See PDFIUM_REMOVAL_PLAN.md's Phase 10
// writeup for that investigation.

