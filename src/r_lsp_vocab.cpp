const RLspFunctionEntry *RLspFindFunction(const std::string &name) {
    // Built once, on first use: the table is a hand-maintained literal
    // grouped by topic rather than sorted, so a linear scan per lookup
    // would be the wrong shape for hover and completion both.
    static const std::map<std::string, const RLspFunctionEntry *> index = [] {
        std::map<std::string, const RLspFunctionEntry *> built;
        for (const RLspFunctionEntry &entry : kFunctions) built.emplace(entry.name, &entry);
        return built;
    }();
    const auto it = index.find(name);
    return it == index.end() ? nullptr : it->second;
}

