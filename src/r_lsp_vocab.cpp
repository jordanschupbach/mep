// The R vocabulary mep's own R language server knows: the functions of
// the base distribution with their real formals, plus reserved words,
// constants, operators, roxygen2 tags and package names.
//
// Hand-maintained rather than generated from an R installation, for the
// same reason the whole server is in-house: `mep-r-lsp` has to answer a
// hover on `mean()` on a machine with no R on it at all. The formals are
// written exactly as R declares them (`?mean` and friends), because
// signature help, the unknown-argument check and the argument-name
// completions all read them: an entry whose formals drift from R's own
// is worse than no entry, so anything uncertain is left out instead of
// guessed.
//
// Every entry's formals were checked against a real R 4.6 installation
// (`formals(args(fn))`) while this table was written. Four of them --
// legend(), pdf(), source() and library(), whose real formal lists run to
// twenty arguments and more -- deliberately list the arguments people
// actually pass and end in `...`; that is the conservative direction,
// because an entry ending in `...` is never argument-checked.
//
// Coverage is "what a person writing R actually types", not "everything
// exported": the arithmetic/vector/apply/string/IO core, the common
// statistics, the base graphics people still use, and the S4/R5 plumbing.
// Entries are grouped by topic rather than sorted, so lookups go through
// the name index RLspFindFunction builds once.
// A name not in here is simply not annotated -- it is never reported as
// an error, because RLspDiagnostics only trusts this table for
// *positive* knowledge (see r_lsp.cpp's own note on that).

