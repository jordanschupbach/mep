// `mep-ruby-lsp`: the wire half of mep's own Ruby language server, and a
// command-line linter. Speaks LSP over stdio; every answer comes from
// ruby_lsp.h's pure analysis functions.
//
//   mep-ruby-lsp                    the language server on stdio
//   mep-ruby-lsp --lint FILE...     diagnostics as path:line:col: severity: message [code];
//                                     exit 1 on any error or warning ('-' reads stdin)
//   mep-ruby-lsp --doc NAME [-I DIR]... [-r LIB]... [--file FILE]... [--context FILE]
//                                   NAME's documentation as Markdown, from the YARD comments
//                                   of the files LIB/FILE load (the Ruby UI's Help panel)
//
// Single-threaded and synchronous; Content-Length framing via
// rpc_framing.h, full text sync, `positionEncoding: "utf-8"`.
// Generated by tools/new_language.py from nix_lsp_server.cpp.
