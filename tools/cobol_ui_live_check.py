#!/usr/bin/env python3
"""Drive the real mep COBOL support over its agent socket, on a private X11 display.

A free-format program COPYs two rosetta-style copybooks: one found through
$COBCPY (fixed format), one only through the `-I` of the Run button's Setup
flags (free format). Checks the syntax highlighting, that mep-cobol-lsp
attaches with the Setup's -I as `includeDirs`, hover (through gh's Help tab)
on a CALL literal with several CALL lines, on a field and on an 88,
go-to-definition into the copybook and CALL-literal completion, then the
COBOL UI mode's Copybooks and Build tabs and its teardown.
"""
import argparse
import json
import os
from pathlib import Path
import select
import shutil
import subprocess
import tempfile
import time

from fold_live_check import Mep

BOOK = (
    "      *> Generated by Rosetta (test fixture).\n"
    "      *>> The status of the last call.\n"
    "       01 TT-STATUS.\n"
    "      *>> 0 after a successful call; otherwise the error kind.\n"
    "          05 TT-STATUS-CODE USAGE BINARY-LONG SIGNED VALUE 0.\n"
    "             88 TT-STATUS-OK VALUE 0.\n"
    "             88 TT-STATUS-RANGE VALUE 2.\n"
    "\n"
    "      *>> tt::Square::side\n"
    "      *>> CALL \"tt_square_side_get\" USING TT-SQUARE-SIDE TT-STATUS\n"
    "      *>> CALL \"tt_square_side_set\" USING TT-SQUARE-SIDE TT-STATUS (writes\n"
    "      *>>   -VALUE)\n"
    "      *>>\n"
    "      *>> The side length of a square.\n"
    "       01 TT-SQUARE-SIDE.\n"
    "      *>> Self: the SQUARE handle.\n"
    "          05 TT-SQUARE-SIDE-SELF USAGE BINARY-DOUBLE UNSIGNED.\n"
    "      *>> side (double): the value get reads and set writes.\n"
    "          05 TT-SQUARE-SIDE-VALUE USAGE COMP-2.\n"
)

CALLBACKS = (
    "*> Callback records (free format).\n"
    "  *>> tt::Shape::area() const -> double\n"
    "  *>> PROCEDURE DIVISION USING TT-AREA-ARGS TT-CALLBACK-STATUS\n"
    "  *>>\n"
    "  *>> The record of a COBOL override of tt::Shape::area.\n"
    "01 TT-AREA-ARGS.\n"
    "    *>> Result (double): double.\n"
    "    05 TT-AREA-ARGS-RESULT USAGE COMP-2.\n"
)

PROGRAM = (
    "*> mep COBOL live check.\n"                                   # 1
    "IDENTIFICATION DIVISION.\n"                                   # 2
    "PROGRAM-ID. LIVECHECK.\n"                                     # 3
    "DATA DIVISION.\n"                                             # 4
    "WORKING-STORAGE SECTION.\n"                                   # 5
    "COPY \"tt.cpy\".\n"                                           # 6
    "COPY \"tt-callbacks.cpy\".\n"                                 # 7
    "PROCEDURE DIVISION.\n"                                        # 8
    "    MOVE 2.5 TO TT-SQUARE-SIDE-VALUE\n"                       # 9
    "    CALL \"tt_square_side_set\" USING TT-SQUARE-SIDE TT-STATUS\n"  # 10
    "    IF NOT TT-STATUS-OK\n"                                    # 11
    "        DISPLAY \"failed\"\n"                                 # 12
    "    END-IF\n"                                                 # 13
    "    STOP RUN.\n"                                              # 14
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--build-dir', default='build/native')
    parser.add_argument('--keep', action='store_true')
    args = parser.parse_args()
    home = tempfile.mkdtemp(prefix='mepcobolui-')
    editor = None
    server = None
    read_fd, write_fd = os.pipe()
    try:
        server = subprocess.Popen(['Xvfb', '-displayfd', str(write_fd), '-screen', '0',
                                   '1600x1200x24', '-nolisten', 'tcp'], pass_fds=(write_fd,),
                                  stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        os.close(write_fd)
        write_fd = None
        if not select.select([read_fd], [], [], 10)[0]:
            raise RuntimeError('Xvfb did not start')
        number = os.read(read_fd, 64).decode().strip()
        if not number.isdigit():
            raise RuntimeError('Xvfb could not allocate a display')
        root = Path(home)
        (root / 'cpy').mkdir()
        (root / 'inc').mkdir()
        (root / 'src').mkdir()
        (root / 'cpy' / 'tt.cpy').write_text(BOOK)
        (root / 'inc' / 'tt-callbacks.cpy').write_text(CALLBACKS)
        source = root / 'src' / 'live.cob'
        source.write_text(PROGRAM)
        os.environ['COBCPY'] = str(root / 'cpy')
        editor = Mep(args.build_dir, home, ':' + number, [], cwd=home)

        def value(expr):
            v = editor.lua_value(expr)
            if v is None or v.startswith('ERR:'):
                raise RuntimeError(f'{expr}: {v}\nlog={editor.log_tail()}')
            return v

        def wait(expr, predicate, label, timeout=30):
            deadline = time.monotonic() + timeout
            last = None
            while time.monotonic() < deadline:
                last = editor.lua_value(expr)
                if last is not None and not last.startswith('ERR:') and predicate(last):
                    return last
                editor.pump(2)
            raise AssertionError(label + '\nlast=' + str(last) + '\nlog=' + editor.log_tail())

        # The Setup flags' -I reaches the server; open the file afterwards so it starts with them.
        editor.cmd("lua mep.opt.run_button_defaults.cob.flags = '-I inc'; mep.opt.language_ui_poll_interval = 0.05")
        editor.cmd('e ' + str(source))
        opts = json.loads(value('mep_ai_json_encode(mep.cobol_lsp_init_options(mep.filename()))'))
        assert opts == {'includeDirs': [str(root / 'inc')]}, opts
        print('PASS: the Run Setup\'s -I becomes includeDirs')

        decos = wait('table.concat(mep.ns_decorations(mep.ns_create("syntax")), "\\n")', lambda v: 'Green' in v,
                     'no COBOL syntax highlighting')
        assert 'Comment' in decos and 'Purple' in decos and 'Cyan' in decos, decos
        print('PASS: COBOL syntax highlighting')

        wait('tostring(mep.lsp_client_for() ~= nil)', lambda v: v == 'true', 'mep-cobol-lsp did not attach')
        editor.cmd('lua mep.language_ui_toggle()')

        def info():
            return json.loads(value('(function() local i = mep.cobol_ui_info(); return i and mep_ai_json_encode(i) or "null" end)()'))

        state = info()
        assert state is not None, 'COBOL mode did not open'
        books = {b['name']: b for b in state['copybooks']}
        assert books['tt.cpy']['path'] == str(root / 'cpy' / 'tt.cpy'), books
        assert books['tt-callbacks.cpy']['path'] == str(root / 'inc' / 'tt-callbacks.cpy'), books
        side = [r for r in books['tt.cpy']['records'] if r['name'] == 'TT-SQUARE-SIDE'][0]
        assert side['calls'] == ['tt_square_side_get', 'tt_square_side_set'], side
        print('PASS: Copybooks tab: $COBCPY and -I copybooks, records with all their CALLs')

        help_expr = '(mep.cobol_ui_info() or {}).help or ""'
        editor.cmd('lua mep.set_cursor(10, 14); mep.help_at_cursor()')
        text = wait(help_expr, lambda v: 'tt_square_side_set' in v,
                    'gh on the CALL literal showed nothing')
        assert 'tt::Square::side' in text and 'CALL "tt_square_side_get" USING TT-SQUARE-SIDE TT-STATUS' in text, text
        assert 'CALL "tt_square_side_set" USING TT-SQUARE-SIDE TT-STATUS (writes -VALUE)' in text, text
        assert 'The side length of a square.' in text and 'side (double): the value get reads and set writes.' in text, text
        print('PASS: gh on a CALL literal: signature, both CALL lines, body, fields')
        editor.cmd('lua mep.set_cursor(9, 20); mep.help_at_cursor()')
        text = wait(help_expr, lambda v: '05 TT-SQUARE-SIDE-VALUE' in v, 'gh on a field showed nothing')
        assert 'In `TT-SQUARE-SIDE`' in text, text
        editor.cmd('lua mep.set_cursor(11, 14); mep.help_at_cursor()')
        text = wait(help_expr, lambda v: '88 TT-STATUS-OK VALUE 0.' in v, 'gh on an 88 showed nothing')
        assert 'Condition on `TT-STATUS-CODE`' in text, text
        print('PASS: gh on a field and on an 88')

        lsp_call = ("lua _G.cobol_live = nil; mep.lsp_request(mep.lsp_client_for(), '%s', "
                    "{textDocument = {uri = mep_lsp_uri(mep.filename())}, position = {line = %d, character = %d}}, "
                    "function(msg) _G.cobol_live = mep_ai_json_encode(mep_lsp_result(msg)) end)")
        editor.cmd(lsp_call % ('textDocument/definition', 9, 14))
        found = json.loads(wait('_G.cobol_live or ""', lambda v: v != '', 'no definition reply'))
        assert found[0]['uri'].endswith('/cpy/tt.cpy') and found[0]['range']['start']['line'] == 14, found
        editor.cmd(lsp_call % ('textDocument/completion', 9, 14))
        found = json.loads(wait('_G.cobol_live or ""', lambda v: v != '', 'no completion reply'))
        labels = [i['label'] for i in found['items']]
        assert labels == ['tt_square_side_get', 'tt_square_side_set'], labels
        print('PASS: go to definition into the copybook; CALL-literal completion')

        cobc = shutil.which('cobc')
        state = wait('mep_ai_json_encode(mep.cobol_ui_info().build)', lambda v: '[' in v and ('ok' in v or 'exit' in v),
                     'the Build tab never got cobc\'s answer', timeout=60)
        build = json.loads(state)
        assert build[0].startswith('$ cobc -fsyntax-only') and '-I inc' in build[0], build
        if cobc:
            assert build[-1] == '[syntax ok]', build
            print('PASS: Build tab: cobc -fsyntax-only with the Setup flags, syntax ok')
        else:
            print('PASS: Build tab ran cobc -fsyntax-only (cobc not on PATH: %s)' % build[-1])

        editor.cmd('lua mep.language_ui_toggle()')
        assert info() is None
        print('PASS: mode teardown')
    finally:
        if editor:
            editor.quit()
        if server:
            server.terminate()
            server.wait(timeout=5)
        os.close(read_fd)
        if write_fd is not None:
            os.close(write_fd)
        if args.keep:
            print('Kept isolated editor home:', home)
        else:
            shutil.rmtree(home, ignore_errors=True)


if __name__ == '__main__':
    main()
