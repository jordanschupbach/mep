#!/usr/bin/env python3
"""Regenerate src/fish_lsp_vocab.cpp: what mep-fish-lsp knows about fish's commands.

    just fish-vocab [FISH_SOURCE_DIR]   # needs `fish` on PATH; the source defaults to nixpkgs#fish.src

For every builtin (`builtin -n`) and every public function fish ships
(`functions -a`, minus the `__fish_*` helpers) it records:

  * the synopsis lines of its man page (doc_src/cmds/NAME.rst, the
    `.. synopsis::` block) -- usage lines only;
  * its option spellings, from the synopsis and from fish's own completion
    file for it (share/completions/NAME.fish: the -s / -l / -o of each
    `complete -c NAME` line).

fish is GPL-2; only names, usage lines and option spellings are taken, never
descriptions or other prose.
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / 'src' / 'fish_lsp_vocab.cpp'


def fish_source():
    if len(sys.argv) > 1:
        return Path(sys.argv[1])
    p = subprocess.run(['nix', 'eval', '--raw', 'nixpkgs#fish.src.outPath'], capture_output=True, text=True)
    if p.returncode != 0:
        sys.exit('cannot find fish.src: ' + p.stderr)
    path = Path(p.stdout.strip())
    if not path.exists():
        subprocess.run(['nix', 'build', '--no-link', 'nixpkgs#fish.src'], check=True)
    return path


def fish_lines(cmd):
    return subprocess.run(['fish', '--no-config', '-c', cmd], capture_output=True, text=True, check=True).stdout


def synopsis(rst):
    if not rst.exists():
        return []
    lines = rst.read_text().splitlines()
    out = []
    for i, l in enumerate(lines):
        if l.strip() == '.. synopsis::':
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            cur = None
            while j < len(lines) and (lines[j].startswith(' ') or not lines[j].strip()):
                s = lines[j]
                if s.strip():
                    if cur is not None and len(s) - len(s.lstrip()) > 4:
                        cur += ' ' + s.strip()  # a continuation line
                    else:
                        if cur is not None:
                            out.append(cur)
                        cur = s.strip()
                elif cur is not None:
                    out.append(cur)
                    cur = None
                j += 1
            if cur is not None:
                out.append(cur)
            break
    return [re.sub(r'\s+', ' ', l) for l in out]


OPT_RE = re.compile(r'(?<![\w-])(--?[A-Za-z0-9][\w-]*)')


def options(name, syn, src):
    opts = []
    for line in syn:
        for m in OPT_RE.finditer(line):
            o = m.group(1)
            if o.startswith('-') and not o.startswith('--') and len(o) > 2:
                # -Uflg: a bundle of short flags
                for ch in o[1:]:
                    opts.append('-' + ch)
            else:
                opts.append(o.rstrip('='))
    comp = src / 'share' / 'completions' / f'{name}.fish'
    if comp.exists():
        for line in comp.read_text(errors='replace').splitlines():
            line = line.strip()
            if not re.match(rf'complete\s+(-c|--command)\s+{re.escape(name)}\b', line):
                continue
            for flag, prefix in (('-s', '-'), ('--short-option', '-'), ('-l', '--'), ('--long-option', '--'),
                                 ('-o', '-'), ('--old-option', '-')):
                for m in re.finditer(rf'(?:^|\s){re.escape(flag)}\s+([A-Za-z0-9][\w-]*)', line):
                    opts.append(prefix + m.group(1))
    seen = []
    for o in opts:
        if o not in seen and o not in ('-', '--'):
            seen.append(o)
    return seen


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('??', '?\\?') + '"'


def main():
    src = fish_source()
    builtins = fish_lines('builtin -n').split()
    functions = [f for f in fish_lines('functions -a').replace(',', '\n').split()
                 if not f.startswith('_') and f not in builtins]
    entries = []
    for name, is_builtin in [(b, True) for b in builtins] + [(f, False) for f in functions]:
        syn = synopsis(src / 'doc_src' / 'cmds' / f'{name}.rst')
        if name == '[':
            syn = synopsis(src / 'doc_src' / 'cmds' / 'test.rst')
        if name == 'string':
            syn = []
            for sub in sorted((src / 'doc_src' / 'cmds').glob('string-*.rst')):
                syn += synopsis(sub)
        entries.append((name, '\n'.join(syn), ' '.join(options(name, syn, src)), is_builtin))
    entries.sort()
    body = ['// Generated by tools/fish_vocab.py -- do not edit by hand. See fish_lsp_vocab.h.',
            '// Names, synopsis lines and option spellings from fish 4.x (GPL-2) -- no prose.',
            '#include "fish_lsp_vocab.h"', '', '#include <cstring>', '', 'namespace {',
            'const FishVocabEntry kVocab[] = {']
    for name, syn, opts, b in entries:
        body.append(f'    {{{cstr(name)}, {cstr(syn)},\n     {cstr(opts)}, {"true" if b else "false"}}},')
    body += ['};', '}  // namespace', '',
             'const FishVocabEntry *FishVocab(size_t *count) {',
             '    *count = sizeof(kVocab) / sizeof(kVocab[0]);',
             '    return kVocab;', '}', '',
             'const FishVocabEntry *FishVocabFind(const char *name, size_t len) {',
             '    for (const FishVocabEntry &e : kVocab)',
             '        if (std::strlen(e.name) == len && std::memcmp(e.name, name, len) == 0) return &e;',
             '    return nullptr;', '}', '']
    OUT.write_text('\n'.join(body))
    print(f'{OUT}: {len(entries)} commands ({len(builtins)} builtins, {len(entries) - len(builtins)} functions)')


if __name__ == '__main__':
    main()
