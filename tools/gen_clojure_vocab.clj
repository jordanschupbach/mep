;; Generates src/clojure_lsp_core_names.cpp, the vocabulary of mep's own
;; Clojure language server: every var of clojure.core and the namespaces
;; that ship with Clojure (the private ones marked: `#'ns/private` is
;; legal, and so is a var made public at run time), with its kind,
;; arglists, docstring, :added and :deprecated, plus the special forms (and
;; their docs from clojure.repl). Run from the repository root:
;;
;;   clojure -M tools/gen_clojure_vocab.clj > src/clojure_lsp_core_names.cpp
(ns gen-clojure-vocab
  (:require [clojure.string :as str]
            [clojure.repl]))

(def namespaces
  '[clojure.core clojure.string clojure.set clojure.walk clojure.edn clojure.java.io
    clojure.pprint clojure.test clojure.repl clojure.data clojure.zip clojure.java.shell
    clojure.template clojure.stacktrace clojure.instant clojure.main clojure.math
    clojure.core.protocols clojure.datafy clojure.reflect clojure.xml clojure.core.reducers
    clojure.java.browse clojure.java.javadoc clojure.spec.alpha clojure.core.specs.alpha
    clojure.core.server clojure.uuid clojure.inspector clojure.tools.deps.interop])

(doseq [n namespaces] (try (require n) (catch Throwable _)))

(defn c-str [s]
  (str "\""
       (-> (or s "")
           (str/replace "\\" "\\\\")
           (str/replace "\"" "\\\"")
           (str/replace "\n" "\\n")
           (str/replace "\t" "\\t")
           (str/replace "\r" ""))
       "\""))

;; A docstring as Clojure writes it: every line after the first indented two
;; spaces. Shown in an editor it reads better without that indent.
(defn tidy-doc [doc]
  (when doc
    (let [lines (str/split-lines doc)]
      (str/join "\n" (cons (str/trim (first lines))
                           (map #(str/replace % #"^  " "") (rest lines)))))))

(defn kind [v]
  (let [m (meta v)]
    (cond (:macro m) "macro"
          (:dynamic m) "dynamic"
          (and (bound? v) (fn? @v)) "function"
          (and (bound? v) (instance? clojure.lang.MultiFn @v)) "function"
          (:arglists m) "function"
          (and (bound? v) (satisfies? clojure.core.protocols/CollReduce @v)) "var"
          :else "var")))

(defn row [ns-name sym v]
  (let [m (meta v)]
    (format "    {%s, %s, %s, %s, %s, %s, %s, %s},"
            (c-str (str ns-name)) (c-str (str sym)) (c-str (kind v))
            (c-str (str/join "\n" (map pr-str (:arglists m))))
            (c-str (tidy-doc (:doc m)))
            (c-str (some-> (:added m) str))
            (c-str (some-> (:deprecated m) str))
            (if (:private m) "true" "false"))))

(def special-forms
  ;; The compiler's special forms (clojure.lang.Compiler/specials), with the
  ;; usage clojure.repl documents for each.
  (let [docs @#'clojure.repl/special-doc-map]
    (for [s (sort (map str (keys clojure.lang.Compiler/specials)))
          :when (not (#{"&" "fn*" "let*" "loop*" "letfn*" "case*" "import*" "reify*" "deftype*" "clojure.core/import*"} s))]
      (let [d (get docs (symbol s))]
        (format "    {%s, %s, %s, %s, %s, %s, %s, false},"
                (c-str "") (c-str s) (c-str "special")
                (c-str (str/join "\n" (map pr-str (or (:forms d) []))))
                (c-str (tidy-doc (:doc d))) (c-str "") (c-str ""))))))

(println "// Generated by tools/gen_clojure_vocab.clj from Clojure" (clojure-version) "-- do not edit.")
(println "// The vars of clojure.core and the namespaces that ship with it (private ones marked),")
(println "// and the special forms: name, kind, arglists, docstring, :added, :deprecated.")
(println)
(println "#include \"clojure_lsp_core_names.h\"")
(println)
(println "namespace {")
(println "const CljCoreName kNames[] = {")
(doseq [s special-forms] (println s))
(doseq [n namespaces
        :let [ns (find-ns n)]
        :when ns
        [sym v] (sort-by (comp str key) (ns-interns ns))]
  (println (row n sym v)))
(println "};")
(println "}  // namespace")
(println)
(println "const CljCoreName *CljCoreNames(size_t *count) {")
(println "    *count = sizeof(kNames) / sizeof(kNames[0]);")
(println "    return kNames;")
(println "}")
