#!/usr/bin/env python3
"""Generate mep's C# syntax tables from Roslyn's own sources.

    python3 -I tools/gen_csharp_syntax.py ROSLYN_CSHARP_PORTABLE_DIR UNICODE_CATEGORIES

ROSLYN_CSHARP_PORTABLE_DIR is Roslyn's src/Compilers/CSharp/Portable (the
copy matching the .NET SDK's compiler; `just csharp-syntax-gen` fetches it).
UNICODE_CATEGORIES is `csharp-oracle unicode-categories`' output: .NET's own
char.GetUnicodeCategory, which Roslyn's lexer classifies identifiers by.
Writes, under src/ (all committed, so building mep never needs Roslyn):

  csharp_syntax_kinds.inc    CS_KIND(Name, value) for every SyntaxKind
                             (Syntax/SyntaxKind.cs, values as there)
  csharp_errors.inc          CS_ERROR(Name, number, severity, "message") for
                             every ErrorCode the parser and lexer use, plus
                             the ones mep's lints borrow (CSharpResources.resx
                             text, verbatim)
  csharp_syntax_factory.h    one factory per concrete node of Syntax/Syntax.xml,
  csharp_syntax_factory.cpp  the internal SyntaxFactory's signature (kind first
                             when the node has several kinds, then every field
                             in order), plus the Field enum and the kind ->
                             field -> slot table
  csharp_unicode.inc         {first, last, category} ranges of every UTF-16 unit

Roslyn is MIT-licensed (c) .NET Foundation and Contributors; the generated
files carry that notice.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

NOTICE = """// GENERATED by tools/gen_csharp_syntax.py from Roslyn's {src} -- do not edit.
// Roslyn: Copyright (c) .NET Foundation and Contributors, MIT License
// (https://github.com/dotnet/roslyn/blob/main/License.txt).
"""

# ErrorCodes mep's own lints report with Roslyn's wording (src/csharp_lsp_diagnostics.cpp).
EXTRA_ERRORS = [
    "WRN_UnreferencedVar", "WRN_UnreferencedVarAssg", "WRN_UnreachableCode", "WRN_UnreferencedLabel",
    "WRN_UnreferencedLocalFunction", "WRN_DuplicateUsing", "HDN_UnusedUsingDirective",
    "WRN_UnreferencedField", "WRN_UnreferencedFieldAssg", "WRN_UnreferencedEvent",
    "ERR_UseDefViolation", "ERR_NameNotInContext", "WRN_EmptySwitch", "WRN_PossibleMistakenNullStatement",
    "WRN_AssignmentToSelf", "WRN_ComparisonToSelf", "ERR_LocalDuplicate", "ERR_DuplicateNameInClass",
    "ERR_DuplicateParamName", "WRN_EqualsWithoutGetHashCode",
]

CPP_KEYWORDS = {"operator", "new", "default", "delete", "this", "class", "struct", "namespace", "public",
                "private", "protected", "case", "switch", "typename", "template", "union", "unsigned", "signed",
                "explicit", "static", "const", "volatile", "virtual", "bool", "char", "int", "long", "short",
                "float", "double", "void", "true", "false", "return", "if", "else", "for", "while", "do",
                "goto", "break", "continue", "try", "catch", "throw", "using", "enum", "sizeof", "typeid",
                "friend", "inline", "register", "extern", "mutable", "auto", "asm", "export", "and", "or",
                "not", "xor", "bitand", "bitor", "compl", "concept", "requires", "module", "import"}


def read(path):
    with open(path, encoding="utf-8-sig") as f:
        return f.read()


def gen_kinds(src):
    text = read(os.path.join(src, "Syntax/SyntaxKind.cs"))
    body = text[text.index("enum SyntaxKind"):]
    kinds = []
    for m in re.finditer(r"^\s*(\w+)\s*=\s*([^,\s]+)\s*,", body, re.M):
        name, value = m.group(1), m.group(2)
        if value == "GreenNode.ListKind":
            value = "1"
        if not value.isdigit():
            raise SystemExit(f"unexpected SyntaxKind value {name} = {value}")
        kinds.append((name, int(value)))
    return kinds


def gen_errors(src):
    text = read(os.path.join(src, "Errors/ErrorCode.cs"))
    codes = {}
    for m in re.finditer(r"^\s*((?:ERR|WRN|INF|HDN|FTL)_\w+)\s*=\s*(\d+)\s*,", text, re.M):
        codes[m.group(1)] = int(m.group(2))
    used = set()
    for d in ("Parser", "Syntax"):
        for root, _, files in os.walk(os.path.join(src, d)):
            for fn in files:
                if fn.endswith(".cs"):
                    used.update(re.findall(r"ErrorCode\.((?:ERR|WRN|INF|HDN|FTL)_\w+)", read(os.path.join(root, fn))))
    used.update(EXTRA_ERRORS)
    resx = ET.parse(os.path.join(src, "CSharpResources.resx")).getroot()
    messages = {}
    for data in resx.findall("data"):
        v = data.find("value")
        messages[data.get("name")] = v.text if v is not None and v.text is not None else ""
    out = []
    for name in sorted(used, key=lambda n: (codes.get(n, 0), n)):
        if name not in codes:
            continue  # referenced in a comment or a removed code
        sev = {"ERR": "Error", "WRN": "Warning", "INF": "Info", "HDN": "Hidden", "FTL": "Error"}[name[:3]]
        out.append((name, codes[name], sev, messages.get(name, "")))
    return out


def c_string(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20:
            out.append("\\x%02x" % o)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def flatten_fields(elem):
    fields = []
    for child in elem:
        if child.tag == "Field":
            fields.append(child)
        elif child.tag in ("Choice", "Sequence"):
            fields.extend(flatten_fields(child))
    return fields


def gen_nodes(src):
    tree = ET.parse(os.path.join(src, "Syntax/Syntax.xml")).getroot()
    bases = {}
    nodes = []
    for elem in tree:
        if elem.tag in ("PredefinedNode", "AbstractNode", "Node"):
            bases[elem.get("Name")] = elem.get("Base")
        if elem.tag == "Node":
            kinds = [k.get("Name") for k in elem.findall("Kind")]
            fields = [(f.get("Name"), f.get("Type"), f.get("Optional") == "true") for f in flatten_fields(elem)]
            nodes.append((elem.get("Name"), kinds, fields))

    def derives(name, base):
        while name:
            if name == base:
                return True
            name = bases.get(name)
        return False

    return nodes, derives


def param_name(field):
    name = field[0]
    p = name[0].lower() + name[1:]
    return p + "_" if p in CPP_KEYWORDS else p


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    src = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    outdir = os.path.join(here, "..", "src")

    kinds = gen_kinds(src)
    with open(os.path.join(outdir, "csharp_syntax_kinds.inc"), "w") as f:
        f.write(NOTICE.format(src="Syntax/SyntaxKind.cs"))
        for name, value in kinds:
            f.write(f"CS_KIND({name}, {value})\n")

    errors = gen_errors(src)
    with open(os.path.join(outdir, "csharp_errors.inc"), "w") as f:
        f.write(NOTICE.format(src="Errors/ErrorCode.cs and CSharpResources.resx"))
        for name, num, sev, msg in errors:
            f.write(f"CS_ERROR({name}, {num}, {sev}, {c_string(msg)})\n")

    nodes, derives = gen_nodes(src)
    field_names = sorted({fld[0] for _, _, fields in nodes for fld in fields if fld[1] != "bool"})
    bool_names = sorted({fld[0] for _, _, fields in nodes for fld in fields if fld[1] == "bool"})

    h = [NOTICE.format(src="Syntax/Syntax.xml")]
    h.append("""#ifndef MEP_CSHARP_SYNTAX_FACTORY_H
#define MEP_CSHARP_SYNTAX_FACTORY_H

// The internal SyntaxFactory's node constructors, one per concrete node of
// Roslyn's Syntax.xml: the same names and the same parameters in the same
// order (a node with several kinds takes the kind first). Every field is a
// GreenNode* -- a token, a node, or a list (nullptr when empty or absent).
// Field / FieldSlot / GetField read a node's fields by name, whatever its
// kind (so `typeDecl.Modifiers` is GetField(n, Field::Modifiers)).

#include "csharp_syntax.h"

namespace csharp {

enum class Field : uint16_t {
""")
    for fn in field_names:
        h.append(f"    {fn},\n")
    h.append("""    Count_
};

/** @brief The field's name ("Modifiers"). */
const char *FieldName(Field f);
/** @brief Which slot of a node of this kind holds the field; -1 when the kind has no such field. */
int FieldSlot(SyntaxKind kind, Field f);
/** @brief The field of node `n` (nullptr when absent, empty, or `n` has no such field). */
GreenNode *GetField(const GreenNode *n, Field f);
/** @brief The field names of a node kind, in slot order (empty for tokens, trivia and lists). */
const std::vector<Field> &FieldsOf(SyntaxKind kind);
/** @brief Whether `kind` is a node deriving from Roslyn's StructuredTriviaSyntax / DirectiveTriviaSyntax. */
bool IsStructuredTriviaKind(SyntaxKind kind);
bool IsDirectiveTriviaKind(SyntaxKind kind);
/** @brief The Syntax.xml class of a node kind ("ClassDeclarationSyntax"); "" for tokens/trivia. */
const char *NodeClassName(SyntaxKind kind);
/** @brief Whether a node of `kind` derives from the Syntax.xml class `base` ("TypeSyntax", "StatementSyntax"...). */
bool KindDerivesFrom(SyntaxKind kind, const char *base);

""")
    for i, bn in enumerate(bool_names):
        h.append(f"constexpr uint8_t kBool{bn} = {1 << i};\n")
        h.append(f"/** @brief The node's `{bn}` (a bool field of Syntax.xml, kept in GreenNode::bool_fields). */\n")
        h.append(f"inline bool {bn}(const GreenNode *n) {{ return (n->bool_fields & kBool{bn}) != 0; }}\n")
    h.append("""
namespace SyntaxFactory {
""")
    cpp = [NOTICE.format(src="Syntax/Syntax.xml")]
    cpp.append("""#include "csharp_syntax_factory.h"

#include <cstring>
#include <unordered_map>

namespace csharp {

namespace SyntaxFactory {
""")
    kind_fields = []
    for name, node_kinds, fields in nodes:
        fname = name[:-6] if name.endswith("Syntax") else name
        params = []
        if len(node_kinds) > 1:
            params.append("SyntaxKind kind")
        params += [(f"bool {param_name(fl)}" if fl[1] == "bool" else f"GreenNode *{param_name(fl)}") for fl in fields]
        sig = f"GreenNode *{fname}({', '.join(params)})"
        h.append(f"{sig};\n")
        slot_fields = [fl for fl in fields if fl[1] != "bool"]
        bool_fields = [fl for fl in fields if fl[1] == "bool"]
        args = ", ".join(param_name(fl) for fl in slot_fields)
        kind_expr = "kind" if len(node_kinds) > 1 else f"SyntaxKind::{node_kinds[0]}"
        body = f"    GreenNode *slots[] = {{{args}}};\n" if slot_fields else "    GreenNode **slots = nullptr;\n"
        body += f"    GreenNode *n = MakeNode({kind_expr}, slots, {len(slot_fields)});\n"
        for fl in bool_fields:
            body += f"    if ({param_name(fl)}) n->bool_fields |= kBool{fl[0]};\n"
        cpp.append(f"{sig} {{\n{body}    return n;\n}}\n")
        for k in node_kinds:
            kind_fields.append((k, name, [fl[0] for fl in slot_fields]))
    h.append("""
// ContextAwareSyntax.cs's one hand-written overload.
inline GreenNode *GlobalStatement(GreenNode *statement) { return GlobalStatement(nullptr, nullptr, statement); }

}  // namespace SyntaxFactory

}  // namespace csharp

#endif  // MEP_CSHARP_SYNTAX_FACTORY_H
""")
    cpp.append("}  // namespace SyntaxFactory\n\nnamespace {\n\nconst char *const kFieldNames[] = {\n")
    for fn in field_names:
        cpp.append(f"    \"{fn}\",\n")
    cpp.append("};\n\nstruct KindInfo {\n    SyntaxKind kind;\n    const char *cls;\n    bool structured;\n"
               "    bool directive;\n    std::vector<Field> fields;\n};\n\n"
               "const std::vector<KindInfo> &KindTable() {\n    static const std::vector<KindInfo> table = {\n")
    for k, cls, flds in kind_fields:
        st = "true" if derives(cls, "StructuredTriviaSyntax") else "false"
        di = "true" if derives(cls, "DirectiveTriviaSyntax") else "false"
        fl = ", ".join(f"Field::{x}" for x in flds)
        cpp.append(f"        {{SyntaxKind::{k}, \"{cls}\", {st}, {di}, {{{fl}}}}},\n")
    cpp.append("    };\n    return table;\n}\n\n")
    # base chains
    cpp.append("struct BaseLink {\n    const char *cls;\n    const char *base;\n};\n\nconst BaseLink kBases[] = {\n")
    tree = ET.parse(os.path.join(src, "Syntax/Syntax.xml")).getroot()
    for elem in tree:
        if elem.tag in ("PredefinedNode", "AbstractNode", "Node"):
            cpp.append(f"    {{\"{elem.get('Name')}\", \"{elem.get('Base')}\"}},\n")
    cpp.append("};\n\n")
    cpp.append("""const KindInfo *Info(SyntaxKind kind) {
    static const std::unordered_map<uint16_t, const KindInfo *> map = [] {
        std::unordered_map<uint16_t, const KindInfo *> m;
        for (const KindInfo &k : KindTable()) m[static_cast<uint16_t>(k.kind)] = &k;
        return m;
    }();
    auto it = map.find(static_cast<uint16_t>(kind));
    return it == map.end() ? nullptr : it->second;
}

}  // namespace

const char *FieldName(Field f) { return kFieldNames[static_cast<int>(f)]; }

int FieldSlot(SyntaxKind kind, Field f) {
    const KindInfo *info = Info(kind);
    if (!info) return -1;
    for (size_t i = 0; i < info->fields.size(); i++) {
        if (info->fields[i] == f) return static_cast<int>(i);
    }
    return -1;
}

GreenNode *GetField(const GreenNode *n, Field f) {
    if (!n) return nullptr;
    int slot = FieldSlot(n->kind, f);
    return slot < 0 ? nullptr : n->GetSlot(slot);
}

const std::vector<Field> &FieldsOf(SyntaxKind kind) {
    static const std::vector<Field> none;
    const KindInfo *info = Info(kind);
    return info ? info->fields : none;
}

bool IsStructuredTriviaKind(SyntaxKind kind) {
    const KindInfo *info = Info(kind);
    return info && info->structured;
}

bool IsDirectiveTriviaKind(SyntaxKind kind) {
    const KindInfo *info = Info(kind);
    return info && info->directive;
}

const char *NodeClassName(SyntaxKind kind) {
    const KindInfo *info = Info(kind);
    return info ? info->cls : "";
}

bool KindDerivesFrom(SyntaxKind kind, const char *base) {
    const KindInfo *info = Info(kind);
    if (!info) return false;
    const char *cls = info->cls;
    while (cls) {
        if (std::strcmp(cls, base) == 0) return true;
        const char *next = nullptr;
        for (const BaseLink &b : kBases) {
            if (std::strcmp(b.cls, cls) == 0) {
                next = b.base;
                break;
            }
        }
        cls = next;
    }
    return false;
}

}  // namespace csharp
""")
    with open(os.path.join(outdir, "csharp_syntax_factory.h"), "w") as f:
        f.write("".join(h))
    with open(os.path.join(outdir, "csharp_syntax_factory.cpp"), "w") as f:
        f.write("".join(cpp))
    ranges = [line.split() for line in open(sys.argv[2]) if line.strip()]
    with open(os.path.join(outdir, "csharp_unicode.inc"), "w") as f:
        f.write("// GENERATED by tools/gen_csharp_syntax.py from .NET's char.GetUnicodeCategory -- do not edit.\n")
        for a, b, c in ranges:
            f.write(f"{{{a}, {b}, {c}}},\n")
    print(f"{len(ranges)} unicode ranges")
    print(f"{len(kinds)} kinds, {len(errors)} error codes, {len(nodes)} nodes, {len(field_names)} field names")


if __name__ == "__main__":
    main()
