#!/usr/bin/env python3
"""Generate src/gap_lsp_vocab.cpp: mep-gap-lsp's table of GAP names.

    just gap-vocab          (python3 tools/gen_gap_vocab.py [GAP-TARBALL])

Two tables, both names and argument lists only -- GAP's manuals and library
are GPL and mep is MIT, so no prose is copied (the precedent the Maxima,
fish and Nix vocabularies set):

  kGapVocab    every documented function, operation, attribute, property,
               filter, variable ... from the manuals' text versions
               (doc/ref and every bundled package's doc/chap*.txt): the
               `Name( args )  kind` heading lines GAPDoc writes, with the
               book (ref, or the package) it came from.
  kGapGlobals  every name bound in a GAP started with its default packages
               (`NamesGVars()`), plus every name the bundled packages
               declare (DeclareGlobalFunction("X"), DeclareOperation("X",
               ...), BindGlobal("X", ...), ... and `X := ...` at the top
               level of their .gd/.g files): the names an unbound-global
               check must know.

The GAP source tarball is nixpkgs' gap.src (the version mep's flake ships).
"""

import re
import subprocess
import sys
import tarfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / 'src' / 'gap_lsp_vocab.cpp'

HEAD = re.compile(rb'\x1b\[29X\x1b\[2X(.+?)\x1b\[102X(.*?)\x1b\[32X ?([A-Za-z][A-Za-z ]*?)\x1b\[133X')
ESC = re.compile(rb'\x1b\[[0-9;]*[A-Za-z]')
KINDS = {
    'function': 'Func', 'operation': 'Oper', 'attribute': 'Attr', 'property': 'Prop', 'filter': 'Filt',
    'category': 'Filt', 'representation': 'Filt', 'global variable': 'Var', 'method': 'Meth',
    'info class': 'InfoClass', 'constructor': 'Constr', 'family': 'Fam', 'variable': 'Var',
}
DECL = re.compile(r'\b(?:Declare\w*|BindGlobal|BIND_GLOBAL|InstallValue|InstallGlobalFunction)\s*\(\s*"([A-Za-z_@][\w@]*)"')
ASSIGN = re.compile(r'^([A-Za-z_@][\w@]*)\s*:=', re.M)


def nix_src():
    return subprocess.run(['nix', 'build', '--no-link', '--print-out-paths', 'nixpkgs#gap.src'],
                          check=True, capture_output=True, text=True).stdout.strip()


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('??', '?\\?') + '"'


def main():
    tarball = sys.argv[1] if len(sys.argv) > 1 else nix_src()
    vocab = {}  # (name, kind, args) -> book
    declared = set()
    with tarfile.open(tarball) as tar:
        for m in tar:
            if not m.isfile():
                continue
            parts = m.name.split('/')
            if re.search(r'/doc/(ref/)?chap\d+\.txt$', m.name) and ('/doc/ref/' in m.name or parts[1] == 'pkg'):
                book = 'ref' if '/doc/ref/' in m.name else parts[2].lower()
                if parts[1] == 'pkg' and len(parts) > 5:
                    continue  # a package's sub-manual
                data = tar.extractfile(m).read()
                for h in HEAD.finditer(data):
                    name = ESC.sub(b'', h.group(1)).decode('utf-8', 'replace').strip()
                    args = ESC.sub(b'', h.group(2)).decode('utf-8', 'replace').strip()
                    kind = KINDS.get(h.group(3).decode().strip().lower())
                    if not kind or not re.fullmatch(r'[A-Za-z_@][\w@.]*', name):
                        continue
                    if args.startswith('(') and args.endswith(')'):
                        args = args[1:-1].strip()
                    elif args:
                        continue
                    args = re.sub(r'\s+', ' ', args)
                    vocab.setdefault((name, kind, args), book)
            elif parts[1] == 'pkg' and m.name.endswith(('.gd', '.g')) and '/tst/' not in m.name:
                text = tar.extractfile(m).read().decode('utf-8', 'replace')
                declared.update(DECL.findall(text))
                if m.name.endswith('.gd'):
                    declared.update(ASSIGN.findall(text))
    got = subprocess.run(['gap', '-q', '-b'], input='Print(JoinStringsWithSeparator(NamesGVars(), "\\n"), "\\n");\nQUIT;\n',
                         capture_output=True, text=True, check=True).stdout
    bound = {n for n in got.split() if re.fullmatch(r'[A-Za-z_@][\w@]*', n)}
    names = sorted(bound | declared | {n for n, _, _ in vocab if '.' not in n})

    rows = sorted(vocab.items(), key=lambda kv: (kv[0][0], kv[0][1], kv[0][2]))
    out = ['// Generated by tools/gen_gap_vocab.py from GAP 4.15.1 and its bundled packages -- do not edit.',
           '// Names, kinds and argument lists only (GAP is GPL; no manual prose is copied).',
           '#include "gap_lsp_vocab.h"', '', 'const GapVocabEntry kGapVocab[] = {']
    for (name, kind, args), book in rows:
        out.append(f'    {{{c_str(name)}, "{kind}", {c_str(args)}, {c_str(book)}}},')
    out += ['};', f'const size_t kGapVocabSize = {len(rows)};', '', 'const char *const kGapGlobals[] = {']
    line = '   '
    for n in names:
        piece = ' ' + c_str(n) + ','
        if len(line) + len(piece) > 118:
            out.append(line)
            line = '   '
        line += piece
    out += [line, '};', f'const size_t kGapGlobalsSize = {len(names)};', '']
    OUT.write_text('\n'.join(out))
    print(f'{OUT.relative_to(REPO)}: {len(rows)} documented forms, {len(names)} global names')


if __name__ == '__main__':
    main()
