// gen_go_unicode writes src/go_unicode.inc: the Unicode range tables of
// Go's own unicode package that mep's Go scanner, printer and doc-comment
// formatter consult, so identifiers and word breaks agree with the Go
// toolchain that generated them.
//
//	nix shell nixpkgs#go --command go run tools/gen_go_unicode.go > src/go_unicode.inc
package main

import (
	"fmt"
	"unicode"
)

func emit(name string, tabs ...*unicode.RangeTable) {
	var ranges [][2]rune
	var lo, hi rune = -1, -1
	for r := rune(0); r <= unicode.MaxRune; r++ {
		in := unicode.In(r, tabs...)
		if in {
			if lo < 0 {
				lo = r
			}
			hi = r
		} else if lo >= 0 {
			ranges = append(ranges, [2]rune{lo, hi})
			lo = -1
		}
	}
	if lo >= 0 {
		ranges = append(ranges, [2]rune{lo, hi})
	}
	fmt.Printf("static const uint32_t %s[][2] = {\n", name)
	for i, r := range ranges {
		if i%6 == 0 {
			fmt.Print("   ")
		}
		fmt.Printf(" {0x%X, 0x%X},", r[0], r[1])
		if i%6 == 5 || i == len(ranges)-1 {
			fmt.Println()
		}
	}
	fmt.Println("};")
}

func main() {
	fmt.Printf("// Generated by tools/gen_go_unicode.go from Go's unicode package (Unicode %s). Do not edit.\n", unicode.Version)
	fmt.Println("// Copyright 2009 The Go Authors. All rights reserved. BSD-style license (see go_parse.cpp).")
	emit("kGoLetter", unicode.Letter)
	emit("kGoDigit", unicode.Digit)
	emit("kGoSpace", unicode.White_Space)
	emit("kGoUpper", unicode.Upper)
	emit("kGoLower", unicode.Lower)
	emit("kGoPunct", unicode.Punct)
	emit("kGoPrint", unicode.L, unicode.M, unicode.N, unicode.P, unicode.S)
}
