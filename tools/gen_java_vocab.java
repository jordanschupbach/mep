// Generates src/java_lsp_vocab_data.cpp: the JDK's public API for
// mep-java-lsp (completion, hover, signature help, member typing).
//
//   just java-lsp-vocab
//   (= <jdk25>/bin/java tools/gen_java_vocab.java <jdk25>/lib/openjdk/lib/src.zip > out)
//
// Every public/protected type of the exported packages of the java.* modules
// and a set of commonly used jdk.* modules, read with javax.lang.model from
// the running JDK's own class files: module, package, kind, modifiers, type
// parameters, supertypes, deprecation, and the public/protected fields,
// enum constants, constructors and methods with full generic signatures.
// Parameter names are not in the class files; they come from the JDK's
// src.zip, parsed with javac's tree API and matched by name and parameter
// types. NAMES AND SIGNATURES ONLY: the javadoc prose is GPLv2+CPE, so it is
// never read; hover links to docs.oracle.com for it.
//
// Output encoding (one C string per type, see java_lsp_vocab.h):
//   header  module \t kind \t flags \t typeparams \t superclass \t interfaces
//   member  kind \t flags \t name \t typeparams \t type \t params \t throws \t value
// lines separated by '\n'. Type strings are qualified except java.lang's
// top-level types (`String`, `Thread.State`); type parameters are bare
// names; generic arguments are joined with ',' and no space. Lists
// (typeparams, interfaces, params, throws) are joined with ';'. A param is
// `type name`; a varargs method has flag 'v' and its last param type ends
// in "[]".

import com.sun.source.tree.*;
import com.sun.source.util.*;
import java.io.*;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.util.*;
import java.util.zip.*;
import javax.lang.model.element.*;
import javax.lang.model.type.*;
import javax.lang.model.util.*;
import javax.tools.*;

public class gen_java_vocab {
    static final String[] JDK_MODULES = {
        "jdk.accessibility", "jdk.attach", "jdk.compiler", "jdk.dynalink", "jdk.httpserver", "jdk.javadoc",
        "jdk.jdi", "jdk.jfr", "jdk.jshell", "jdk.jsobject", "jdk.management", "jdk.management.jfr", "jdk.net",
        "jdk.nio.mapmode", "jdk.sctp", "jdk.security.auth", "jdk.security.jgss", "jdk.unsupported", "jdk.xml.dom",
    };

    static Elements elements;
    static Types types;
    static final Map<String, String[]> paramNames = new HashMap<>();  // key -> names

    public static void main(String[] args) throws Exception {
        String srcZip = args.length > 0 ? args[0] : null;
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        List<String> modules = new ArrayList<>();
        for (java.lang.module.ModuleReference r : java.lang.module.ModuleFinder.ofSystem().findAll()) {
            String n = r.descriptor().name();
            if ((n.startsWith("java.") && !n.equals("java.se")) || Arrays.asList(JDK_MODULES).contains(n)) modules.add(n);
        }
        Collections.sort(modules);
        JavaFileObject dummy = new SimpleJavaFileObject(URI.create("string:///Dummy.java"), JavaFileObject.Kind.SOURCE) {
            @Override public CharSequence getCharContent(boolean b) { return "class Dummy {}"; }
        };
        JavacTask task = (JavacTask) javac.getTask(null, null, null,
            List.of("--add-modules", String.join(",", modules), "-proc:none"), null, List.of(dummy));
        task.analyze();
        elements = task.getElements();
        types = task.getTypes();

        // Pass 1: the types to emit, so the source pass knows which files to read.
        TreeMap<String, TypeElement> out = new TreeMap<>();
        Map<String, String> moduleOf = new HashMap<>();
        for (String mn : modules) {
            ModuleElement me = elements.getModuleElement(mn);
            if (me == null) continue;
            for (ModuleElement.Directive d : me.getDirectives()) {
                if (!(d instanceof ModuleElement.ExportsDirective ex) || ex.getTargetModules() != null) continue;
                for (Element e : ex.getPackage().getEnclosedElements()) collect((TypeElement) e, mn, out, moduleOf);
            }
        }
        if (srcZip != null) readParamNames(srcZip, out.keySet(), moduleOf);

        PrintStream o = new PrintStream(new FileOutputStream(FileDescriptor.out), false, StandardCharsets.UTF_8);
        o.println("// Generated by tools/gen_java_vocab.java (just java-lsp-vocab) -- do not edit.");
        o.println("// The public API of OpenJDK " + Runtime.version() + "'s exported packages (java.* and");
        o.println("// " + String.join(", ", JDK_MODULES) + "):");
        o.println("// names and signatures only, read with javax.lang.model from the JDK's class files,");
        o.println("// parameter names from its src.zip. No documentation text is included.");
        o.println();
        o.println("#include \"java_lsp_vocab.h\"");
        o.println();
        o.println("extern const JavaVocabRow kJavaVocab[];");
        o.println("extern const size_t kJavaVocabCount;");
        o.println();
        o.println("const JavaVocabRow kJavaVocab[] = {");
        int rows = 0, members = 0, named = 0, unnamed = 0;
        long bytes = 0;
        for (Map.Entry<String, TypeElement> en : out.entrySet()) {
            TypeElement te = en.getValue();
            StringBuilder head = new StringBuilder();
            head.append(moduleOf.get(en.getKey())).append('\t').append(kindOf(te)).append('\t').append(typeFlags(te))
                .append('\t').append(typeParams(te.getTypeParameters())).append('\t');
            TypeMirror sup = te.getSuperclass();
            if (sup.getKind() == TypeKind.DECLARED && te.getKind() == ElementKind.CLASS) head.append(type(sup));
            head.append('\t');
            StringJoiner ifs = new StringJoiner(";");
            for (TypeMirror t : te.getInterfaces()) ifs.add(type(t));
            head.append(ifs);
            List<String> lines = new ArrayList<>();
            lines.add(head.toString());
            // Declared members, plus the public members a non-exported superclass passes down.
            List<Element> mem = new ArrayList<>(te.getEnclosedElements());
            for (TypeMirror s = te.getSuperclass(); s.getKind() == TypeKind.DECLARED;) {
                TypeElement se = (TypeElement) types.asElement(s);
                if (out.containsKey(se.getQualifiedName().toString())) break;
                for (Element e : se.getEnclosedElements())
                    if (e.getKind() == ElementKind.METHOD || e.getKind() == ElementKind.FIELD) mem.add(e);
                s = se.getSuperclass();
            }
            Set<String> seen = new HashSet<>();
            Set<String> declared = new HashSet<>();
            for (Element e : te.getEnclosedElements())
                if (e instanceof ExecutableElement x) declared.add(key(te, x));
            for (Element e : mem) {
                if (e.getEnclosingElement() != te && e instanceof ExecutableElement x && declared.contains(key(te, x)))
                    continue;  // overridden here
                String line = member(te, e);
                if (line == null || !seen.add(line)) continue;
                lines.add(line);
                members++;
                if (e instanceof ExecutableElement ee && !ee.getParameters().isEmpty()) {
                    if (line.contains(" arg0")) unnamed++;
                    else named++;
                }
            }
            // Split a long type over rows of the same name (string literals stay under 60 KB).
            StringBuilder cur = new StringBuilder();
            List<String> chunks = new ArrayList<>();
            for (String l : lines) {
                if (cur.length() + l.length() > 50000) {
                    chunks.add(cur.toString());
                    cur.setLength(0);
                }
                cur.append(l).append('\n');
            }
            chunks.add(cur.toString());
            for (String c : chunks) {
                o.print("    {\"" + en.getKey() + "\",\n     ");
                o.print(lit(c));
                o.println("},");
                rows++;
                bytes += c.length();
            }
        }
        o.println("};");
        o.println();
        o.println("const size_t kJavaVocabCount = sizeof(kJavaVocab) / sizeof(kJavaVocab[0]);");
        o.flush();
        System.err.printf("%d types, %d rows, %d members, %d bytes; parameter names: %d named, %d unnamed%n",
            out.size(), rows, members, bytes, named, unnamed);
    }

    static void collect(TypeElement te, String mn, Map<String, TypeElement> out, Map<String, String> moduleOf) {
        Set<Modifier> m = te.getModifiers();
        if (!m.contains(Modifier.PUBLIC) && !m.contains(Modifier.PROTECTED)) return;
        String qn = te.getQualifiedName().toString();
        out.put(qn, te);
        moduleOf.put(qn, mn);
        for (Element e : te.getEnclosedElements())
            if (e instanceof TypeElement n) collect(n, mn, out, moduleOf);
    }

    static char kindOf(TypeElement te) {
        switch (te.getKind()) {
            case INTERFACE: return 'i';
            case ENUM: return 'e';
            case RECORD: return 'r';
            case ANNOTATION_TYPE: return 'a';
            default: return 'c';
        }
    }

    static String deprecation(Element e) {
        if (!elements.isDeprecated(e)) return "";
        Deprecated d = e.getAnnotation(Deprecated.class);
        return d != null && d.forRemoval() ? "DR" : "D";
    }

    static String typeFlags(TypeElement te) {
        StringBuilder f = new StringBuilder();
        Set<Modifier> m = te.getModifiers();
        if (m.contains(Modifier.ABSTRACT) && te.getKind() == ElementKind.CLASS) f.append('a');
        if (m.contains(Modifier.FINAL) && te.getKind() == ElementKind.CLASS) f.append('f');
        if (m.contains(Modifier.STATIC)) f.append('s');
        if (m.contains(Modifier.SEALED)) f.append('S');
        if (m.contains(Modifier.PROTECTED)) f.append('p');
        if (te.getAnnotation(FunctionalInterface.class) != null) f.append('F');
        f.append(deprecation(te));
        return f.toString();
    }

    static String member(TypeElement owner, Element e) {
        Set<Modifier> m = e.getModifiers();
        if (!m.contains(Modifier.PUBLIC) && !m.contains(Modifier.PROTECTED)) {
            // interface members are implicitly public
            if (!(owner.getKind().isInterface() && e.getKind() != ElementKind.CONSTRUCTOR
                  && !m.contains(Modifier.PRIVATE))) return null;
        }
        StringBuilder f = new StringBuilder();
        if (m.contains(Modifier.STATIC)) f.append('s');
        if (m.contains(Modifier.ABSTRACT)) f.append('a');
        if (m.contains(Modifier.FINAL)) f.append('f');
        if (m.contains(Modifier.DEFAULT)) f.append('d');
        if (m.contains(Modifier.PROTECTED)) f.append('p');
        f.append(deprecation(e));
        switch (e.getKind()) {
            case FIELD:
            case ENUM_CONSTANT: {
                VariableElement v = (VariableElement) e;
                String value = "";
                Object c = v.getConstantValue();
                if (c != null) value = constant(c);
                return (e.getKind() == ElementKind.FIELD ? "f" : "k") + "\t" + f + "\t" + v.getSimpleName() + "\t\t"
                    + type(v.asType()) + "\t\t\t" + value;
            }
            case METHOD:
            case CONSTRUCTOR: {
                ExecutableElement x = (ExecutableElement) e;
                if (x.isVarArgs()) f.append('v');
                boolean ctor = e.getKind() == ElementKind.CONSTRUCTOR;
                if (ctor && owner.getKind() == ElementKind.ENUM) return null;
                String[] names = paramNames.get(key((TypeElement) x.getEnclosingElement(), x));
                if (names == null && owner.getKind() == ElementKind.ENUM && x.getSimpleName().contentEquals("valueOf"))
                    names = new String[] {"name"};  // the implicit Enum.valueOf(String name)
                StringJoiner ps = new StringJoiner(";");
                int i = 0;
                for (VariableElement p : x.getParameters()) {
                    String n = names != null && i < names.length ? names[i] : p.getSimpleName().toString();
                    ps.add(type(p.asType()) + " " + n);
                    i++;
                }
                StringJoiner th = new StringJoiner(";");
                for (TypeMirror t : x.getThrownTypes()) th.add(type(t));
                String def = "";
                AnnotationValue dv = x.getDefaultValue();
                if (dv != null) {
                    def = dv.toString();
                    if (def.length() > 60 || def.indexOf('\n') >= 0) def = "...";
                }
                return (ctor ? "c" : "m") + "\t" + f + "\t" + (ctor ? owner.getSimpleName() : x.getSimpleName()) + "\t"
                    + typeParams(x.getTypeParameters()) + "\t" + (ctor ? "" : type(x.getReturnType())) + "\t" + ps
                    + "\t" + th + "\t" + def;
            }
            default:
                return null;
        }
    }

    static String constant(Object c) {
        String s;
        if (c instanceof String str) {
            if (str.length() > 60) return "";
            StringBuilder b = new StringBuilder("\"");
            for (char ch : str.toCharArray()) {
                if (ch == '"' || ch == '\\') b.append('\\').append(ch);
                else if (ch < 0x20 || ch > 0x7e) b.append(String.format("\\u%04x", (int) ch));
                else b.append(ch);
            }
            return b.append('"').toString();
        }
        if (c instanceof Character ch) {
            if (ch < 0x20 || ch > 0x7e || ch == '\'' || ch == '\\') return String.format("'\\u%04x'", (int) ch);
            return "'" + ch + "'";
        }
        s = elements.getConstantExpression(c);
        return s.length() > 40 ? "" : s;
    }

    static String typeParams(List<? extends TypeParameterElement> tps) {
        StringJoiner j = new StringJoiner(";");
        for (TypeParameterElement tp : tps) {
            StringBuilder b = new StringBuilder(tp.getSimpleName());
            List<String> bs = new ArrayList<>();
            for (TypeMirror bnd : tp.getBounds()) {
                String t = type(bnd);
                if (!t.equals("Object")) bs.add(t);
            }
            if (!bs.isEmpty()) b.append(" extends ").append(String.join(" & ", bs));
            j.add(b);
        }
        return j.toString();
    }

    static String typeName(TypeElement te) {
        String qn = te.getQualifiedName().toString();
        PackageElement p = elements.getPackageOf(te);
        if (p.getQualifiedName().contentEquals("java.lang")) return qn.substring("java.lang.".length());
        return qn;
    }

    static String type(TypeMirror t) {
        switch (t.getKind()) {
            case BOOLEAN: case BYTE: case SHORT: case INT: case LONG: case CHAR: case FLOAT: case DOUBLE: case VOID:
                return t.getKind().name().toLowerCase(Locale.ROOT);
            case ARRAY:
                return type(((ArrayType) t).getComponentType()) + "[]";
            case TYPEVAR:
                return ((TypeVariable) t).asElement().getSimpleName().toString();
            case WILDCARD: {
                WildcardType w = (WildcardType) t;
                if (w.getExtendsBound() != null) return "? extends " + type(w.getExtendsBound());
                if (w.getSuperBound() != null) return "? super " + type(w.getSuperBound());
                return "?";
            }
            case INTERSECTION: {
                StringJoiner j = new StringJoiner(" & ");
                for (TypeMirror b : ((IntersectionType) t).getBounds()) j.add(type(b));
                return j.toString();
            }
            case DECLARED: {
                DeclaredType d = (DeclaredType) t;
                StringBuilder b = new StringBuilder(typeName((TypeElement) d.asElement()));
                if (!d.getTypeArguments().isEmpty()) {
                    StringJoiner j = new StringJoiner(",", "<", ">");
                    for (TypeMirror a : d.getTypeArguments()) j.add(type(a));
                    b.append(j);
                }
                return b.toString();
            }
            default:
                return t.toString();
        }
    }

    // --- parameter names from src.zip -------------------------------------------------------

    // owner qualified name + '#' + method name + '(' + simple param type names ')'
    static String key(TypeElement owner, ExecutableElement x) {
        StringJoiner j = new StringJoiner(",");
        for (VariableElement p : x.getParameters()) j.add(simple(p.asType()));
        String n = x.getKind() == ElementKind.CONSTRUCTOR ? "<init>" : x.getSimpleName().toString();
        return owner.getQualifiedName() + "#" + n + "(" + j + ")";
    }

    static String simple(TypeMirror t) {
        switch (t.getKind()) {
            case ARRAY: return simple(((ArrayType) t).getComponentType()) + "[]";
            case TYPEVAR: return ((TypeVariable) t).asElement().getSimpleName().toString();
            case DECLARED: return ((DeclaredType) t).asElement().getSimpleName().toString();
            default: return t.toString();
        }
    }

    static String simpleTree(Tree t) {
        switch (t.getKind()) {
            case ARRAY_TYPE: return simpleTree(((ArrayTypeTree) t).getType()) + "[]";
            case PARAMETERIZED_TYPE: return simpleTree(((ParameterizedTypeTree) t).getType());
            case MEMBER_SELECT: return ((MemberSelectTree) t).getIdentifier().toString();
            case IDENTIFIER: return ((IdentifierTree) t).getName().toString();
            case ANNOTATED_TYPE: return simpleTree(((AnnotatedTypeTree) t).getUnderlyingType());
            case PRIMITIVE_TYPE: return t.toString();
            default: return t.toString();
        }
    }

    static void readParamNames(String srcZip, Set<String> wanted, Map<String, String> moduleOf) throws Exception {
        // Which files: module/pkg/path/TopLevel.java for every wanted top-level type.
        Set<String> files = new HashSet<>();
        List<TypeElement> all = new ArrayList<>();
        for (String qn : wanted) {
            TypeElement te = elements.getTypeElement(qn);
            if (te == null) continue;
            all.add(te);
            for (TypeMirror s = te.getSuperclass(); s.getKind() == TypeKind.DECLARED;) {  // non-exported bases
                TypeElement se = (TypeElement) types.asElement(s);
                if (wanted.contains(se.getQualifiedName().toString())) break;
                all.add(se);
                s = se.getSuperclass();
            }
        }
        for (TypeElement te : all) {
            String mod = elements.getModuleOf(te).getQualifiedName().toString();
            while (te.getEnclosingElement() instanceof TypeElement o) te = o;
            files.add(mod + "/" + te.getQualifiedName().toString().replace('.', '/') + ".java");
        }
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        List<JavaFileObject> batch = new ArrayList<>();
        try (ZipFile z = new ZipFile(srcZip)) {
            for (Enumeration<? extends ZipEntry> en = z.entries(); en.hasMoreElements();) {
                ZipEntry ze = en.nextElement();
                if (!files.contains(ze.getName())) continue;
                String text = new String(z.getInputStream(ze).readAllBytes(), StandardCharsets.UTF_8);
                String name = ze.getName();
                batch.add(new SimpleJavaFileObject(URI.create("string:///" + name), JavaFileObject.Kind.SOURCE) {
                    @Override public CharSequence getCharContent(boolean b) { return text; }
                });
                if (batch.size() >= 500) {
                    parseBatch(javac, batch);
                    batch.clear();
                }
            }
        }
        if (!batch.isEmpty()) parseBatch(javac, batch);
    }

    static void parseBatch(JavaCompiler javac, List<JavaFileObject> batch) throws IOException {
        JavacTask t = (JavacTask) javac.getTask(null, null, d -> {}, List.of("-proc:none"), null, batch);
        for (CompilationUnitTree cu : t.parse()) {
            String pkg = cu.getPackageName() == null ? "" : cu.getPackageName().toString();
            for (Tree td : cu.getTypeDecls())
                if (td instanceof ClassTree ct) walk(ct, pkg.isEmpty() ? "" : pkg + ".");
        }
    }

    static void walk(ClassTree ct, String prefix) {
        String qn = prefix + ct.getSimpleName();
        for (Tree m : ct.getMembers()) {
            if (m instanceof ClassTree n) {
                walk(n, qn + ".");
            } else if (m instanceof MethodTree mt) {
                StringJoiner k = new StringJoiner(",");
                StringJoiner names = new StringJoiner(";");
                for (VariableTree p : mt.getParameters()) {
                    String s = simpleTree(p.getType());
                    k.add(s);
                    names.add(p.getName());
                }
                String n = mt.getName().contentEquals("<init>") ? "<init>" : mt.getName().toString();
                paramNames.put(qn + "#" + n + "(" + k + ")", names.toString().split(";"));
            }
        }
        // A record's canonical constructor is implicit: its components are its parameters.
        if (ct.getKind() == Tree.Kind.RECORD) {
            StringJoiner k = new StringJoiner(",");
            StringJoiner names = new StringJoiner(";");
            for (Tree m : ct.getMembers())
                if (m instanceof VariableTree v && !v.getModifiers().getFlags().contains(javax.lang.model.element.Modifier.STATIC)) {
                    k.add(simpleTree(v.getType()));
                    names.add(v.getName());
                }
            paramNames.putIfAbsent(qn + "#<init>(" + k + ")", names.toString().split(";"));
        }
    }

    // One quoted piece per line of the blob; `??` is split so it can never form a trigraph.
    static String lit(String s) {
        StringBuilder b = new StringBuilder();
        String[] ls = s.split("\n", -1);
        for (int k = 0; k < ls.length; k++) {
            String l = ls[k];
            boolean last = k == ls.length - 1;
            if (last && l.isEmpty()) break;
            if (b.length() > 0) b.append("\n     ");
            b.append('"');
            for (int i = 0; i < l.length(); i++) {
                char c = l.charAt(i);
                if (c == '"' || c == '\\') b.append('\\').append(c);
                else if (c == '\t') b.append("\\t");
                else if (c == '?' && i + 1 < l.length() && l.charAt(i + 1) == '?') b.append("?\" \"");
                else if (c < 0x20 || c > 0x7e) {
                    for (byte u : String.valueOf(c).getBytes(StandardCharsets.UTF_8)) b.append(String.format("\\%03o", u & 0xff));
                } else b.append(c);
            }
            if (!last) b.append("\\n");
            b.append('"');
        }
        if (b.length() == 0) b.append("\"\"");
        return b.toString();
    }
}
