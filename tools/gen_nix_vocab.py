#!/usr/bin/env python3
"""Generate src/nix_lsp_builtins.cpp: the Nix builtins mep-nix-lsp knows.

    just nix-lsp-vocab        (= python3 tools/gen_nix_vocab.py)

For each builtin: its argument names and kind from `nix __dump-language`,
and -- probed with `nix-instantiate --parse`, which reports an undefined
variable for anything outside the top-level scope -- whether it is in
scope at the top level bare (`map`), only as `__name` (`__attrNames`), or
only as `builtins.name`. That is exactly the scope Nix checks variables
against, so the server's "undefined variable" agrees with Nix's.

Only names and facts go in the table. The documentation text is Nix's own
(LGPL); the server asks the installed Nix for it at run time
(`nix __dump-language`) and shows nothing when there is no Nix.
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / 'src' / 'nix_lsp_builtins.cpp'

# Top-level names that are not attributes of `builtins` (or not in the dump).
EXTRA = ['derivation', 'derivationStrict', 'scopedImport', 'fetchMercurial', 'storePath', 'builtins',
         'true', 'false', 'null', 'import', 'abort', 'throw', 'baseNameOf', 'dirOf', 'isNull', 'map',
         'removeAttrs', 'toString', 'placeholder', 'fetchTarball', 'fetchGit', 'fetchTree', 'currentSystem',
         'currentTime', 'nixPath', 'nixVersion', 'langVersion', 'storeDir']


def defined(name):
    with tempfile.NamedTemporaryFile('w', suffix='.nix', delete=False) as f:
        f.write(name)
        path = f.name
    try:
        p = subprocess.run(['nix-instantiate', '--parse', path], capture_output=True, text=True)
        return p.returncode == 0
    finally:
        Path(path).unlink()


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    dump = json.loads(subprocess.run(['nix', '__dump-language'], check=True, capture_output=True, text=True).stdout)
    attrs = json.loads(subprocess.run(['nix-instantiate', '--eval', '--json', '-E', 'builtins.attrNames builtins'],
                                      check=True, capture_output=True, text=True).stdout)
    version = subprocess.run(['nix', '--version'], check=True, capture_output=True, text=True).stdout.strip()
    names = sorted(set(dump) | set(attrs) | set(EXTRA))
    rows = []
    for n in names:
        info = dump.get(n, {})
        bare = defined(n)
        dunder = defined('__' + n)
        in_builtins = n in attrs or n in dump
        kind = 'function' if 'args' in info else (info.get('type') or ('function' if in_builtins else 'value'))
        rows.append(dict(name=n, args=' '.join(info.get('args', [])), kind=kind, bare=bare, dunder=dunder,
                         member=in_builtins, experimental=info.get('experimental-feature', ''),
                         impure=bool(info.get('impure-only'))))
        print(f'{n:32} bare={bare!s:5} __={dunder!s:5} {kind}', file=sys.stderr)
    out = ['// Generated by tools/gen_nix_vocab.py from ' + version + ' -- do not edit.',
           '// Names and facts only; the documentation is read from the installed Nix at run time.',
           '#include "nix_lsp.h"', '', 'namespace {', '', 'const NixLspBuiltin kBuiltins[] = {']
    for r in rows:
        out.append(f'    {{{cstr(r["name"])}, {cstr(r["args"])}, {cstr(r["kind"])}, {str(r["bare"]).lower()}, '
                   f'{str(r["dunder"]).lower()}, {str(r["member"]).lower()}, {cstr(r["experimental"])}, '
                   f'{str(r["impure"]).lower()}}},')
    out += ['};', '', '}  // namespace', '',
            'const NixLspBuiltin *NixLspBuiltinTable(size_t *count) {',
            '    *count = sizeof(kBuiltins) / sizeof(*kBuiltins);',
            '    return kBuiltins;', '}', '']
    OUT.write_text('\n'.join(out))
    print(f'{len(rows)} names -> {OUT.relative_to(REPO)}', file=sys.stderr)


if __name__ == '__main__':
    main()
