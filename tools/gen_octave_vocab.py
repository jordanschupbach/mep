#!/usr/bin/env python3
"""Regenerate src/octave_lsp_vocab.cpp: what mep-octave-lsp knows about
Octave's own functions.

    python3 tools/gen_octave_vocab.py      # needs octave-cli (nix develop)

The names are Octave's own list -- `__builtins__ ()` (compiled functions)
and `__list_functions__ ()` (the .m files on the default path) -- and each
one's usage lines are the `@deftypefn` / `@deftypefnx` headers of its help
text with the Texinfo markup taken out ("Y = abs (X)"). Names and
signatures only: Octave is GPL, so none of the help prose is copied.
"""

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / 'src' / 'octave_lsp_vocab.cpp'

SCRIPT = r'''
b = __builtins__ ();
f = __list_functions__ ();
names = unique ([b(:); f(:)]);
isb = ismember (names, b);
for i = 1:numel (names)
  nm = names{i};
  try
    [t, fmt] = get_help_text (nm);
  catch
    t = ""; fmt = "";
  end_try_catch
  printf ("@@NAME %s %d\n", nm, isb(i));
  if (strcmp (fmt, "texinfo"))
    lines = strsplit (t, "\n");
    for j = 1:numel (lines)
      l = strtrim (lines{j});
      if (strncmp (l, "@deftypefn", 10))
        printf ("%s\n", l);
      endif
    endfor
  endif
endfor
'''


def untexi(s):
    s = re.sub(r'^@deftypefnx?\s*', '', s)
    s = re.sub(r'^\{[^{}]*\}\s*', '', s)  # the category: {} or {Function File}
    # The return part: {@var{y} =} or {} -- a braced group.
    ret = ''
    if s.startswith('{'):
        depth = 0
        for i, ch in enumerate(s):
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
                if depth == 0:
                    ret, s = s[1:i], s[i + 1:].lstrip()
                    break
    out = (ret + ' ' if ret.strip() else '') + s

    def strip(m):
        return m.group(2)
    for _ in range(4):
        out = re.sub(r'@(var|code|qcode|samp|asis|strong|emph|w|file|env|command|option|t)\{([^{}]*)\}', strip, out)
    out = out.replace('@dots{}', '...').replace('@{', '{').replace('@}', '}').replace('@@', '@')
    out = re.sub(r'@[a-zA-Z]+\{\}', '', out)
    out = re.sub(r'\s+', ' ', out).strip()
    return out


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('?', '\\?').replace('\n', '\\n') + '"'


def main():
    with tempfile.NamedTemporaryFile('w', suffix='.m', delete=False) as f:
        f.write(SCRIPT)
        script = f.name
    env = {k: v for k, v in os.environ.items() if k != 'LD_LIBRARY_PATH'}
    try:
        p = subprocess.run(['octave-cli', '--norc', '--quiet', '--no-gui', script], capture_output=True, env=env,
                           timeout=1800)
    finally:
        os.unlink(script)
    text = p.stdout.decode('utf-8', 'replace')
    entries = []
    cur = None
    for line in text.split('\n'):
        if line.startswith('@@NAME '):
            _, nm, b = line.split(' ')
            cur = [nm, b == '1', []]
            entries.append(cur)
        elif cur is not None and line.startswith('@deftypefn'):
            u = untexi(line)
            if u and u not in cur[2]:
                cur[2].append(u)
    # Internal helpers (__foo__) are left out of completion but kept for hover.
    entries = [e for e in entries if re.match(r'^[A-Za-z_][A-Za-z0-9_]*$', e[0])]
    entries.sort(key=lambda e: e[0])
    if len(entries) < 500:
        sys.exit(f'only {len(entries)} names from octave-cli: is it Octave 10+?\n' + p.stderr.decode()[:2000])
    out = ['// Generated by tools/gen_octave_vocab.py -- do not edit by hand. See octave_lsp_vocab.h.',
           '// Names and usage lines from Octave\'s __builtins__ / __list_functions__ and the',
           '// @deftypefn headers of their help texts (Octave is GPL-3) -- no prose.',
           '#include "octave_lsp_vocab.h"', '', '#include <cstring>', '', 'namespace {',
           'const OctaveVocabEntry kVocab[] = {']
    for nm, b, us in entries:
        out.append(f'    {{{cstr(nm)}, {cstr(chr(10).join(us)) if us else chr(34) * 2}, {"true" if b else "false"}}},')
    out += ['};', '}  // namespace', '',
            'const OctaveVocabEntry *OctaveVocab(size_t *count) {',
            '    *count = sizeof(kVocab) / sizeof(kVocab[0]);', '    return kVocab;', '}', '',
            'const OctaveVocabEntry *OctaveVocabFind(const char *name, size_t len) {',
            '    size_t lo = 0, hi = sizeof(kVocab) / sizeof(kVocab[0]);',
            '    while (lo < hi) {', '        const size_t mid = (lo + hi) / 2;',
            '        const char *n = kVocab[mid].name;', '        const int c = std::strncmp(n, name, len);',
            '        if (c == 0 && n[len] == 0) return &kVocab[mid];',
            '        if (c < 0) {', '            lo = mid + 1;', '        } else {',
            '            hi = mid;  // greater, or a longer name with this one as its prefix', '        }', '    }',
            '    return nullptr;', '}', '']
    OUT.write_text('\n'.join(out))
    print(f'{OUT}: {len(entries)} names, {sum(1 for e in entries if e[2])} with usage lines')


if __name__ == '__main__':
    main()
