#!/usr/bin/env python3
"""The editor half of the mepml benchmarks (plans/MEPML_PERFORMANCE_PLAN.md).

Starts a throwaway mep on a private Xvfb display (so it can never take
focus from, or be typed into by, a mep someone is using), feeds it
fixtures generated by `mep-mepml-bench --dump`, runs
tools/mepml_editor_bench.lua in it over the agent socket, and appends
the results to bench_results/history.jsonl as binary
"mepml_editor_bench" (n = lines, ms = median; frame scenarios also carry
p95/max).

Two phases, each in its own mep:
  1. cold maths: an empty LaTeX cache (a fresh $HOME -- tectonic's own
     bundle cache stays the real one via XDG_CACHE_HOME), test.mepml and
     synth_1000 (~50 fragments) opened, and the time until every fragment's PNG exists plus
     the most tectonic processes seen running at once;
  2. the Lua scenarios (hooks, idle/scroll/typing frames) on a warm cache:
     every fixture's maths rendered first (kept in
     ~/.cache/mep-mepml-bench/latex between runs), so no compile runs
     while frames are timed.

  tools/mepml_editor_bench.py [--no-record] [--build-dir build/native] [--display :91]
"""

import argparse
import datetime
import glob
import json
import os
import shutil
import socket
import subprocess
import sys
import tempfile
import time

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HISTORY = os.path.join(REPO, "bench_results", "history.jsonl")
FIXTURES = ["test_mepml", "synth_1000", "synth_4000", "synth_16000", "patho_unclosed_4000", "patho_math_1000",
            "patho_table_2000", "patho_longline_5k"]


def rpc(sock_path, method, params=None, timeout=10.0):
    s = socket.socket(socket.AF_UNIX)
    s.settimeout(timeout)
    s.connect(sock_path)
    body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": method, "params": params or {}}).encode()
    s.sendall(b"Content-Length: %d\r\n\r\n" % len(body) + body)
    data = b""
    try:
        while b'"id":1' not in data:
            chunk = s.recv(65536)
            if not chunk:
                break
            data += chunk
    except socket.timeout:
        pass
    s.close()
    return data.decode(errors="replace")


class Mep:
    """A mep process on `display`, with HOME=`home`, reachable over its agent socket."""

    def __init__(self, build_dir, display, home, first_file, log):
        env = dict(os.environ, DISPLAY=display, HOME=home, XDG_DATA_HOME=os.path.join(home, ".local/share"),
                   XDG_CONFIG_HOME=os.path.join(home, ".config"),
                   XDG_CACHE_HOME=os.environ.get("XDG_CACHE_HOME", os.path.expanduser("~/.cache")))
        self.sock_dir = os.path.join(home, ".local/share/mep/agent-sockets")
        self.proc = subprocess.Popen([os.path.join(build_dir, "mep"), "--no-session", first_file], env=env,
                                     stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, cwd=REPO)
        self.sock = os.path.join(self.sock_dir, "%d.sock" % self.proc.pid)
        for _ in range(100):
            if os.path.exists(self.sock):
                break
            time.sleep(0.1)
        else:
            self.close()
            raise RuntimeError("mep's agent socket never appeared (%s)" % self.sock)
        # The socket file exists a moment before mep answers on it.
        info = ""
        for _ in range(50):
            try:
                info = rpc(self.sock, "session.info", timeout=2.0)
            except OSError:
                info = ""
            if '"pid":%d' % self.proc.pid in info:
                break
            time.sleep(0.2)
        if '"pid":%d' % self.proc.pid not in info:
            self.close()
            raise RuntimeError("socket answered for another process: " + info[:200])

    def cmd(self, cmd):
        return rpc(self.sock, "command.run", {"cmd": cmd})

    def close(self):
        self.proc.terminate()
        try:
            self.proc.wait(5)
        except subprocess.TimeoutExpired:
            self.proc.kill()


def tectonic_count():
    out = subprocess.run(["pgrep", "-fc", "tectonic -X compile"], capture_output=True, text=True).stdout.strip()
    return int(out or 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-record", action="store_true")
    ap.add_argument("--build-dir", default=os.path.join(REPO, "build/native"))
    ap.add_argument("--display", default=":91")
    ap.add_argument("--only", default="", help="run only fixtures whose name contains this")
    args = ap.parse_args()

    bench = os.path.join(args.build_dir, "mep-mepml-bench")
    work = tempfile.mkdtemp(prefix="mep-mepml-editor-bench-")
    fixtures = []
    for name in FIXTURES:
        if args.only and args.only not in name:
            continue
        path = os.path.join(work, name + ".mepml")
        with open(path, "w") as f:
            subprocess.run([bench, "--dump", name], stdout=f, check=True)
        fixtures.append({"name": name, "path": path})
    # test.mepml imports its neighbours; give it them.
    for extra in ("refs.mepml", "opts.mepml"):
        shutil.copy(os.path.join(REPO, extra), work)

    xvfb = subprocess.Popen(["Xvfb", args.display, "-screen", "0", "1600x1000x24"], stdout=subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL)
    time.sleep(1.0)
    results = []
    log = open(os.path.join(work, "mep.log"), "w")
    try:
        # Phase 1: cold maths.
        # Not patho_math_1000: every fragment starts its own tectonic at
        # once (see the plan), and a thousand of them would take the machine
        # down rather than measure it.
        for name in ("test_mepml", "synth_1000"):
            fx = next((f for f in fixtures if f["name"] == name), None)
            if not fx:
                continue
            home = os.path.join(work, "home-cold-" + name)
            os.makedirs(home)
            cache = os.path.join(home, ".cache/mep/latex")
            t0 = time.time()
            mep = Mep(args.build_dir, args.display, home, fx["path"], log)
            peak, last_count, stable_since = 0, -1, time.time()
            while time.time() - t0 < 600:
                peak = max(peak, tectonic_count())
                count = len(glob.glob(os.path.join(cache, "*.png")))
                if count != last_count:
                    last_count, stable_since = count, time.time()
                # Done when nothing is compiling and the count has held still.
                if count > 0 and tectonic_count() == 0 and time.time() - stable_since > 3.0:
                    break
                time.sleep(0.1)
            elapsed = (stable_since - t0) * 1000
            mep.close()
            results.append({"fixture": name, "scenario": "math_cold_render_all", "n": last_count, "ms": elapsed,
                            "peak_tectonic": peak})
            print("%-22s math_cold_render_all      %4d fragments  %9.0f ms  peak %d tectonic at once"
                  % (name, last_count, elapsed, peak))

        # Phase 2: the Lua scenarios, on a warm cache. Every fixture's maths
        # is rendered *before* anything is timed -- otherwise the frames
        # measure tectonic running in the background as much as the editor.
        # The cache persists between runs (only the first one pays), and the
        # fixtures are generated identically each time.
        home = os.path.join(work, "home")
        os.makedirs(os.path.join(home, ".cache/mep"))
        persistent = os.path.expanduser("~/.cache/mep-mepml-bench/latex")
        os.makedirs(persistent, exist_ok=True)
        os.symlink(persistent, os.path.join(home, ".cache/mep/latex"))
        for png in glob.glob(os.path.join(work, "home-cold-*/.cache/mep/latex/*.png")):
            shutil.copy(png, persistent)
        mep = Mep(args.build_dir, args.display, home, fixtures[0]["path"], log)
        mep.cmd("set idlefps=0")  # never sleep between frames: a frame is its own work
        for fx in fixtures:
            mep.cmd("e " + fx["path"])
            t0, quiet_since = time.time(), None
            while time.time() - t0 < 900:
                time.sleep(0.25)
                if tectonic_count() > 0:
                    quiet_since = None
                elif quiet_since is None:
                    quiet_since = time.time()
                elif time.time() - quiet_since > 3.0:
                    break
            print("%-22s maths cache warm (%.0f s)" % (fx["name"], time.time() - t0))
        out, done = os.path.join(work, "results.jsonl"), os.path.join(work, "done")
        cfg = "MEPML_BENCH = {fixtures = {%s}, out = %s, done = %s}" % (
            ", ".join("{name = %s, path = %s}" % (json.dumps(f["name"]), json.dumps(f["path"])) for f in fixtures),
            json.dumps(out), json.dumps(done))
        mep.cmd("lua " + cfg)
        mep.cmd("source " + os.path.join(REPO, "tools/mepml_editor_bench.lua"))
        t0 = time.time()
        while not os.path.exists(done) and time.time() - t0 < 1800:
            if mep.proc.poll() is not None:
                raise RuntimeError("mep exited during the benchmark; see " + log.name)
            time.sleep(0.5)
        mep.close()
        with open(out) as f:
            for line in f:
                r = json.loads(line)
                results.append(r)
                extra = "  p95 %7.2f  max %7.2f" % (r["p95"], r["max"]) if "p95" in r else ""
                print("%-22s %-26s n=%-6d %9.3f ms%s" % (r["fixture"], r["scenario"], r["n"], r["ms"], extra))
    finally:
        log.close()
        xvfb.terminate()

    if not args.no_record:
        commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                                cwd=REPO).stdout.strip() or "unknown"
        stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        with open(HISTORY, "a") as f:
            for r in results:
                rec = {"timestamp": stamp, "commit": commit, "binary": "mepml_editor_bench",
                       "scenario": r["fixture"] + "/" + r["scenario"], "n": r["n"], "ms": r["ms"],
                       "ops_per_sec": (r["n"] / r["ms"] * 1000) if r["ms"] > 0 else 0}
                for k in ("p95", "max", "peak_tectonic"):
                    if k in r:
                        rec[k] = r[k]
                f.write(json.dumps(rec) + "\n")
    shutil.rmtree(work, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
