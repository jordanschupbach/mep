# --- the edits -----------------------------------------------------------------------------------

class Plan:
    def __init__(self, write):
        self.write = write
        self.files = {}     # path -> new text, for files edited in place
        self.report = []

    def text(self, rel):
        if rel not in self.files:
            self.files[rel] = (REPO / rel).read_text()
        return self.files[rel]

    def new_file(self, rel, content):
        path = REPO / rel
        if path.exists():
            self.report.append(f'  exists, left alone  {rel}')
            return
        self.report.append(f'  create              {rel}')
        if self.write:
            path.write_text(content)

    def insert(self, rel, anchor, addition, present, before=False, what=''):
        """Puts `addition` after (or before) the one occurrence of `anchor`, unless `present` is already there."""
        s = self.text(rel)
        if present in s:
            self.report.append(f'  present, left alone {rel}: {what}')
            return
        n = s.count(anchor)
        if n != 1:
            sys.exit(f'{rel}: expected the anchor once, found it {n} times -- has it moved?\n  {anchor[:100]!r}')
        self.files[rel] = s.replace(anchor, addition + anchor if before else anchor + addition)
        self.report.append(f'  edit                {rel}: {what}')

    def replace_in(self, rel, pattern, repl, present, what=''):
        s = self.text(rel)
        if present in s:
            self.report.append(f'  present, left alone {rel}: {what}')
            return
        new, n = re.subn(pattern, repl, s, count=1)
        if n != 1:
            sys.exit(f'{rel}: pattern not found for {what}: {pattern!r}')
        self.files[rel] = new
        self.report.append(f'  edit                {rel}: {what}')

    def commit(self):
        if not self.write:
            return
        for rel, s in self.files.items():
            if (REPO / rel).read_text() != s:
                (REPO / rel).write_text(s)


