#!/usr/bin/env python3
"""Stamp out the skeleton of a new in-house language server and formatter.

    python3 tools/new_language.py lua --ext lua --name Lua            # show what it would do
    python3 tools/new_language.py lua --ext lua --name Lua --write    # do it
    python3 tools/new_language.py lua --ext lua --no-format --write   # the server only

Every in-house language follows the same shape (plans/LANGUAGE_PARITY_PLAN.md,
section 2); this writes the shape so a new language starts from something
that builds, runs and is wired in, and the work is the language itself:

  src/<lang>_lsp.h, <lang>_lsp.cpp    the analysis half: pure functions of the
                                      text (stubs: word completion, nothing else)
  src/<lang>_lsp_server.cpp           the LSP wire half + `--lint FILE...`
  src/<lang>_lsp_test.cpp             CHECK()-style test of the analysis
  src/<lang>_format.h, .cpp           the formatter (a stub returning its input)
  src/<lang>_format_test.cpp          `--format FILE...`, for tools/format_compare.py
  help/<lang>-lsp.org                 the help page, to fill in

and splices the registrations in beside Nix's (the reference language: it has
every piece): CMake targets and source lists, MEP_CTEST_TARGETS, the
`mep.lsp_servers` entry in src/main.cpp, the `mep.format_<lang>` Lua binding in
src/lua_env.cpp and its `mep.format_languages` entries, flake.nix's installed
tools, `just test`'s target list and help/lsp.org's table.

Nothing is overwritten: an existing file or registration is left alone and
reported. After --write: build (`cmake --build build/native --target
mep-<lang>-lsp mep-<lang>-lsp-test mep-<lang>-format-test mep`), run the test,
export the help page (`mep --export-org`), and add a PRESETS entry to
tools/format_compare.py and, if needed, a BINARIES entry to
tools/lsp_lint_corpus.py.
"""

