#!/usr/bin/env python3
"""Writes unicode_tables.h from regex-syntax's Unicode tables.

tree-sitter's generator expands a pattern's `\\p{...}` classes (and `.`,
negated classes, case folding) with the Rust regex-syntax crate's tables;
mep's generator must use exactly the same ones for its lexer tables to come
out byte-identical. So rather than derive them from the Unicode data again,
this converts the crate's own: regex-syntax 0.8.5 (the version tree-sitter
0.25.10's Cargo.lock pins), Unicode 16.0.

    python3 tools/ts_generate/gen_unicode_tables.py <regex-syntax-0.8.5 dir> \\
        > tools/ts_generate/unicode_tables.h

The crate's tarball is in the Nix store as the dependency of
nixpkgs#tree-sitter (`crate-regex-syntax-0.8.5.tar.gz`).
"""

import re
import sys
from pathlib import Path

ESC = {'t': 0x09, 'n': 0x0A, 'r': 0x0D, '0': 0, "'": 0x27, '"': 0x22, '\\': 0x5C}


def char_value(lit):
    """The code point of a Rust char literal's body (between the quotes)."""
    if lit.startswith('\\u{'):
        return int(lit[3:-1], 16)
    if lit.startswith('\\'):
        return ESC[lit[1]]
    assert len(lit) == 1, lit
    return ord(lit)


CHAR = r"'((?:\\u\{[0-9a-fA-F]+\}|\\.|[^'\\]))'"
PAIR = re.compile(r'\(\s*' + CHAR + r'\s*,\s*' + CHAR + r'\s*\)')
CONST = re.compile(r"pub const (\w+): &'static \[\(char, char\)\] =\s*&\[(.*?)\];", re.S)
BY_NAME = re.compile(r'pub const BY_NAME:[^=]*=\s*&\[(.*?)\];', re.S)
NAME_ENTRY = re.compile(r'\("([^"]+)",\s*(\w+)\)')


def range_tables(path):
    text = path.read_text()
    consts = {}
    for m in CONST.finditer(text):
        consts[m.group(1)] = [(char_value(a), char_value(b)) for a, b in PAIR.findall(m.group(2))]
    by_name = []
    m = BY_NAME.search(text)
    if m:
        by_name = [(n, consts[c]) for n, c in NAME_ENTRY.findall(m.group(1))]
    return consts, by_name


def main():
    src = Path(sys.argv[1]) / 'src' / 'unicode_tables'
    ranges = []  # flat (lo, hi) list
    tables = []  # (c array name, [(name, offset, count)])

    def add(entries):
        out = []
        for name, rs in entries:
            out.append((name, len(ranges), len(rs)))
            ranges.extend(rs)
        return out

    for fname, cname in [('general_category.rs', 'kGeneralCategory'), ('script.rs', 'kScript'),
                         ('script_extension.rs', 'kScriptExtension'), ('property_bool.rs', 'kPropertyBool'),
                         ('age.rs', 'kAge'), ('grapheme_cluster_break.rs', 'kGraphemeClusterBreak'),
                         ('word_break.rs', 'kWordBreak'), ('sentence_break.rs', 'kSentenceBreak')]:
        _, by_name = range_tables(src / fname)
        tables.append((cname, add(by_name)))
    singles = []
    for fname, const, cname in [('perl_word.rs', 'PERL_WORD', 'kPerlWord'),
                                ('perl_space.rs', 'WHITE_SPACE', 'kPerlSpace'),
                                ('perl_decimal.rs', 'DECIMAL_NUMBER', 'kPerlDecimal')]:
        consts, _ = range_tables(src / fname)
        singles.append((cname, add([(const, consts[const])])[0]))

    names = re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', (src / 'property_names.rs').read_text())
    values_text = (src / 'property_values.rs').read_text()
    values = []
    for m in re.finditer(r'\(\s*"(\w+)",\s*&\[(.*?)\],\s*\)', values_text, re.S):
        values.append((m.group(1), re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', m.group(2))))

    folds_text = (src / 'case_folding_simple.rs').read_text()
    folds = []
    for m in re.finditer(r'\(\s*' + CHAR + r'\s*,\s*&\[([^\]]*)\]\s*\)', folds_text):
        targets = [char_value(t) for t in re.findall(CHAR, m.group(2))]
        folds.append((char_value(m.group(1)), targets))

    w = sys.stdout.write
    w('// Generated by tools/ts_generate/gen_unicode_tables.py from regex-syntax 0.8.5\n'
      '// (Unicode 16.0) -- do not edit. The tables tree-sitter 0.25.10 expands a\n'
      "// pattern's Unicode classes with; Unicode data under the Unicode license\n"
      '// (https://www.unicode.org/license.txt).\n'
      '#pragma once\n#include <cstdint>\n\nnamespace tsgen::unicode {\n\n'
      'struct Range { uint32_t lo, hi; };\n'
      'struct Table { const char *name; uint32_t offset, count; };\n'
      'struct Name { const char *normalized, *canonical; };\n'
      'struct Values { const char *property; const Name *names; uint32_t count; };\n'
      'struct Fold { uint32_t c; uint32_t offset, count; };\n\n')
    w('inline constexpr Range kRanges[] = {\n')
    for i in range(0, len(ranges), 6):
        w('    ' + ' '.join('{0x%X, 0x%X},' % r for r in ranges[i:i + 6]) + '\n')
    w('};\n\n')
    for cname, entries in tables:
        w('inline constexpr Table %s[] = {\n' % cname)
        for name, off, cnt in entries:
            w('    {"%s", %d, %d},\n' % (name, off, cnt))
        w('};\n')
    w('\n')
    for cname, (name, off, cnt) in singles:
        w('inline constexpr Table %s = {"%s", %d, %d};\n' % (cname, name, off, cnt))
    w('\ninline constexpr Name kPropertyNames[] = {\n')
    for n, c in names:
        w('    {"%s", "%s"},\n' % (n, c))
    w('};\n\n')
    for prop, vals in values:
        w('inline constexpr Name kValues%s[] = {\n' % prop.replace('_', ''))
        for n, c in vals:
            w('    {"%s", "%s"},\n' % (n, c))
        w('};\n')
    w('inline constexpr Values kPropertyValues[] = {\n')
    for prop, vals in values:
        w('    {"%s", kValues%s, %d},\n' % (prop, prop.replace('_', ''), len(vals)))
    w('};\n\n')
    targets = []
    w('inline constexpr Fold kFolds[] = {\n')
    for c, ts in folds:
        w('    {0x%X, %d, %d},\n' % (c, len(targets), len(ts)))
        targets.extend(ts)
    w('};\n')
    w('inline constexpr uint32_t kFoldTargets[] = {\n')
    for i in range(0, len(targets), 12):
        w('    ' + ' '.join('0x%X,' % t for t in targets[i:i + 12]) + '\n')
    w('};\n\n}  // namespace tsgen::unicode\n')


if __name__ == '__main__':
    main()
