#!/usr/bin/env python3
"""web2cpp: a WEB program and its change files, as one C++ class.

  tools/web2cpp/web2cpp.py WEB [CHANGE...] --out DIR [--ns NAMESPACE]

This is how mep's TeX engine (plans/TEX_ENGINE_PLAN.md) is built from
Knuth's tex.web: the change files (src/tex/web/*.ch, applied in order)
replace the system-dependent parts and add mep's extensions, and the
result is translated mechanically -- TANGLE's macro and module expansion,
then Pascal to C++ -- so the engine is TeX's own algorithms, not a
re-typing of them. The output is committed (src/tex/gen/) and regenerated
with `just tex-gen` whenever tex.web or a change file changes.

What it writes into DIR:
  tex_gen.h        the Engine class: constants, globals, method declarations
  tex_gen_N.cpp    the methods, a few hundred lines of TeX at a time
  tex_pool.cpp     the pool strings (what TANGLE would have written to TEX.POOL)
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import emit  # noqa: E402
import pascal  # noqa: E402
import web  # noqa: E402

PRAGMAS = '''#if defined(__clang__) || defined(__GNUC__)
#pragma GCC diagnostic ignored "-Wunused-label"
#pragma GCC diagnostic ignored "-Wunused-variable"
#pragma GCC diagnostic ignored "-Wunused-but-set-variable"
#pragma GCC diagnostic ignored "-Wparentheses"
#pragma GCC diagnostic ignored "-Wsign-compare"
#pragma GCC diagnostic ignored "-Wunused-parameter"
#pragma GCC diagnostic ignored "-Wmaybe-uninitialized"
#pragma GCC diagnostic ignored "-Wimplicit-fallthrough"
#endif
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('web')
    ap.add_argument('changes', nargs='*')
    ap.add_argument('--out', required=True)
    ap.add_argument('--ns', default='meptex')
    ap.add_argument('--base', default='EngineBase')
    ap.add_argument('--extra', default='tex/tex_engine_members.h',
                    help='header #included inside the class body (hand-written members)')
    ap.add_argument('--externals', default='',
                    help='comma-separated hand-written members called like Pascal routines')
    ap.add_argument('--members', default='',
                    help='hand-written members header: every routine it declares may be called '
                         'from the change files like a Pascal routine')
    ap.add_argument('--split', type=int, default=8, help='number of .cpp files')
    ap.add_argument('--dump-pascal', help='also write the tangled token stream here')
    args = ap.parse_args()

    lines = open(args.web, encoding='latin-1').read().split('\n')
    for ch in args.changes:
        lines = web.apply_changes(lines, open(ch, encoding='latin-1').read(), ch)
    w = web.Web('\n'.join(lines))
    toks = w.tangle()
    if args.dump_pascal:
        with open(args.dump_pascal, 'w') as f:
            f.write(' '.join(str(t.val) if t.kind != 'pool' else repr(t.val[1]) for t in toks))
    prog = pascal.Parser(toks).program()
    ext = [x for x in args.externals.split(',') if x]
    if args.members:
        import re
        text = open(args.members).read()
        text = re.sub(r'//[^\n]*|/\*.*?\*/', '', text, flags=re.S)
        ext += re.findall(r'\b([A-Za-z_]\w*)\s*\([^;{]*\)\s*(?:const\s*)?[;{]', text)
    e = emit.Emitter(prog, externals=ext)

    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, 'tex_gen.h'), 'w') as f:
        f.write(e.header(args.ns, args.base, args.extra))

    # Methods, split into roughly equal files in program order.
    bodies = [e.alloc()]
    for r in prog.routines:
        if r.forward:
            continue
        bodies.append(e.routine(r))
    bodies.append(e.main())
    total = sum(len(b) for b in bodies)
    per = total // args.split + 1
    files = [[]]
    size = 0
    for b in bodies:
        if size > per and len(files) < args.split:
            files.append([])
            size = 0
        files[-1].append(b)
        size += len(b)
    for i, chunk in enumerate(files):
        with open(os.path.join(args.out, f'tex_gen_{i}.cpp'), 'w') as f:
            f.write('// Generated by tools/web2cpp; see tex_gen.h.\n')
            f.write(PRAGMAS)
            f.write('#include "tex_gen.h"\n\n')
            f.write(f'namespace {args.ns} {{\n\n')
            f.write('\n'.join(chunk))
            f.write(f'\n}}  // namespace {args.ns}\n')
    # Any stale numbered files from a previous, larger split.
    k = len(files)
    while os.path.exists(os.path.join(args.out, f'tex_gen_{k}.cpp')):
        os.remove(os.path.join(args.out, f'tex_gen_{k}.cpp'))
        k += 1

    # Every macro that stands for a constant (command codes, eqtb locations,
    # node types and sizes ...), for the hand-written C++ beside the
    # generated code, which has no WEB macros of its own.
    consts = []
    for name, (params, kind, body) in sorted(w.macros.items()):
        if params:
            continue
        try:
            toks = w._expand_macros([web.Tok(web.ID, name, 0)], 0)
            toks = web._join_reals(w._drop_meta(toks))
            toks = [web.Tok(web.NUM, e.consts[t.val.lower()], t.mod)
                    if t.kind == web.ID and isinstance(e.consts.get(t.val.lower()), int) else t for t in toks]
            if not toks or any(t.kind not in (web.NUM, web.SYM, web.CHAR) for t in toks):
                continue
            p = pascal.Parser(toks)
            ast = p.expr()
            if p.i != len(toks):
                continue
            v = pascal.const_value(ast)
        except (web.WebError, pascal.PascalError, IndexError, AttributeError):
            continue
        if v is not None and -2**31 <= v < 2**31:
            consts.append((name, v))
    with open(os.path.join(args.out, 'tex_consts.h'), 'w') as f:
        f.write('// Generated by tools/web2cpp: the WEB macros that are constants, for the\n')
        f.write('// hand-written parts of the engine (tex.web\'s own names, in namespace tc).\n')
        f.write('#pragma once\n#include <cstdint>\n\n')
        f.write(f'namespace {args.ns}::tc {{\n\n')
        for name, v in consts:
            f.write(f'constexpr int32_t {emit.cname(name)} = {v};\n')
        f.write(f'\n}}  // namespace {args.ns}::tc\n')

    with open(os.path.join(args.out, 'tex_pool.cpp'), 'w') as f:
        f.write('// Generated by tools/web2cpp: the program\'s string pool (TANGLE\'s TEX.POOL).\n')
        f.write('#include "tex/tex_runtime.h"\n\n')
        f.write(f'namespace {args.ns} {{\n\n')
        f.write(f'const int kPoolStringCount = {len(w.pool_list)};\n')
        f.write('const char *const kPoolStrings[] = {\n')
        for s in w.pool_list:
            f.write(f'    {emit.cstr(s)},\n')
        f.write('};\n\n')
        f.write(f'}}  // namespace {args.ns}\n')
    print(f'web2cpp: {len(prog.routines)} routines, {len(w.pool_list)} pool strings, {len(files)} files')


if __name__ == '__main__':
    try:
        main()
    except (web.WebError, pascal.PascalError, emit.EmitError) as ex:
        print(f'web2cpp: {ex}', file=sys.stderr)
        sys.exit(1)
